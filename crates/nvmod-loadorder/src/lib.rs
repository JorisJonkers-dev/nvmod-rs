//! The Load order of a Profile. loot-rs proposes it from the plugins of the Staging tree; applying it writes
//! `plugins.txt` and `loadorder.txt` together and encodes the order in the modification times of the plugin files
//! of the Staging tree, because nv-rs orders plugins by file time until the fork has a `plugins.txt` switch
//! (docs/DECISIONS.md). The authoritative order is the one in the Profile; the times are a cache that is rewritten.
//!
//! The Staging tree hard-links plugin files to the Mod folders (which, for an imported Instance, share inodes with
//! the MO2 instance). Setting a time on a hard link would set it on the Mod's file too, so a plugin file's link
//! is first replaced by a copy.

mod stamp;

use loot_rs::api::{Masterlist, PluginSlot, SortError, SortOptions, SortOutput, sort};
use nvmod_formats::plugins::parse_plugin_list;
use nvmod_formats::text::{encode_windows_1252, read_limited};
use nvmod_instance::{NvmodInstance, find_ci};
use nvmod_modinstall::journal;
use std::fs;
use std::path::{Path, PathBuf};

pub use stamp::{BASE_TIME_SECS, STEP_SECS, target_time};

const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// One plugin of a Load order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Slot {
    /// The file name as the lists spell it.
    pub name: String,
    /// Listed in `plugins.txt`.
    pub active: bool,
}

/// Why a Load order could not be computed or applied.
#[derive(Debug, PartialEq, Eq)]
pub enum Error {
    /// Refused before anything was written (exit code 2).
    Refused(String),
    /// A step failed; the profile files and the Staging tree were put back (exit code 4).
    Failed(String),
}

/// What loot-rs proposes for a Profile.
#[derive(Debug)]
pub struct Proposal {
    /// The profile.
    pub profile: String,
    /// The Staging tree's `Data` folder loot-rs read.
    pub data: PathBuf,
    /// The order in the profile now.
    pub current: Vec<Slot>,
    /// The proposed order, with the plugins that are not installed placed after the plugin that preceded them.
    pub proposed: Vec<Slot>,
    /// Everything loot-rs reported.
    pub output: SortOutput,
}

impl Proposal {
    /// Whether the proposed order differs from the current one (names, ignoring case, in order).
    #[must_use]
    pub fn reordered(&self) -> bool {
        self.current.len() != self.proposed.len()
            || self
                .current
                .iter()
                .zip(&self.proposed)
                .any(|(a, b)| !a.name.eq_ignore_ascii_case(&b.name))
    }
}

/// What applying a proposal changed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Applied {
    /// `plugins.txt` or `loadorder.txt` was rewritten.
    pub lists_written: bool,
    /// Plugin files that got a new modification time.
    pub stamped: usize,
    /// Of those, files whose hard link was replaced by a copy first.
    pub detached: usize,
    /// The journal `nvmod rollback` uses; `None` when nothing needed to change.
    pub journal: Option<String>,
}

fn refuse<T>(text: impl Into<String>) -> Result<T, Error> {
    Err(Error::Refused(text.into()))
}

/// The plugins of `profile_dir` in `loadorder.txt` order (or `plugins.txt` order when there is no
/// `loadorder.txt`), each marked active when `plugins.txt` lists it. Plugins only in `plugins.txt` follow at the end.
///
/// # Errors
/// `Refused` when the profile has neither list, or a list cannot be read.
pub fn read_slots(profile_dir: &Path) -> Result<Vec<Slot>, Error> {
    let read = |file: &str| -> Result<Option<Vec<String>>, Error> {
        let path = profile_dir.join(file);
        if !path.is_file() {
            return Ok(None);
        }
        read_limited(&path)
            .map(|bytes| Some(parse_plugin_list(&bytes)))
            .map_err(|e| Error::Refused(format!("{}: {e}", path.display())))
    };
    let active = read("plugins.txt")?;
    let order = read("loadorder.txt")?;
    if active.is_none() && order.is_none() {
        return refuse(format!(
            "{} has neither plugins.txt nor loadorder.txt",
            profile_dir.display()
        ));
    }
    let active = active.unwrap_or_default();
    let is_active = |name: &str| active.iter().any(|a| a.eq_ignore_ascii_case(name));
    let mut slots: Vec<Slot> = Vec::new();
    for name in order.unwrap_or_default().into_iter().chain(active.clone()) {
        if !slots.iter().any(|s| s.name.eq_ignore_ascii_case(&name)) {
            let active = is_active(&name);
            slots.push(Slot { name, active });
        }
    }
    Ok(slots)
}

/// The `Data` folder of the Staging tree of `profile`.
///
/// # Errors
/// `Refused`, telling the user to run `nvmod stage`, when the tree does not exist.
pub fn staging_data(instance: &NvmodInstance, profile: &str) -> Result<PathBuf, Error> {
    let data = instance.staging_dir(profile).join("data");
    if data.is_dir() {
        Ok(data)
    } else {
        refuse(format!(
            "profile `{profile}` has no Staging tree; run `nvmod stage --instance {} --profile {profile}` first",
            instance.root.display()
        ))
    }
}

/// Read a masterlist.
///
/// # Errors
/// `Refused` with loot-rs's reason.
pub fn load_masterlist(path: &Path) -> Result<Masterlist, Error> {
    Masterlist::from_file(path).map_err(|e| Error::Refused(e.to_string()))
}

/// A masterlist without entries: only the header masters and the current order decide.
///
/// # Panics
/// Never: an empty text is a valid masterlist (tested).
#[must_use]
pub fn empty_masterlist() -> Masterlist {
    Masterlist::parse("").expect("an empty masterlist is valid")
}

fn describe(error: &SortError) -> String {
    format!("loot-rs cannot sort this Load order: {error}")
}

/// Place the plugins that are not installed: each goes right after the plugin that preceded it in `current`.
fn place_not_installed(current: &[Slot], sorted: &[String]) -> Vec<Slot> {
    let active = |name: &str| {
        current
            .iter()
            .find(|s| s.name.eq_ignore_ascii_case(name))
            .is_some_and(|s| s.active)
    };
    let mut names: Vec<String> = sorted.to_vec();
    for (index, slot) in current.iter().enumerate() {
        if names.iter().any(|n| n.eq_ignore_ascii_case(&slot.name)) {
            continue;
        }
        let at = current[..index]
            .iter()
            .rev()
            .find_map(|before| {
                names
                    .iter()
                    .position(|n| n.eq_ignore_ascii_case(&before.name))
            })
            .map_or(0, |i| i + 1);
        names.insert(at, slot.name.clone());
    }
    names
        .into_iter()
        .map(|name| Slot {
            active: active(&name),
            name,
        })
        .collect()
}

/// Sort the Load order of `profile` with loot-rs, reading the plugins of its Staging tree.
///
/// # Errors
/// `Refused` when the Staging tree or the lists are missing, or loot-rs refuses the input (rules that contradict
/// each other, too many plugins).
pub fn propose(
    instance: &NvmodInstance,
    profile: &str,
    masterlist: &Masterlist,
) -> Result<Proposal, Error> {
    let data = staging_data(instance, profile)?;
    let current = read_slots(&instance.profile_dir(profile))?;
    let slots: Vec<PluginSlot> = current
        .iter()
        .map(|s| PluginSlot::new(s.name.clone(), s.active))
        .collect();
    let output = sort(&slots, masterlist, &data, &SortOptions::default())
        .map_err(|e| Error::Refused(describe(&e)))?;
    let proposed = place_not_installed(&current, &output.order);
    Ok(Proposal {
        profile: profile.to_owned(),
        data,
        current,
        proposed,
        output,
    })
}

fn join(lines: impl IntoIterator<Item = String>) -> String {
    let mut out = format!("{HEADER}\r\n");
    for line in lines {
        out.push_str(&line);
        out.push_str("\r\n");
    }
    out
}

/// The bytes of `plugins.txt` (active plugins, Windows code page) and `loadorder.txt` (all plugins, UTF-8) for
/// `order`.
///
/// # Errors
/// `Refused` when an active plugin's name has no place in the Windows code page.
pub fn list_bytes(order: &[Slot]) -> Result<(Vec<u8>, Vec<u8>), Error> {
    let plugins = join(order.iter().filter(|s| s.active).map(|s| s.name.clone()));
    let load_order = join(order.iter().map(|s| s.name.clone()));
    let plugins = encode_windows_1252(&plugins).ok_or_else(|| {
        Error::Refused(
            "a plugin name cannot be written to plugins.txt in the Windows code page".to_owned(),
        )
    })?;
    Ok((plugins, load_order.into_bytes()))
}

fn differs(path: &Path, bytes: &[u8]) -> bool {
    fs::read(path).map_or(true, |old| old != bytes)
}

/// Where a step may fail: an injected failure (`NVMOD_FAIL_AT`) or a termination request.
fn fail_point(step: &str) -> Result<(), String> {
    nvmod_core::cancel::step_point(step)
}

/// Write the proposed order: `plugins.txt` and `loadorder.txt` together, then the modification times of the
/// plugin files of the Staging tree (strictly increasing in Load order). A journal and a backup are written
/// before the first change, so `nvmod rollback` undoes it; a step that fails puts everything back. Nothing is
/// written, and no journal made, when the files and times are already right.
///
/// # Errors
/// `Refused` before any change; `Failed` when a step failed and was rolled back.
pub fn apply(instance: &NvmodInstance, proposal: &Proposal) -> Result<Applied, Error> {
    let dir = instance.profile_dir(&proposal.profile);
    let (plugins, load_order) = list_bytes(&proposal.proposed)?;
    let write_plugins = differs(&dir.join("plugins.txt"), &plugins);
    let write_order = differs(&dir.join("loadorder.txt"), &load_order);
    let stamps = stamp::plan(&proposal.data, &proposal.proposed);
    if !write_plugins && !write_order && stamps.is_empty() {
        return Ok(Applied {
            lists_written: false,
            stamped: 0,
            detached: 0,
            journal: None,
        });
    }
    let entry = journal::begin_kind(instance, &proposal.profile, "", journal::KIND_SORT)
        .map_err(Error::Refused)?;
    let outcome = (|| -> Result<usize, String> {
        fail_point("sort-lists")?;
        // plugins.txt before loadorder.txt, so loadorder.txt stays the newest.
        if write_plugins {
            journal::write_atomic(&dir.join("plugins.txt"), &plugins)?;
        }
        if write_order {
            journal::write_atomic(&dir.join("loadorder.txt"), &load_order)?;
        }
        fail_point("sort-times")?;
        stamp::apply(&stamps)
    })();
    match outcome {
        Ok(detached) => {
            journal::complete(instance, &entry).map_err(Error::Failed)?;
            Ok(Applied {
                lists_written: write_plugins || write_order,
                stamped: stamps.len(),
                detached,
                journal: Some(entry.id),
            })
        }
        Err(why) => match journal::undo(instance, &entry) {
            Ok(()) => Err(Error::Failed(format!(
                "{why}; the Load order change was rolled back"
            ))),
            Err(undo) => Err(Error::Failed(format!(
                "{why}; the rollback failed too ({undo}); run `nvmod rollback`"
            ))),
        },
    }
}

/// The file of `name` in the `Data` folder of a Staging tree (paths are lowercase there), ignoring case.
#[must_use]
pub fn staged_file(data: &Path, name: &str) -> Option<PathBuf> {
    let direct = data.join(name.to_lowercase());
    if direct.is_file() {
        Some(direct)
    } else {
        find_ci(data, name).filter(|p| p.is_file())
    }
}

/// The masters a plugin file declares in its header.
///
/// # Errors
/// The reason, when the file cannot be read or its header is not a plugin header.
pub fn masters_of(path: &Path) -> Result<Vec<String>, String> {
    loot_rs::plugin::read_header(path)
        .map(|header| header.masters)
        .map_err(|e| format!("{}: {e}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use nvmod_testkit::{TempDir, write_file};

    fn slot(name: &str, active: bool) -> Slot {
        Slot {
            name: name.to_owned(),
            active,
        }
    }

    #[test]
    fn slots_follow_loadorder_txt_and_mark_the_active_ones_ignoring_case() {
        let dir = TempDir::new("lo-slots");
        write_file(
            dir.path(),
            "loadorder.txt",
            b"# header\r\nA.esm\r\nb.esp\r\nC.esp\r\n",
        );
        write_file(dir.path(), "plugins.txt", b"B.ESP\r\nA.esm\r\nD.esp\r\n");
        let slots = read_slots(dir.path()).unwrap();
        assert_eq!(
            slots,
            [
                slot("A.esm", true),
                slot("b.esp", true),
                slot("C.esp", false),
                slot("D.esp", true)
            ]
        );
    }

    #[test]
    fn plugins_txt_alone_gives_the_order_and_no_list_at_all_is_refused() {
        let dir = TempDir::new("lo-slots-one");
        assert!(matches!(read_slots(dir.path()), Err(Error::Refused(_))));
        write_file(dir.path(), "plugins.txt", b"A.esm\r\nB.esp\r\n");
        assert_eq!(
            read_slots(dir.path()).unwrap(),
            [slot("A.esm", true), slot("B.esp", true)]
        );
    }

    #[test]
    fn a_plugin_that_is_not_installed_follows_the_plugin_before_it() {
        let current = [
            slot("A.esm", true),
            slot("Ghost.esp", true),
            slot("B.esp", false),
            slot("C.esp", true),
        ];
        let sorted = ["A.esm".to_owned(), "C.esp".to_owned(), "B.esp".to_owned()];
        let names: Vec<_> = place_not_installed(&current, &sorted)
            .into_iter()
            .map(|s| (s.name, s.active))
            .collect();
        assert_eq!(
            names,
            [
                ("A.esm".to_owned(), true),
                ("Ghost.esp".to_owned(), true),
                ("C.esp".to_owned(), true),
                ("B.esp".to_owned(), false)
            ]
        );
        // First in the list: stays first.
        let current = [slot("Ghost.esp", false), slot("A.esm", true)];
        let placed = place_not_installed(&current, &["A.esm".to_owned()]);
        assert_eq!(placed[0].name, "Ghost.esp");
    }

    #[test]
    fn list_bytes_write_the_header_active_plugins_and_the_code_page() {
        let order = [
            slot("A.esm", true),
            slot("Caf\u{e9}.esp", true),
            slot("B.esp", false),
        ];
        let (plugins, load_order) = list_bytes(&order).unwrap();
        assert_eq!(
            plugins,
            b"# This file was automatically generated by Mod Organizer.\r\nA.esm\r\nCaf\xE9.esp\r\n"
        );
        assert_eq!(
            String::from_utf8(load_order).unwrap(),
            "# This file was automatically generated by Mod Organizer.\r\nA.esm\r\nCaf\u{e9}.esp\r\nB.esp\r\n"
        );
        assert!(list_bytes(&[slot("\u{6f22}.esp", true)]).is_err());
    }

    #[test]
    fn target_times_strictly_increase() {
        assert!(target_time(0) < target_time(1));
        assert_eq!(
            target_time(2)
                .duration_since(target_time(0))
                .unwrap()
                .as_secs(),
            2 * STEP_SECS
        );
    }

    #[test]
    fn the_masters_of_a_plugin_file_are_read_and_a_bad_file_is_reported() {
        let dir = TempDir::new("lo-masters");
        write_file(
            dir.path(),
            "a.esp",
            &nvmod_testkit::PluginBuilder::new()
                .requires("X.esm")
                .build(),
        );
        write_file(dir.path(), "bad.esp", b"not a plugin");
        assert_eq!(masters_of(&dir.path().join("a.esp")).unwrap(), ["X.esm"]);
        assert!(masters_of(&dir.path().join("bad.esp")).is_err());
        assert!(masters_of(&dir.path().join("none.esp")).is_err());
        assert!(staged_file(dir.path(), "A.ESP").is_some());
        assert!(staged_file(dir.path(), "none.esp").is_none());
        assert_eq!(empty_masterlist().warnings().len(), 0);
    }
}
