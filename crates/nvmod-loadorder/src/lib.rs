//! The Load order of a Profile. loot-rs proposes it from the plugins of the Staging tree; applying it writes
//! `plugins.txt` and `loadorder.txt` together and encodes the order in the modification times of the plugin files
//! of the Staging tree, because nv-rs orders plugins by file time until the fork has a `plugins.txt` switch
//! (docs/DECISIONS.md). The authoritative order is the one in the Profile; the times are a cache that is rewritten.
//!
//! The Staging tree hard-links plugin files to the Mod folders (which, for an imported Instance, share inodes with
//! the MO2 instance). Setting a time on a hard link would set it on the Mod's file too, so a plugin file's link
//! is first replaced by a copy.

use loot_rs::api::{Masterlist, PluginSlot, SortError, SortOptions, SortOutput, sort};
use nvmod_core::{Finding, Severity};
use nvmod_formats::LockedOrder;
use nvmod_formats::text::{encode_windows_1252, read_limited};
use nvmod_instance::NvmodInstance;
use nvmod_modinstall::journal;
use std::fs;
use std::path::{Path, PathBuf};

use nvmod_stage::stamp;
pub use nvmod_stage::stamp::{BASE_TIME_SECS, STEP_SECS, target_time, times_stale};
pub use nvmod_stage::{Slot, staged_file};

const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// Why a Load order could not be computed or applied.
#[derive(Debug, PartialEq, Eq)]
pub enum Error {
    /// Refused before anything was written (exit code 2).
    Refused(String),
    /// A step failed; the profile files and the Staging tree were put back (exit code 4).
    Failed(String),
}

/// What loot-rs proposes for a Profile.
#[derive(Debug)]
pub struct Proposal {
    /// The profile.
    pub profile: String,
    /// The Staging tree's `Data` folder loot-rs read.
    pub data: PathBuf,
    /// The order in the profile now.
    pub current: Vec<Slot>,
    /// The proposed order, with the plugins that are not installed placed after the plugin that preceded them.
    pub proposed: Vec<Slot>,
    /// Everything loot-rs reported.
    pub output: SortOutput,
}

impl Proposal {
    /// Whether the proposed order differs from the current one (names, ignoring case, in order).
    #[must_use]
    pub fn reordered(&self) -> bool {
        self.current.len() != self.proposed.len()
            || self
                .current
                .iter()
                .zip(&self.proposed)
                .any(|(a, b)| !a.name.eq_ignore_ascii_case(&b.name))
    }
}

impl Proposal {
    /// How many positions of the Load order the proposal would change: the places where the proposed plugin is
    /// not the current one (names, ignoring case), plus the difference in length. Counts only, no names.
    #[must_use]
    pub fn positions_changed(&self) -> usize {
        let differing = self
            .current
            .iter()
            .zip(&self.proposed)
            .filter(|(a, b)| !a.name.eq_ignore_ascii_case(&b.name))
            .count();
        differing + self.current.len().abs_diff(self.proposed.len())
    }
}

/// What applying a proposal changed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Applied {
    /// `plugins.txt` or `loadorder.txt` was rewritten.
    pub lists_written: bool,
    /// Plugin files that got a new modification time.
    pub stamped: usize,
    /// Of those, files whose hard link was replaced by a copy first.
    pub detached: usize,
    /// The journal `nvmod rollback` uses; `None` when nothing needed to change.
    pub journal: Option<String>,
}

fn refuse<T>(text: impl Into<String>) -> Result<T, Error> {
    Err(Error::Refused(text.into()))
}

/// The plugins of `profile_dir` in `loadorder.txt` order (or `plugins.txt` order when there is no
/// `loadorder.txt`), each marked active when `plugins.txt` lists it. Plugins only in `plugins.txt` follow at the end.
///
/// # Errors
/// `Refused` when the profile has neither list, or a list cannot be read.
pub fn read_slots(profile_dir: &Path) -> Result<Vec<Slot>, Error> {
    nvmod_stage::read_slots(profile_dir).map_err(Error::Refused)
}

/// The `Data` folder of the Staging tree of `profile`.
///
/// # Errors
/// `Refused`, telling the user to run `nvmod stage`, when the tree does not exist.
pub fn staging_data(instance: &NvmodInstance, profile: &str) -> Result<PathBuf, Error> {
    let data = instance.staging_dir(profile).join("data");
    if data.is_dir() {
        Ok(data)
    } else {
        refuse(format!(
            "profile `{profile}` has no Staging tree; run `nvmod stage --instance {} --profile {profile}` first",
            instance.root.display()
        ))
    }
}

/// Read a masterlist.
///
/// # Errors
/// `Refused` with loot-rs's reason.
pub fn load_masterlist(path: &Path) -> Result<Masterlist, Error> {
    Masterlist::from_file(path).map_err(|e| Error::Refused(e.to_string()))
}

/// A masterlist without entries: only the header masters and the current order decide.
///
/// # Panics
/// Never: an empty text is a valid masterlist (tested).
#[must_use]
pub fn empty_masterlist() -> Masterlist {
    Masterlist::parse("").expect("an empty masterlist is valid")
}

fn describe(error: &SortError) -> String {
    format!("loot-rs cannot sort this Load order: {error}")
}

/// Place the plugins that are not installed (loot-rs's default rule: each goes right after the installed plugin
/// that preceded it in `current`), and carry each plugin's active flag over from `current`.
fn place_not_installed(current: &[Slot], output: &SortOutput, slots: &[PluginSlot]) -> Vec<Slot> {
    let active = |name: &str| {
        current
            .iter()
            .find(|s| s.name.eq_ignore_ascii_case(name))
            .is_some_and(|s| s.active)
    };
    output
        .order_with_not_installed(slots)
        .into_iter()
        .map(|name| Slot {
            active: active(&name),
            name,
        })
        .collect()
}

/// Sort the Load order of `profile` with loot-rs, reading the plugins of its Staging tree.
///
/// # Errors
/// `Refused` when the Staging tree or the lists are missing, or loot-rs refuses the input (rules that contradict
/// each other, too many plugins).
pub fn propose(
    instance: &NvmodInstance,
    profile: &str,
    masterlist: &Masterlist,
) -> Result<Proposal, Error> {
    propose_with(instance, profile, masterlist, &SortOptions::default())
}

/// [`propose`] with the loot-rs options given: a cancel token and a progress hook, for a caller that runs the sort
/// as a job.
///
/// # Errors
/// As [`propose`]; a cancelled sort is `Refused` with loot-rs's reason (the caller asked, so it knows).
pub fn propose_with(
    instance: &NvmodInstance,
    profile: &str,
    masterlist: &Masterlist,
    options: &SortOptions,
) -> Result<Proposal, Error> {
    let data = staging_data(instance, profile)?;
    let current = read_slots(&instance.profile_dir(profile))?;
    let slots: Vec<PluginSlot> = current
        .iter()
        .map(|s| PluginSlot::new(s.name.clone(), s.active))
        .collect();
    let output =
        sort(&slots, masterlist, &data, options).map_err(|e| Error::Refused(describe(&e)))?;
    let mut proposed = place_not_installed(&current, &output, &slots);
    let locks = read_locks(&instance.profile_dir(profile))?;
    enforce_locks(&mut proposed, &locks);
    Ok(Proposal {
        profile: profile.to_owned(),
        data,
        current,
        proposed,
        output,
    })
}

fn join(lines: impl IntoIterator<Item = String>) -> String {
    let mut out = format!("{HEADER}\r\n");
    for line in lines {
        out.push_str(&line);
        out.push_str("\r\n");
    }
    out
}

/// The bytes of `plugins.txt` (active plugins, Windows code page) and `loadorder.txt` (all plugins, UTF-8) for
/// `order`.
///
/// # Errors
/// `Refused` when an active plugin's name has no place in the Windows code page.
pub fn list_bytes(order: &[Slot]) -> Result<(Vec<u8>, Vec<u8>), Error> {
    let plugins = join(order.iter().filter(|s| s.active).map(|s| s.name.clone()));
    let load_order = join(order.iter().map(|s| s.name.clone()));
    let plugins = encode_windows_1252(&plugins).ok_or_else(|| {
        Error::Refused(
            "a plugin name cannot be written to plugins.txt in the Windows code page".to_owned(),
        )
    })?;
    Ok((plugins, load_order.into_bytes()))
}

fn differs(path: &Path, bytes: &[u8]) -> bool {
    fs::read(path).map_or(true, |old| old != bytes)
}

/// Where a step may fail: an injected failure (`NVMOD_FAIL_AT`) or a termination request.
fn fail_point(step: &str) -> Result<(), String> {
    nvmod_core::cancel::step_point(step)
}

/// Write the proposed order: `plugins.txt` and `loadorder.txt` together, then the modification times of the
/// plugin files of the Staging tree (strictly increasing in Load order). A journal and a backup are written
/// before the first change, so `nvmod rollback` undoes it; a step that fails puts everything back. Nothing is
/// written, and no journal made, when the files and times are already right.
///
/// # Errors
/// `Refused` before any change; `Failed` when a step failed and was rolled back.
pub fn apply(instance: &NvmodInstance, proposal: &Proposal) -> Result<Applied, Error> {
    write_order(
        instance,
        &proposal.profile,
        Some(&proposal.data),
        &proposal.proposed,
        None,
        journal::KIND_SORT,
    )
}

/// Write `order` as the Load order of `profile` in one journaled step: `plugins.txt` and `loadorder.txt` (and
/// `lockedorder.txt` when `locked` holds its bytes), then the file times of the plugins in the Staging tree
/// `data` (none when it is `None`). `kind` is the journal kind. Nothing is written, and no journal made, when
/// the files and times are already right.
///
/// # Errors
/// `Refused` before any change; `Failed` when a step failed and was rolled back.
pub fn write_order(
    instance: &NvmodInstance,
    profile: &str,
    data: Option<&Path>,
    order: &[Slot],
    locked: Option<&[u8]>,
    kind: &str,
) -> Result<Applied, Error> {
    let dir = instance.profile_dir(profile);
    let (plugins, load_order) = list_bytes(order)?;
    let write_plugins = differs(&dir.join("plugins.txt"), &plugins);
    let write_order = differs(&dir.join("loadorder.txt"), &load_order);
    let write_locked = locked.is_some_and(|bytes| differs(&dir.join(LOCKED_FILE), bytes));
    let stamps = data.map_or_else(Vec::new, |data| stamp::plan(data, order));
    if !write_plugins && !write_order && !write_locked && stamps.is_empty() {
        return Ok(Applied {
            lists_written: false,
            stamped: 0,
            detached: 0,
            journal: None,
        });
    }
    let entry = journal::begin_kind(instance, profile, "", kind).map_err(Error::Refused)?;
    let outcome = (|| -> Result<usize, String> {
        fail_point("sort-lists")?;
        if let (true, Some(bytes)) = (write_locked, locked) {
            journal::write_atomic(&dir.join(LOCKED_FILE), bytes)?;
        }
        // plugins.txt before loadorder.txt, so loadorder.txt stays the newest.
        if write_plugins {
            journal::write_atomic(&dir.join("plugins.txt"), &plugins)?;
        }
        if write_order {
            journal::write_atomic(&dir.join("loadorder.txt"), &load_order)?;
        }
        fail_point("sort-times")?;
        stamp::apply(&stamps)
    })();
    match outcome {
        Ok(detached) => {
            journal::complete(instance, &entry).map_err(Error::Failed)?;
            Ok(Applied {
                lists_written: write_plugins || write_order || write_locked,
                stamped: stamps.len(),
                detached,
                journal: Some(entry.id),
            })
        }
        Err(why) => match journal::undo(instance, &entry) {
            Ok(()) => Err(Error::Failed(format!(
                "{why}; the Load order change was rolled back"
            ))),
            Err(undo) => Err(Error::Failed(format!(
                "{why}; the rollback failed too ({undo}); run `nvmod rollback`"
            ))),
        },
    }
}

/// The file of the locks in a profile folder.
pub const LOCKED_FILE: &str = "lockedorder.txt";

/// The locks of the profile in `profile_dir`: empty when there is no `lockedorder.txt`.
///
/// # Errors
/// `Refused` when the file cannot be read or has a line that is not `name|priority`.
pub fn read_locks(profile_dir: &Path) -> Result<LockedOrder, Error> {
    let path = profile_dir.join(LOCKED_FILE);
    if !path.is_file() {
        return Ok(LockedOrder::default());
    }
    let bytes =
        read_limited(&path).map_err(|e| Error::Refused(format!("{}: {e}", path.display())))?;
    LockedOrder::parse(&bytes).map_err(Error::Refused)
}

