#[test]
fn a_refusal_copies_as_text_without_a_command_line() {
    let dir = TempDir::new("conflicts-copy");
    let mut request = contested().request();
    request.instance = dir.path().to_path_buf();
    let text = refused(&request).copy_text();
    assert!(text.contains("job: conflicts.report"), "{text}");
    assert!(text.contains("error: refused"), "{text}");
    assert!(!text.contains("nvmod conflicts"), "{text}");
}

#[test]
fn a_report_whose_cancel_is_set_before_the_call_stops_at_once_and_changes_nothing() {
    let s = contested();
    let before = snapshot(&s.root());
    let token = CancelToken::new();
    token.cancel();
    let mut steps = 0;
    let mut count = |_: &Event| steps += 1;
    let out = report(&s.request(), &mut count, &token).expect("not an error");
    assert!(matches!(out, Outcome::Cancelled));
    assert_eq!(steps, 0);
    assert_eq!(snapshot(&s.root()), before);
}

#[test]
fn a_report_cancelled_from_its_progress_stops_before_the_work_and_changes_nothing() {
    let s = contested();
    let before = snapshot(&s.root());
    let token = CancelToken::new();
    let stopper = token.clone();
    let mut seen = Vec::new();
    let mut on_event = |event: &Event| {
        seen.push(event.step);
        if event.step == "read-layers" {
            stopper.cancel();
        }
    };
    let out = report(&s.request(), &mut on_event, &token).expect("not an error");
    assert!(matches!(out, Outcome::Cancelled));
    assert_eq!(seen, ["open-instance", "read-layers"]);
    assert_eq!(snapshot(&s.root()), before);
}

#[test]
fn a_report_request_round_trips_through_json_with_the_mod_key() {
    let mut request = contested().request();
    request.profile = Some("Default".to_owned());
    request.mod_name = Some("A".to_owned());
    request.archives = true;
    let text = serde_json::to_string(&request).expect("serialises");
    assert!(text.contains("\"mod\":\"A\""), "{text}");
    let back: ReportRequest = serde_json::from_str(&text).expect("parses");
    assert_eq!(back, request);
}
