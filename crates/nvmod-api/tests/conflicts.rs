//! The conflicts job, called in process on a synthetic nvmod Instance: Mods are written as files, in code. Nothing
//! is read from a game.

use nvmod_api::conflicts::{ReportOutput, ReportRequest, report};
use nvmod_api::{CancelToken, ErrorKind, Event, JobError, NoProgress, Outcome};
use nvmod_instance::NvmodInstance;
use nvmod_testkit::{BaseBuilder, PeBuilder, TempDir, snapshot, write_file};
use std::path::PathBuf;

/// The job name of every refusal of this job.
const REPORT: &str = "conflicts.report";

/// An nvmod Instance with a Default profile whose modlist names the given Mods, highest priority first, and whose
/// Mods hold the given files. Two Mods that hold the same path contest it.
struct Scratch {
    base: TempDir,
    inst: TempDir,
}

impl Scratch {
    fn new(modlist: &str, mods: &[(&str, &[&str])]) -> Self {
        let base = TempDir::new("conflicts-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
        write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
        let inst = TempDir::new("conflicts-inst");
        let s = Self { base, inst };
        let instance =
            NvmodInstance::create(&s.root(), s.base.path()).expect("create the Instance");
        instance
            .create_profile("Default")
            .expect("create the profile");
        s.modlist(modlist);
        for (name, files) in mods {
            for file in *files {
                write_file(
                    &s.root(),
                    &format!("mods/{name}/{file}"),
                    format!("{name}:{file}").as_bytes(),
                );
            }
        }
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn modlist(&self, lines: &str) {
        write_file(
            &self.root(),
            "profiles/Default/modlist.txt",
            format!("# This file was automatically generated by Mod Organizer.\r\n{lines}")
                .as_bytes(),
        );
    }

    fn request(&self) -> ReportRequest {
        ReportRequest {
            instance: self.root(),
            profile: None,
            mod_name: None,
            archives: false,
        }
    }
}

/// Three Mods, A the highest priority, that contest `meshes/rock.nif` and `textures/a.dds`.
fn contested() -> Scratch {
    Scratch::new(
        "+A\r\n+B\r\n+C\r\n",
        &[
            ("A", &["meshes/rock.nif", "textures/a.dds"]),
            ("B", &["Meshes/Rock.nif", "textures/A.dds", "sound/x.wav"]),
            ("C", &["textures/a.dds", "c_only.txt"]),
        ],
    )
}

fn run(request: &ReportRequest) -> Result<Outcome<ReportOutput>, JobError> {
    report(request, &mut NoProgress, &CancelToken::new())
}

fn done(request: &ReportRequest) -> ReportOutput {
    run(request)
        .expect("the report is made")
        .done()
        .expect("not cancelled")
}

fn refused(request: &ReportRequest) -> JobError {
    run(request).expect_err("refused")
}

#[test]
fn a_profile_with_contested_paths_reports_the_winner_and_the_losers() {
    let s = contested();
    let out = done(&s.request());
    assert_eq!(out.report.profile, "Default");
    assert_eq!(out.report.mods.len(), 3);
    assert_eq!(out.report.conflicts.len(), 2);
    let rock = out
        .report
        .conflicts
        .iter()
        .find(|c| c.path == "meshes/rock.nif")
        .expect("the rock is contested");
    assert_eq!(rock.winner.name, "A");
    assert_eq!(rock.losers[0].name, "B");
    assert!(out.report.archives.is_none());
}

#[test]
fn a_profile_without_contested_paths_reports_an_empty_conflict_list() {
    let s = Scratch::new("+A\r\n", &[("A", &["only.txt"])]);
    let out = done(&s.request());
    assert_eq!(out.report.mods.len(), 1);
    assert_eq!(out.report.conflicts.len(), 0);
}

#[test]
fn the_archive_axes_report_a_loose_file_over_an_archive_when_asked_for() {
    // Alpha's archive loads through its plugin and holds a texture that Beta also has as a loose file; with the
    // INI flag on, the loose file wins over the archive.
    let s = Scratch::new(
        "+Beta\r\n+Alpha\r\n",
        &[("Alpha", &[]), ("Beta", &["Textures/Fake/A.dds"])],
    );
    let bsa = nvmod_testkit::BsaBuilder::new()
        .file("textures/fake/a.dds", 4)
        .bytes();
    write_file(&s.root(), "mods/Alpha/Alpha.bsa", &bsa);
    write_file(
        &s.root(),
        "profiles/Default/plugins.txt",
        b"FalloutNV.esm\r\nAlpha.esp\r\n",
    );
    write_file(
        &s.root(),
        "profiles/Default/loadorder.txt",
        b"FalloutNV.esm\r\nAlpha.esp\r\n",
    );
    write_file(
        &s.root(),
        "profiles/Default/fallout.ini",
        b"[Archive]\r\nSArchiveList=Alpha.bsa\r\nbInvalidateOlderFiles=1\r\n",
    );
    let mut request = s.request();
    request.archives = true;
    let out = done(&request);
    let archives = out.report.archives.expect("the archive axes are there");
    assert_eq!(archives.invalidate_older_files, Some(true));
    assert_eq!(archives.archives.len(), 1);
    assert_eq!(archives.archives[0].name, "Alpha.bsa");
    let collision = archives
        .conflicts
        .iter()
        .find(|c| c.path == "textures/fake/a.dds")
        .expect("the archive texture collides with the loose file");
    assert_eq!(collision.rule, "loose-over-archive");
    assert_eq!(collision.winner.name, "Beta");
    assert_eq!(collision.winner.kind, "loose");
    assert_eq!(collision.losers[0].name, "Alpha");
}

#[test]
fn without_the_flag_the_report_has_no_archive_axis() {
    let s = contested();
    assert!(done(&s.request()).report.archives.is_none());
}

#[test]
fn a_named_mod_keeps_its_own_row_and_the_paths_it_is_in() {
    let s = contested();
    let mut request = s.request();
    request.mod_name = Some("B".to_owned());
    let out = done(&request);
    assert_eq!(out.report.mods.len(), 1);
    assert_eq!(out.report.mods[0].name, "B");
    assert!(
        out.report
            .conflicts
            .iter()
            .all(|c| c.winner.name == "B" || c.losers.iter().any(|l| l.name == "B"))
    );
    assert_eq!(out.report.conflicts.len(), 2);
}

#[test]
fn a_folder_that_is_not_an_nvmod_instance_is_a_refusal() {
    let dir = TempDir::new("conflicts-empty");
    let mut request = contested().request();
    request.instance = dir.path().to_path_buf();
    let error = refused(&request);
    assert_eq!(error.kind, ErrorKind::Refused);
    assert_eq!(error.job, REPORT);
    assert!(
        error.summary.contains("is not an nvmod Instance"),
        "{error}"
    );
}

