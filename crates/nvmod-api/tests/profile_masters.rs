//! The profile job lists the masters of the base copy, called in process on a synthetic base copy.

use nvmod_api::profile::{CreateRequest, create};
use nvmod_api::{CancelToken, NoProgress, Outcome};
use nvmod_instance::NvmodInstance;
use nvmod_testkit::{BaseBuilder, TempDir, write_file};

fn list(root: &std::path::Path, file: &str) -> String {
    std::fs::read_to_string(root.join("profiles/Default").join(file)).unwrap()
}

#[test]
fn the_profile_job_lists_the_present_masters_in_both_lists() {
    let base = TempDir::new("pm-base");
    BaseBuilder::steam().write(base.path());
    for name in ["tribalpack.esm", "DEADMONEY.esm"] {
        write_file(base.path(), &format!("Data/{name}"), b"synthetic master");
    }
    let inst = TempDir::new("pm-inst");
    let root = inst.path().join("fnv");
    NvmodInstance::create(&root, base.path()).expect("create the Instance");
    let outcome = create(
        &CreateRequest {
            instance: root.clone(),
            name: None,
        },
        &mut NoProgress,
        &CancelToken::new(),
    )
    .expect("create the profile");
    assert!(matches!(outcome, Outcome::Done(_)));
    let want = "# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nDeadMoney.esm\r\nTribalPack.esm\r\n";
    assert_eq!(list(&root, "plugins.txt"), want);
    assert_eq!(list(&root, "loadorder.txt"), want);
}

#[test]
fn without_dlc_the_job_still_lists_only_the_game_master() {
    let base = TempDir::new("pm-base-none");
    BaseBuilder::steam().write(base.path());
    let inst = TempDir::new("pm-inst-none");
    let root = inst.path().join("fnv");
    NvmodInstance::create(&root, base.path()).expect("create the Instance");
    create(
        &CreateRequest {
            instance: root.clone(),
            name: None,
        },
        &mut NoProgress,
        &CancelToken::new(),
    )
    .expect("create the profile");
    assert_eq!(
        list(&root, "plugins.txt"),
        "# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\n"
    );
}
