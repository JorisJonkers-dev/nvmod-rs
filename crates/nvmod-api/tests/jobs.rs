//! Every job of `nvmod-api`, called in process on a scratch Instance. Plugins are synthetic headers built by the
//! testkit and the masterlist is written here; no game data is used.

use nvmod_api::loadorder::{SortRequest, sort};
use nvmod_api::mods::{Change, ChangeRequest, ListRequest, Place};
use nvmod_api::run::PlanRequest;
use nvmod_api::{API_VERSION, CancelToken, ErrorKind, Event, NoProgress, Outcome};
use nvmod_instance::NvmodInstance;
use nvmod_testkit::{BaseBuilder, PeBuilder, PluginBuilder, TempDir, write_file};
use std::fs;
use std::path::PathBuf;

const MASTERLIST: &str = r"
globals:
  - {type: say, content: 'Masterlist for tests'}
";

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Mods `Patch` (Patch.esp, needs Base.esp) and `Core` (Base.esp); a Load order with the patch before its
    /// master. Staged.
    fn new() -> Self {
        let base = TempDir::new("api-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("api-inst");
        let root = inst.path().join("fnv");
        let instance = NvmodInstance::create(&root, base.path()).expect("create the Instance");
        if !instance.profile_dir("Default").is_dir() {
            instance
                .create_profile("Default")
                .expect("create the profile");
        }
        write_file(
            &root,
            "mods/Patch/Patch.esp",
            &PluginBuilder::new().requires("Base.esp").build(),
        );
        write_file(&root, "mods/Core/Base.esp", &PluginBuilder::new().build());
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n+Patch\r\n+Core\r\n",
        );
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nPatch.esp\r\nBase.esp\r\n",
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nPatch.esp\r\nBase.esp\r\n",
        );
        nvmod_stage::stage(
            &instance,
            "Default",
            nvmod_stage::Options { copy_only: false },
        )
        .expect("stage");
        fs::write(inst.path().join("masterlist.yaml"), MASTERLIST).expect("masterlist");
        Self { _base: base, inst }
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn sort_request(&self, apply: bool) -> SortRequest {
        SortRequest {
            instance: self.root(),
            profile: None,
            masterlist: self.inst.path().join("masterlist.yaml"),
            apply,
        }
    }
}

fn names(order: &[nvmod_api::loadorder::Slot]) -> Vec<&str> {
    order.iter().map(|s| s.name.as_str()).collect()
}

#[test]
fn mods_list_gives_the_mods_in_priority_order() {
    let s = Scratch::new();
    let request = ListRequest {
        instance: s.root(),
        profile: None,
        category: None,
    };
    let listed = nvmod_api::mods::list(&request, &mut NoProgress, &CancelToken::new())
        .expect("lists")
        .done()
        .expect("not cancelled");
    assert_eq!(listed.profile, "Default");
    let rows: Vec<(&str, &str)> = listed
        .mods
        .iter()
        .map(|r| (r.row.name.as_str(), r.row.state))
        .collect();
    assert_eq!(rows, [("Patch", "enabled"), ("Core", "enabled")]);
}

#[test]
fn mods_change_disables_a_mod_and_reports_it() {
    let s = Scratch::new();
    let request = ChangeRequest {
        instance: s.root(),
        profile: Some("Default".into()),
        change: Change::Disable {
            mods: vec!["Patch".into()],
        },
        dry_run: false,
    };
    let report = nvmod_api::mods::change(&request, &mut NoProgress, &CancelToken::new())
        .expect("changes")
        .done()
        .expect("not cancelled");
    assert_eq!(report.status, "changed");
    assert_eq!(report.changed, ["Patch"]);
    let modlist = fs::read_to_string(s.root().join("profiles/Default/modlist.txt")).unwrap();
    assert!(modlist.contains("-Patch"), "{modlist}");
}

#[test]
fn a_mods_change_dry_run_writes_nothing() {
    let s = Scratch::new();
    let before = fs::read(s.root().join("profiles/Default/modlist.txt")).unwrap();
    let request = ChangeRequest {
        instance: s.root(),
        profile: None,
        change: Change::Move {
            name: "Core".into(),
            to: Place::Top,
        },
        dry_run: true,
    };
    let report = nvmod_api::mods::change(&request, &mut NoProgress, &CancelToken::new())
        .expect("plans")
        .done()
        .expect("not cancelled");
    assert_eq!(report.status, "dry-run");
    assert_eq!(report.mods[0].name, "Core");
    assert_eq!(
        fs::read(s.root().join("profiles/Default/modlist.txt")).unwrap(),
        before
    );
}

#[test]
fn sort_proposes_an_order_and_reports_loot_rs_progress() {
    let s = Scratch::new();
    let mut events: Vec<Event> = Vec::new();
    let mut progress = |e: &Event| events.push(e.clone());
    let done = sort(&s.sort_request(false), &mut progress, &CancelToken::new())
        .expect("sorts")
        .done()
        .expect("not cancelled");
    assert_eq!(
        names(&done.proposal.proposed),
        ["FalloutNV.esm", "Base.esp", "Patch.esp"]
    );
    assert!(done.applied.is_none());
    assert!(
        events.iter().any(|e| e.step == "read-plugins"),
        "{events:?}"
    );
    assert!(events.iter().any(|e| e.step == "check"), "{events:?}");
}

#[test]
fn sort_with_apply_writes_the_lists() {
    let s = Scratch::new();
    let done = sort(&s.sort_request(true), &mut NoProgress, &CancelToken::new())
        .expect("sorts")
        .done()
        .expect("not cancelled");
    assert!(done.applied.expect("applied").lists_written);
    let order = fs::read_to_string(s.root().join("profiles/Default/loadorder.txt")).unwrap();
    assert!(order.find("Base.esp") < order.find("Patch.esp"), "{order}");
}

#[test]
fn a_cancelled_sort_is_a_result_and_writes_nothing() {
    let s = Scratch::new();
    let before = fs::read(s.root().join("profiles/Default/loadorder.txt")).unwrap();
    let cancel = CancelToken::new();
    cancel.cancel();
    let outcome = sort(&s.sort_request(true), &mut NoProgress, &cancel).expect("no error");
    assert!(matches!(outcome, Outcome::Cancelled));
    assert_eq!(
        fs::read(s.root().join("profiles/Default/loadorder.txt")).unwrap(),
        before
    );
}

#[test]
fn a_missing_masterlist_is_a_refusal_with_copyable_text() {
    let s = Scratch::new();
    let mut request = s.sort_request(false);
    request.masterlist = s.inst.path().join("missing.yaml");
    let error = sort(&request, &mut NoProgress, &CancelToken::new()).expect_err("refused");
    assert_eq!(error.kind, ErrorKind::Refused);
    let text = error.copy_text();
    assert!(
        text.starts_with(&format!(
            "nvmod {API_VERSION}\njob: loadorder.sort\nerror: refused\n"
        )),
        "{text}"
    );
    assert!(!text.contains("--"), "no command line: {text}");
}

#[test]
fn saves_list_reads_the_profile_saves() {
    let s = Scratch::new();
    fs::write(
        s.root().join("profiles/Default/settings.ini"),
        "[General]\r\nLocalSaves=true\r\n",
    )
    .unwrap();
    fs::create_dir_all(s.root().join("profiles/Default/saves")).unwrap();
    fs::write(s.root().join("profiles/Default/saves/Save 1.fos"), b"x").unwrap();
    let request = nvmod_api::saves::ListRequest {
        instance: s.root(),
        profile: None,
        prefix: None,
    };
    let listed = nvmod_api::saves::list(&request, &mut NoProgress, &CancelToken::new())
        .expect("lists")
        .done()
        .expect("not cancelled");
    assert!(listed.local);
    assert_eq!(listed.saves.len(), 1);
    assert_eq!(listed.saves[0].name, "Save 1.fos");
}

#[test]
fn run_plan_plans_the_game_without_starting_it() {
    let s = Scratch::new();
    let proton = s.inst.path().join("proton");
    fs::write(&proton, b"#!/bin/sh\n").unwrap();
    let request = PlanRequest {
        instance: s.root(),
        profile: None,
        target: "game".into(),
        args: Vec::new(),
        proton: Some(proton.display().to_string()),
        steam_client: None,
        via_proton: false,
        viewer: None,
        shared_root: None,
        restage: false,
        no_stage: true,
    };
    let plan = nvmod_api::run::plan(&request, &mut NoProgress, &CancelToken::new())
        .expect("plans")
        .done()
        .expect("not cancelled");
    assert_eq!(plan.entry, "game");
    assert_eq!(plan.staging, nvmod_api::run::StagingAction::Skipped);
}

#[test]
fn a_folder_that_is_not_an_instance_is_refused() {
    let dir = TempDir::new("api-none");
    let request = ListRequest {
        instance: dir.path().to_path_buf(),
        profile: None,
        category: None,
    };
    let error =
        nvmod_api::mods::list(&request, &mut NoProgress, &CancelToken::new()).expect_err("refused");
    assert_eq!(error.kind, ErrorKind::Refused);
    assert_eq!(error.job, "mods.list");
}

#[test]
fn requests_round_trip_through_json() {
    let request = ChangeRequest {
        instance: PathBuf::from("/x"),
        profile: None,
        change: Change::Move {
            name: "A".into(),
            to: Place::Before("B".into()),
        },
        dry_run: true,
    };
    let text = serde_json::to_string(&request).unwrap();
    let back: ChangeRequest = serde_json::from_str(&text).unwrap();
    assert_eq!(back, request);
}

#[test]
fn the_api_version_is_the_release_version() {
    let manifest = fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../Cargo.toml"))
        .expect("workspace manifest");
    let version = manifest
        .lines()
        .find_map(|line| line.strip_prefix("version = "))
        .expect("version")
        .trim_matches('"');
    assert_eq!(API_VERSION, version);
}
