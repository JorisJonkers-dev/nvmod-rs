const T0: i64 = 1_794_657_600;

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Mods `Patch` (Patch.esp, needs Base.esp) and `Core` (Base.esp); a Load order with the patch before its
    /// master. Staged.
    fn new() -> Self {
        let base = TempDir::new("api-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("api-inst");
        let root = inst.path().join("fnv");
        let instance = NvmodInstance::create(&root, base.path()).expect("create the Instance");
        if !instance.profile_dir("Default").is_dir() {
            instance
                .create_profile("Default")
                .expect("create the profile");
        }
        write_file(
            &root,
            "mods/Patch/Patch.esp",
            &PluginBuilder::new().requires("Base.esp").build(),
        );
        write_file(&root, "mods/Core/Base.esp", &PluginBuilder::new().build());
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n+Patch\r\n+Core\r\n",
        );
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nPatch.esp\r\nBase.esp\r\n",
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nPatch.esp\r\nBase.esp\r\n",
        );
        nvmod_stage::stage(
            &instance,
            "Default",
            nvmod_stage::Options { copy_only: false },
        )
        .expect("stage");
        fs::write(inst.path().join("masterlist.yaml"), MASTERLIST).expect("masterlist");
        Self { _base: base, inst }
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    /// An Instance with no Mods at all: the Doctor has nothing to fail on.
    fn bare() -> Self {
        let base = TempDir::new("api-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("api-inst");
        let root = inst.path().join("fnv");
        let instance = NvmodInstance::create(&root, base.path()).expect("create the Instance");
        if !instance.profile_dir("Default").is_dir() {
            instance
                .create_profile("Default")
                .expect("create the profile");
        }
        nvmod_stage::stage(
            &instance,
            "Default",
            nvmod_stage::Options { copy_only: false },
        )
        .expect("stage");
        fs::write(inst.path().join("masterlist.yaml"), MASTERLIST).expect("masterlist");
        Self { _base: base, inst }
    }

    fn sort_request(&self, apply: bool) -> SortRequest {
        SortRequest {
            instance: self.root(),
            profile: None,
            masterlist: self.inst.path().join("masterlist.yaml"),
            apply,
        }
    }

    fn keep_order_request(&self) -> KeepOrderRequest {
        KeepOrderRequest {
            instance: self.root(),
            profile: None,
        }
    }
}

fn names(order: &[nvmod_api::loadorder::Slot]) -> Vec<&str> {
    order.iter().map(|s| s.name.as_str()).collect()
}

