//! A job given its own token is stopped by that token and not by the process-wide stop request (nvmod-rs#212).
//! This file is its own test binary with one test: it sets the process-wide request, which no other test may see.

use nvmod_api::install::{InstallOutput, InstallRequest, LimitOverrides};
use nvmod_api::{CancelToken, NoProgress, Outcome};
use nvmod_instance::NvmodInstance;
use nvmod_testkit::{BaseBuilder, PeBuilder, TempDir, write_file};
use nvmod_testkit::{covers, ids};

#[test]
fn a_process_wide_request_does_not_stop_a_job_with_its_own_token() {
    covers(&[ids::api::jobs::SCOPED_CANCEL]);
    let base = TempDir::new("scope-base");
    BaseBuilder::steam().write(base.path());
    write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
    let inst = TempDir::new("scope-inst");
    let root = inst.path().join("fnv");
    let instance = NvmodInstance::create(&root, base.path()).expect("create the Instance");
    if !instance.profile_dir("Default").is_dir() {
        instance
            .create_profile("Default")
            .expect("create the profile");
    }
    write_file(
        &root,
        "profiles/Default/modlist.txt",
        b"# This file was automatically generated by Mod Organizer.\r\n",
    );
    let folder = TempDir::new("scope-mod");
    write_file(folder.path(), "Meshes/a.nif", b"a");
    write_file(folder.path(), "Scoped.esp", b"p");
    let request = |name: &str| InstallRequest {
        instance: root.clone(),
        profile: None,
        archive: folder.path().to_path_buf(),
        name: Some(name.to_owned()),
        dry_run: false,
        answers: None,
        fomod_answers: None,
        on_conflict: nvmod_api::install::OnConflict::Refuse,
        placement: nvmod_api::install::Placement::Top,
        max_extract_bytes: None,
        extract_limits: LimitOverrides::default(),
    };

    // Something left the process-wide request set (a signal handler, another run).
    nvmod_core::cancel::request();

    // A library step that reads the process-wide request, as every caller without a token does, stops.
    assert!(nvmod_core::cancel::step_point("copy").is_err());

    // The job runs under its own token and is not stopped by it.
    let output =
        nvmod_api::install::install(&request("Scoped"), &mut NoProgress, &CancelToken::new())
            .expect("installs")
            .done()
            .expect("not cancelled");
    assert!(matches!(output, InstallOutput::Installed(_)));
    assert!(root.join("mods/Scoped/Scoped.esp").is_file());

    // The scope ended with the job: this thread reads the process-wide request again.
    assert!(nvmod_core::cancel::requested());

    // And the job's own token still stops it.
    let own = CancelToken::new();
    own.cancel();
    assert!(matches!(
        nvmod_api::install::install(&request("Other"), &mut NoProgress, &own),
        Ok(Outcome::Cancelled)
    ));
    assert!(!root.join("mods/Other").exists());
    nvmod_core::cancel::reset();
}
