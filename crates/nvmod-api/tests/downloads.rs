//! The downloads jobs of `nvmod-api`, called in process on a scratch Instance. Archives are built in code by the
//! testkit and `.meta` files are written here; no mod data is used.

use nvmod_api::downloads::{
    Action, ChangeRequest, InstallRequest, ListRequest, ShowRequest, State, change, install, list,
    show,
};
use nvmod_api::install::{InstallOutput as Installed, InstallRequest as PathInstallRequest};
use nvmod_api::{CancelToken, ErrorKind, Event, NoProgress, Outcome};
use nvmod_instance::NvmodInstance;
use nvmod_testkit::{BaseBuilder, TempDir, ZipBuilder, write_file};
use nvmod_testkit::{covers, ids};
use std::fs;
use std::path::PathBuf;

const ARCHIVE: &str = "[Better] Rocks-4242-1-5-1699999999.zip";

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    fn new() -> Self {
        let base = TempDir::new("dlapi-base");
        BaseBuilder::steam().write(base.path());
        let inst = TempDir::new("dlapi-inst");
        let root = inst.path().join("fnv");
        let instance = NvmodInstance::create(&root, base.path()).expect("create the Instance");
        if !instance.profile_dir("Default").is_dir() {
            instance.create_profile("Default").expect("profile");
        }
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n",
        );
        Self { _base: base, inst }
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn downloads(&self) -> PathBuf {
        self.root().join("downloads")
    }

    fn put_archive(dir: &std::path::Path, name: &str) {
        fs::create_dir_all(dir).unwrap();
        ZipBuilder::new()
            .file("Better.esp", b"plugin")
            .file("meshes/rock.nif", b"rock")
            .write(&dir.join(name));
    }
}

fn list_request(s: &Scratch) -> ListRequest {
    ListRequest {
        instance: s.root(),
        downloads: None,
        unmatched: false,
        hash: false,
    }
}

fn install_request(s: &Scratch) -> InstallRequest {
    InstallRequest {
        instance: s.root(),
        downloads: None,
        archive: ARCHIVE.to_owned(),
        profile: None,
        name: None,
        dry_run: false,
        answers: None,
        max_extract_bytes: None,
        extract_limits: nvmod_api::install::LimitOverrides::default(),
    }
}

fn done<T>(outcome: Result<Outcome<T>, nvmod_api::JobError>) -> T {
    outcome.expect("no error").done().expect("not cancelled")
}

#[test]
fn a_missing_default_folder_is_an_empty_library_and_a_missing_named_one_is_refused() {
    let s = Scratch::new();
    let out = done(list(
        &list_request(&s),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert_eq!(out.archives.len(), 0);
    assert_eq!(out.schema_version, 1);

    let mut request = list_request(&s);
    request.downloads = Some(PathBuf::from("elsewhere"));
    let err = list(&request, &mut NoProgress, &CancelToken::new()).unwrap_err();
    assert_eq!(err.kind, ErrorKind::Refused);
    assert_eq!(err.job, "downloads.list");
}

#[test]
fn the_downloads_folder_can_be_named_relative_to_the_instance_or_absolute() {
    let s = Scratch::new();
    Scratch::put_archive(&s.root().join("my dl"), "Rel.zip");
    let abs = TempDir::new("dlapi-abs");
    Scratch::put_archive(abs.path(), "Abs.zip");

    let mut request = list_request(&s);
    request.downloads = Some(PathBuf::from("my dl"));
    let out = done(list(&request, &mut NoProgress, &CancelToken::new()));
    assert_eq!(out.archives.len(), 1);
    assert_eq!(out.archives[0].file, "Rel.zip");

    request.downloads = Some(abs.path().to_path_buf());
    let out = done(list(&request, &mut NoProgress, &CancelToken::new()));
    assert_eq!(out.archives[0].file, "Abs.zip");
}

#[test]
fn installing_from_the_library_equals_installing_the_path_plus_the_meta_update() {
    covers(&[ids::mods::downloads::INSTALL_FROM_LIBRARY]);
    let a = Scratch::new();
    let b = Scratch::new();
    Scratch::put_archive(&a.downloads(), ARCHIVE);
    let work = TempDir::new("dlapi-work");
    Scratch::put_archive(work.path(), ARCHIVE);
    // The library knows more than the path does: the Nexus ids MO2 recorded.
    let meta = b"[General]\r\nmodID=4242\r\nfileID=9\r\ninstalled=false\r\nuninstalled=false\r\n";
    fs::write(a.downloads().join(format!("{ARCHIVE}.meta")), meta).unwrap();

    let mut events: Vec<Event> = Vec::new();
    let library = done(install(
        &install_request(&a),
        &mut |e: &Event| events.push(e.clone()),
        &CancelToken::new(),
    ));
    let by_path = done(nvmod_api::install::install(
        &PathInstallRequest {
            instance: b.root(),
            profile: None,
            archive: work.path().join(ARCHIVE),
            name: None,
            dry_run: false,
            answers: None,
            fomod_answers: None,
            on_conflict: nvmod_api::install::OnConflict::Refuse,
            max_extract_bytes: None,
            extract_limits: nvmod_api::install::LimitOverrides::default(),
        },
        &mut NoProgress,
        &CancelToken::new(),
    ));
    let (Installed::Installed(left), Installed::Installed(right)) = (&library.install, &by_path)
    else {
        panic!("both install");
    };
    assert_eq!(left.r#mod, right.r#mod);
    assert_eq!(left.profile, right.profile);
    assert_eq!(left.files, right.files);
    assert_eq!(left.plugins, right.plugins);
    assert_eq!(left.staged_files, right.staged_files);
    for file in [
        "profiles/Default/modlist.txt",
        "profiles/Default/plugins.txt",
        "mods/[Better] Rocks-4242-1-5-1699999999/meta.ini",
        "mods/[Better] Rocks-4242-1-5-1699999999/Better.esp",
    ] {
        assert_eq!(
            fs::read(a.root().join(file)).unwrap(),
            fs::read(b.root().join(file)).unwrap(),
            "{file}"
        );
    }
    assert!(
        events
            .iter()
            .any(|e| e.label == "downloads.install.updating-meta")
    );

    let update = library.meta.expect("a meta update");
    assert!(update.installed && update.written && update.warning.is_none());
    assert_eq!(
        fs::read(a.downloads().join(format!("{ARCHIVE}.meta"))).unwrap(),
        b"[General]\r\nmodID=4242\r\nfileID=9\r\ninstalled=true\r\nuninstalled=false\r\n"
    );

    // The library now reports it as installed, matched by the Mod's installationFile.
    let out = done(list(
        &list_request(&a),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    let row = &out.archives[0];
    assert_eq!(row.state, State::Installed);
    assert_eq!(row.nexus_mod_id, Some(4242));
    assert_eq!(row.nexus_file_id, Some(9));
    assert_eq!(
        row.matched_mod.as_ref().map(|m| m.name.as_str()),
        Some("[Better] Rocks-4242-1-5-1699999999")
    );
    let meta_ini = fs::read_to_string(
        a.root()
            .join("mods/[Better] Rocks-4242-1-5-1699999999/meta.ini"),
    )
    .unwrap();
    assert!(
        meta_ini.contains(&format!("installationFile={ARCHIVE}")),
        "{meta_ini}"
    );
}

#[test]
fn an_install_without_a_meta_makes_one_and_a_dry_run_writes_nothing() {
    let s = Scratch::new();
    Scratch::put_archive(&s.downloads(), ARCHIVE);
    let mut dry = install_request(&s);
    dry.dry_run = true;
    let out = done(install(&dry, &mut NoProgress, &CancelToken::new()));
    assert!(out.meta.is_none());
    assert!(!s.downloads().join(format!("{ARCHIVE}.meta")).exists());
    assert!(
        !s.root()
            .join("mods/[Better] Rocks-4242-1-5-1699999999")
            .exists()
    );

    let out = done(install(
        &install_request(&s),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert!(out.meta.is_some_and(|m| m.written));
    assert_eq!(
        fs::read(s.downloads().join(format!("{ARCHIVE}.meta"))).unwrap(),
        b"[General]\r\ninstalled=true\r\n"
    );
}

#[test]
fn install_refuses_paths_missing_archives_and_unfinished_downloads() {
    let s = Scratch::new();
    Scratch::put_archive(&s.downloads(), "Half.zip");
    fs::write(
        s.downloads().join("Half.zip.meta"),
        b"[General]\r\npaused=true\r\n",
    )
    .unwrap();
    for name in [
        "../Half.zip",
        "sub/Half.zip",
        "Missing.zip",
        "Half.zip.meta",
    ] {
        let mut request = install_request(&s);
        request.archive = name.to_owned();
        let err = install(&request, &mut NoProgress, &CancelToken::new()).unwrap_err();
        assert_eq!(err.kind, ErrorKind::Refused, "{name}");
    }
    let mut request = install_request(&s);
    request.archive = "Half.zip".to_owned();
    let err = install(&request, &mut NoProgress, &CancelToken::new()).unwrap_err();
    assert_eq!(err.kind, ErrorKind::Refused);
    assert!(err.summary.contains("unfinished"), "{}", err.summary);
    assert!(!s.root().join("mods/Half").exists());
}

#[test]
fn hide_unhide_and_forget_change_only_what_they_say() {
    let s = Scratch::new();
    Scratch::put_archive(&s.downloads(), "A.zip");
    let request = |action, dry_run| ChangeRequest {
        instance: s.root(),
        downloads: None,
        archive: "A.zip".to_owned(),
        action,
        dry_run,
    };

    let out = done(change(
        &request(Action::Hide, true),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert!(out.dry_run);
    assert!(!s.downloads().join("A.zip.meta").exists());

    let out = done(change(
        &request(Action::Hide, false),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert!(out.changed);
    let rows = done(list(
        &list_request(&s),
        &mut NoProgress,
        &CancelToken::new(),
    ))
    .archives;
    assert_eq!(rows[0].state, State::Hidden);

    let out = done(change(
        &request(Action::Hide, false),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert!(!out.changed);
    let out = done(change(
        &request(Action::Unhide, false),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert!(out.changed);
    let rows = done(list(
        &list_request(&s),
        &mut NoProgress,
        &CancelToken::new(),
    ))
    .archives;
    assert_eq!(rows[0].state, State::Uninstalled);

    let out = done(change(
        &request(Action::Forget, false),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    let trashed = out.trashed_to.expect("a trash folder");
    assert!(trashed.starts_with(".nvmod/trash/downloads/"), "{trashed}");
    assert!(!s.downloads().join("A.zip").exists());
    assert!(!s.downloads().join("A.zip.meta").exists());
    assert!(s.root().join(&trashed).join("A.zip").is_file());
    assert!(s.root().join(&trashed).join("A.zip.meta").is_file());
    let left = done(list(
        &list_request(&s),
        &mut NoProgress,
        &CancelToken::new(),
    ));
    assert_eq!(left.archives.len(), 0);
}

#[test]
fn show_hashes_on_request_and_list_reports_progress() {
    let s = Scratch::new();
    write_file(&s.downloads(), "abc.zip", b"abc");
    let request = ShowRequest {
        instance: s.root(),
        downloads: None,
        archive: "abc.zip".to_owned(),
        hash: true,
    };
    let out = done(show(&request, &mut NoProgress, &CancelToken::new()));
    assert_eq!(
        out.archive.sha256.as_deref(),
        Some("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
    );
    assert!(s.root().join(".nvmod/downloads-hashes.json").is_file());

    let mut steps: Vec<(&'static str, Option<u64>, Option<u64>)> = Vec::new();
    let mut hashed = list_request(&s);
    hashed.hash = true;
    let out = done(list(
        &hashed,
        &mut |e: &Event| steps.push((e.step, e.done, e.total)),
        &CancelToken::new(),
    ));
    assert_eq!(
        out.archives[0].md5.as_deref(),
        Some("900150983cd24fb0d6963f7d28e17f72")
    );
    assert!(steps.contains(&("read-downloads", Some(1), Some(1))));
    assert!(steps.contains(&("hash", Some(1), Some(1))));
}

#[test]
fn a_cancelled_job_is_a_result_and_changes_nothing() {
    let s = Scratch::new();
    Scratch::put_archive(&s.downloads(), ARCHIVE);
    let cancel = CancelToken::new();
    cancel.cancel();
    assert!(matches!(
        list(&list_request(&s), &mut NoProgress, &cancel),
        Ok(Outcome::Cancelled)
    ));
    assert!(matches!(
        install(&install_request(&s), &mut NoProgress, &cancel),
        Ok(Outcome::Cancelled)
    ));
    assert!(!s.downloads().join(format!("{ARCHIVE}.meta")).exists());
}
