//! The tree job, called in process on a synthetic nvmod Instance: Mods are written as files, in code. Nothing is
//! read from a game.

use nvmod_api::tree::{TreeOutput, TreeRequest, show};
use nvmod_api::{CancelToken, ErrorKind, Event, JobError, NoProgress, Outcome};
use nvmod_instance::NvmodInstance;
use nvmod_testkit::{BaseBuilder, PeBuilder, TempDir, snapshot, write_file};
use nvmod_testkit::{covers, ids};
use std::path::PathBuf;

/// The job name of every refusal of this job.
const SHOW: &str = "tree.show";

/// An nvmod Instance with a Default profile whose modlist names the given Mods, highest priority first, and whose
/// Mods hold the given files. Two Mods that hold the same path contest it.
struct Scratch {
    base: TempDir,
    inst: TempDir,
}

impl Scratch {
    fn new(modlist: &str, mods: &[(&str, &[&str])]) -> Self {
        let base = TempDir::new("tree-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
        write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
        write_file(base.path(), "Data/Base_Only.txt", b"base only");
        let inst = TempDir::new("tree-inst");
        let s = Self { base, inst };
        let instance =
            NvmodInstance::create(&s.root(), s.base.path()).expect("create the Instance");
        instance
            .create_profile("Default")
            .expect("create the profile");
        s.modlist(modlist);
        for (name, files) in mods {
            for file in *files {
                write_file(
                    &s.root(),
                    &format!("mods/{name}/{file}"),
                    format!("{name}:{file}").as_bytes(),
                );
            }
        }
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn modlist(&self, lines: &str) {
        write_file(
            &self.root(),
            "profiles/Default/modlist.txt",
            format!("# This file was automatically generated by Mod Organizer.\r\n{lines}")
                .as_bytes(),
        );
    }

    fn request(&self) -> TreeRequest {
        TreeRequest {
            instance: self.root(),
            profile: None,
            path: None,
        }
    }
}

/// Three Mods, A the highest priority, that contest `meshes/rock.nif`, `textures/a.dds` and `sound/x.wav`.
fn contested() -> Scratch {
    Scratch::new(
        "+A\r\n+B\r\n+C\r\n",
        &[
            ("A", &["meshes/rock.nif", "textures/a.dds", "scripts/s.pex"]),
            ("B", &["Meshes/Rock.nif", "textures/A.dds", "sound/x.wav"]),
            ("C", &["textures/a.dds", "c_only.txt", "sound/x.wav"]),
        ],
    )
}

fn run(request: &TreeRequest) -> Result<Outcome<TreeOutput>, JobError> {
    show(request, &mut NoProgress, &CancelToken::new())
}

fn done(request: &TreeRequest) -> TreeOutput {
    run(request)
        .expect("the tree is read")
        .done()
        .expect("not cancelled")
}

fn refused(request: &TreeRequest) -> JobError {
    run(request).expect_err("refused")
}

fn provider(out: &TreeOutput, path: &str) -> String {
    out.tree
        .entries
        .iter()
        .find(|e| e.path == path)
        .unwrap_or_else(|| panic!("{path} is in the tree"))
        .provider
        .clone()
}

#[test]
fn every_path_is_listed_once_with_the_layer_that_provides_it() {
    covers(&[ids::staging::tree::TREE_LISTING]);
    let s = contested();
    let out = done(&s.request());
    assert_eq!(out.tree.profile, "Default");
    let paths: Vec<&str> = out.tree.entries.iter().map(|e| e.path.as_str()).collect();
    let mut sorted = paths.clone();
    sorted.sort_unstable();
    assert_eq!(paths, sorted, "in path order");
    let unique: std::collections::BTreeSet<_> = paths.iter().collect();
    assert_eq!(unique.len(), paths.len(), "every path once");
    assert_eq!(provider(&out, "meshes/rock.nif"), "A");
    assert_eq!(provider(&out, "textures/a.dds"), "A");
    assert_eq!(provider(&out, "sound/x.wav"), "B");
    assert_eq!(provider(&out, "c_only.txt"), "C");
    assert_eq!(provider(&out, "base_only.txt"), "the base copy");
}

#[test]
fn an_overwrite_folder_sits_above_every_mod() {
    covers(&[ids::staging::tree::OVERWRITE_ON_TOP]);
    let s = contested();
    write_file(&s.root(), "overwrite/textures/o.dds", b"o");
    let out = done(&s.request());
    assert_eq!(provider(&out, "textures/o.dds"), "Overwrite");
    assert_eq!(provider(&out, "textures/a.dds"), "A");
}

#[test]
fn a_path_filter_keeps_the_paths_at_or_under_the_folder_without_case() {
    let s = contested();
    let mut request = s.request();
    request.path = Some("Textures".to_owned());
    let out = done(&request);
    assert_ne!(out.tree.entries.len(), 0);
    assert!(
        out.tree
            .entries
            .iter()
            .all(|e| e.path.starts_with("textures/"))
    );
    request.path = Some("textures/a.dds".to_owned());
    let file = done(&request);
    assert_eq!(file.tree.entries.len(), 1);
    assert_eq!(file.tree.entries[0].path, "textures/a.dds");
}

#[test]
fn a_path_that_matches_nothing_is_a_result_with_no_entries() {
    let s = contested();
    let mut request = s.request();
    request.path = Some("nowhere".to_owned());
    let out = done(&request);
    assert_eq!(out.tree.entries.len(), 0);
}

#[test]
fn a_hidden_file_is_not_a_provider_and_the_next_layer_wins() {
    covers(&[ids::staging::tree::HIDDEN_FILES]);
    let s = contested();
    // A hides its copy of the rock; B's copy, the next layer, now provides it.
    write_file(&s.root(), "mods/A/meshes/rock.nif.mohidden", b"hidden");
    std::fs::remove_file(s.root().join("mods/A/meshes/rock.nif")).unwrap();
    let out = done(&s.request());
    assert_eq!(provider(&out, "meshes/rock.nif"), "B");
    assert!(
        out.tree
            .entries
            .iter()
            .all(|e| !e.path.ends_with(".mohidden"))
    );
}

#[test]
fn a_folder_that_is_not_an_nvmod_instance_is_a_refusal() {
    let dir = TempDir::new("tree-empty");
    let mut request = contested().request();
    request.instance = dir.path().to_path_buf();
    let error = refused(&request);
    assert_eq!(error.kind, ErrorKind::Refused);
    assert_eq!(error.job, SHOW);
    assert!(
        error.summary.contains("is not an nvmod Instance"),
        "{error}"
    );
}

#[test]
fn an_instance_file_newer_than_this_nvmod_reads_is_a_refusal() {
    let s = contested();
    let file = s.root().join("nvmod-instance.json");
    let text = std::fs::read_to_string(&file).unwrap();
    let newer = text.replace("\"schema_version\": 2", "\"schema_version\": 99");
    assert_ne!(newer, text, "the schema is written as 2");
    std::fs::write(&file, newer).unwrap();
    let error = refused(&s.request());
    assert_eq!(error.kind, ErrorKind::Refused);
    assert!(
        error.summary.contains("newer than this nvmod reads"),
        "{error}"
    );
}

