#[test]
fn a_base_copy_without_a_data_folder_is_a_refusal() {
    let s = contested();
    // The Instance names its base copy; take the Data folder away from that copy.
    std::fs::remove_dir_all(s.base.path().join("Data"))
        .expect("remove the base copy's Data folder");
    let error = refused(&s.request());
    assert_eq!(error.kind, ErrorKind::Refused);
    assert!(error.summary.contains("has no Data folder"), "{error}");
}

#[test]
fn a_refusal_copies_as_text_without_a_command_line() {
    covers(&[ids::api::jobs::COPYABLE_REFUSALS]);
    let dir = TempDir::new("tree-copy");
    let mut request = contested().request();
    request.instance = dir.path().to_path_buf();
    let text = refused(&request).copy_text();
    assert!(text.contains("job: tree.show"), "{text}");
    assert!(text.contains("error: refused"), "{text}");
    assert!(
        !text.contains("nvmod tree") && !text.contains("--instance"),
        "{text}"
    );
}

#[test]
fn a_tree_whose_cancel_is_set_before_the_call_stops_at_once_and_changes_nothing() {
    let s = contested();
    let before = snapshot(&s.root());
    let token = CancelToken::new();
    token.cancel();
    let mut steps = 0;
    let mut count = |_: &Event| steps += 1;
    let out = show(&s.request(), &mut count, &token).expect("not an error");
    assert!(matches!(out, Outcome::Cancelled));
    assert_eq!(steps, 0);
    assert_eq!(snapshot(&s.root()), before);
}

#[test]
fn a_tree_cancelled_from_its_progress_stops_before_the_work_and_changes_nothing() {
    let s = contested();
    let before = snapshot(&s.root());
    let token = CancelToken::new();
    let stopper = token.clone();
    let mut seen = Vec::new();
    let mut on_event = |event: &Event| {
        seen.push(event.step);
        if event.step == "read-layers" {
            stopper.cancel();
        }
    };
    let out = show(&s.request(), &mut on_event, &token).expect("not an error");
    assert!(matches!(out, Outcome::Cancelled));
    assert_eq!(seen, ["open-instance", "read-layers"]);
    assert_eq!(snapshot(&s.root()), before);
}

#[test]
fn a_tree_request_round_trips_through_json() {
    let mut request = contested().request();
    request.profile = Some("Default".to_owned());
    request.path = Some("textures".to_owned());
    let text = serde_json::to_string(&request).expect("serialises");
    let back: TreeRequest = serde_json::from_str(&text).expect("parses");
    assert_eq!(back, request);
    let minimal: TreeRequest =
        serde_json::from_str(r#"{"instance": "/games/fnv"}"#).expect("parses");
    assert_eq!(minimal.profile, None);
    assert_eq!(minimal.path, None);
}
