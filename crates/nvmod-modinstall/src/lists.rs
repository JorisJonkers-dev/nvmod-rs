//! The three profile files, edited together: `modlist.txt` (MO2's format, first line highest priority, CRLF),
//! `plugins.txt` (active plugins, Windows-1252) and `loadorder.txt` (all plugins, UTF-8). Existing lines are kept
//! as they are; only the new Mod and its plugins are added.

use nvmod_formats::Modlist;
use nvmod_formats::text::{decode, encode_windows_1252, lines};

const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

fn is_master(name: &str) -> bool {
    std::path::Path::new(name)
        .extension()
        .is_some_and(|e| e.eq_ignore_ascii_case("esm"))
}

/// The text of `modlist.txt` with `+name` as its first Mod (just under the comment header).
///
/// # Errors
/// The Mod is already listed.
pub fn add_to_modlist(old: Option<&[u8]>, name: &str) -> Result<Vec<u8>, String> {
    let text = old.map_or_default(decode);
    if Modlist::parse(&text)
        .entries
        .iter()
        .any(|e| e.name.eq_ignore_ascii_case(name))
    {
        return Err(format!("`{name}` is already in modlist.txt"));
    }
    let mut all: Vec<&str> = lines(&text).filter(|l| !l.trim().is_empty()).collect();
    let at = all
        .iter()
        .take_while(|l| l.trim_start().starts_with('#'))
        .count();
    let entry = format!("+{name}");
    if old.is_none() {
        all.push(HEADER);
        all.push(&entry);
    } else {
        all.insert(at, &entry);
    }
    Ok(join(&all).into_bytes())
}

fn join(lines: &[&str]) -> String {
    let mut out = String::new();
    for line in lines {
        out.push_str(line);
        out.push_str("\r\n");
    }
    out
}

fn name_of(line: &str) -> &str {
    line.trim().trim_start_matches('*').trim()
}

fn position(list: &[String], name: &str) -> Option<usize> {
    list.iter()
        .position(|l| name_of(l).eq_ignore_ascii_case(name))
}

/// The new contents of `plugins.txt` and `loadorder.txt`.
pub type NewLists = (Vec<u8>, Vec<u8>);

/// The new `(plugins.txt, loadorder.txt)` after activating `new` (names not yet listed, in the order to add).
///
/// Masters go after the last master of `loadorder.txt`, other plugins at its end; `plugins.txt` gets each new name
/// right after the nearest earlier plugin it already lists. `None` when nothing needs to change.
///
/// # Errors
/// A name that `plugins.txt` would hold has no place in Windows-1252.
pub fn add_plugins(
    old_plugins: Option<&[u8]>,
    old_order: Option<&[u8]>,
    new: &[String],
) -> Result<Option<NewLists>, String> {
    let plugins_in = old_plugins.map(decode);
    let order_text = old_order.map(decode);
    let read = |t: &Option<String>| -> Vec<String> {
        t.as_deref().map_or_default(|t| {
            lines(t)
                .map(str::trim)
                .filter(|l| !l.is_empty())
                .map(str::to_owned)
                .collect()
        })
    };
    let mut plugins = read(&plugins_in);
    let mut order = if order_text.is_some() {
        read(&order_text)
    } else {
        plugins.clone()
    };
    let mut changed = old_plugins.is_none() || old_order.is_none();
    for name in new {
        if position(&order, name).is_some() || position(&plugins, name).is_some() {
            continue;
        }
        changed = true;
        let first = order.iter().take_while(|l| l.starts_with('#')).count();
        let at = if is_master(name) {
            order
                .iter()
                .rposition(|l| !l.starts_with('#') && is_master(name_of(l)))
                .map_or(first, |i| i + 1)
        } else {
            order.len()
        };
        order.insert(at, name.clone());
        let after = order[..at]
            .iter()
            .rev()
            .find_map(|l| position(&plugins, name_of(l)));
        let slot = after.map_or_else(
            || plugins.iter().take_while(|l| l.starts_with('#')).count(),
            |i| i + 1,
        );
        plugins.insert(slot, name.clone());
    }
    if !changed {
        return Ok(None);
    }
    for list in [&mut plugins, &mut order] {
        if !list.first().is_some_and(|l| l.starts_with('#')) {
            list.insert(0, HEADER.to_owned());
        }
    }
    let active_text = join(&plugins.iter().map(String::as_str).collect::<Vec<_>>());
    let order_text = join(&order.iter().map(String::as_str).collect::<Vec<_>>());
    let encoded = encode_windows_1252(&active_text)
        .ok_or("a plugin name cannot be written to plugins.txt in the Windows code page")?;
    Ok(Some((encoded, order_text.into_bytes())))
}

/// The new `(plugins.txt, loadorder.txt)` after listing `new` as inactive plugins: each name not yet in either file
/// goes into `loadorder.txt` only (masters after its last master, other plugins at its end); `plugins.txt` keeps its
/// lines. `None` when every name is listed already.
///
/// # Errors
/// A name that `plugins.txt` would hold has no place in Windows-1252.
pub fn add_inactive_plugins(
    old_plugins: Option<&[u8]>,
    old_order: Option<&[u8]>,
    new: &[String],
) -> Result<Option<NewLists>, String> {
    let read = |bytes: Option<&[u8]>| -> Vec<String> {
        bytes.map_or_default(|b| {
            lines(&decode(b))
                .map(str::trim)
                .filter(|l| !l.is_empty())
                .map(str::to_owned)
                .collect()
        })
    };
    let plugins = read(old_plugins);
    let mut order = if old_order.is_some() {
        read(old_order)
    } else {
        plugins.clone()
    };
    let mut changed = false;
    for name in new {
        if position(&order, name).is_some() || position(&plugins, name).is_some() {
            continue;
        }
        changed = true;
        let first = order.iter().take_while(|l| l.starts_with('#')).count();
        let at = if is_master(name) {
            order
                .iter()
                .rposition(|l| !l.starts_with('#') && is_master(name_of(l)))
                .map_or(first, |i| i + 1)
        } else {
            order.len()
        };
        order.insert(at, name.clone());
    }
    if !changed {
        return Ok(None);
    }
    let with_header = |mut list: Vec<String>| -> Vec<String> {
        if !list.first().is_some_and(|l| l.starts_with('#')) {
            list.insert(0, HEADER.to_owned());
        }
        list
    };
    let plugins_text = join(
        &with_header(plugins)
            .iter()
            .map(String::as_str)
            .collect::<Vec<_>>(),
    );
    let order_text = join(
        &with_header(order)
            .iter()
            .map(String::as_str)
            .collect::<Vec<_>>(),
    );
    let encoded = encode_windows_1252(&plugins_text)
        .ok_or("a plugin name cannot be written to plugins.txt in the Windows code page")?;
    Ok(Some((encoded, order_text.into_bytes())))
}

/// The new `(plugins.txt, loadorder.txt)` without the lines for `names` (ignoring case); every other line, comment
/// lines included, stays. `None` when neither file lists any of them.
///
/// # Errors
/// A name that `plugins.txt` holds has no place in Windows-1252.
pub fn remove_plugins(
    old_plugins: Option<&[u8]>,
    old_order: Option<&[u8]>,
    names: &[String],
) -> Result<Option<NewLists>, String> {
    let strip = |bytes: Option<&[u8]>| -> Option<(Vec<String>, bool)> {
        let text = decode(bytes?);
        let all: Vec<String> = lines(&text)
            .map(str::trim)
            .filter(|l| !l.is_empty())
            .map(str::to_owned)
            .collect();
        let kept: Vec<String> = all
            .iter()
            .filter(|l| {
                l.starts_with('#') || !names.iter().any(|n| name_of(l).eq_ignore_ascii_case(n))
            })
            .cloned()
            .collect();
        let changed = kept.len() != all.len();
        Some((kept, changed))
    };
    let plugins = strip(old_plugins);
    let order = strip(old_order);
    if !plugins.as_ref().is_some_and(|p| p.1) && !order.as_ref().is_some_and(|o| o.1) {
        return Ok(None);
    }
    let render = |list: Option<(Vec<String>, bool)>, old: Option<&[u8]>| -> String {
        list.map_or_else(
            || old.map_or_default(decode),
            |(l, _)| join(&l.iter().map(String::as_str).collect::<Vec<_>>()),
        )
    };
    let plugins_text = render(plugins, old_plugins);
    let order_text = render(order, old_order);
    let encoded = encode_windows_1252(&plugins_text)
        .ok_or("a plugin name cannot be written to plugins.txt in the Windows code page")?;
    Ok(Some((encoded, order_text.into_bytes())))
}

/// The new `plugins.txt` without the lines for `names` (ignoring case): the plugins stop being active but stay in
/// `loadorder.txt`, which remembers their place. Every other line and comment stays. `None` when `plugins.txt` lists
/// none of them.
///
/// # Errors
/// A name that `plugins.txt` holds has no place in Windows-1252.
pub fn deactivate_plugins(
    old_plugins: Option<&[u8]>,
    names: &[String],
) -> Result<Option<Vec<u8>>, String> {
    let Some(bytes) = old_plugins else {
        return Ok(None);
    };
    let text = decode(bytes);
    let all: Vec<String> = lines(&text)
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .map(str::to_owned)
        .collect();
    let kept: Vec<&str> = all
        .iter()
        .map(String::as_str)
        .filter(|l| l.starts_with('#') || !names.iter().any(|n| name_of(l).eq_ignore_ascii_case(n)))
        .collect();
    if kept.len() == all.len() {
        return Ok(None);
    }
    encode_windows_1252(&join(&kept)).map(Some).ok_or_else(|| {
        "a plugin name cannot be written to plugins.txt in the Windows code page".to_owned()
    })
}

/// Whether `name` is listed in `list` (a parsed plugin list), ignoring case.
#[must_use]
pub fn lists(list: &[String], name: &str) -> bool {
    list.iter().any(|l| l.eq_ignore_ascii_case(name))
}

#[cfg(test)]
mod tests {
    #[test]
    fn deactivating_drops_only_the_active_lines_of_the_named_plugins() {
        let old = b"# list\r\n*A.esm\r\n*b.esp\r\n*C.esp\r\n";
        let new = deactivate_plugins(Some(old), &["B.ESP".to_owned()])
            .unwrap()
            .unwrap();
        assert_eq!(new, b"# list\r\n*A.esm\r\n*C.esp\r\n");
        assert_eq!(
            deactivate_plugins(Some(old), &["Z.esp".to_owned()]),
            Ok(None)
        );
        assert_eq!(deactivate_plugins(None, &["A.esm".to_owned()]), Ok(None));
    }

    use super::*;

    fn text(bytes: &[u8]) -> Vec<String> {
        lines(&decode(bytes))
            .filter(|l| !l.is_empty())
            .map(str::to_owned)
            .collect()
    }

    #[test]
    fn a_new_mod_goes_first_under_the_header() {
        let out = add_to_modlist(Some(b"# h\r\n+A\r\n-B_separator\r\n"), "N").unwrap();
        assert_eq!(text(&out), ["# h", "+N", "+A", "-B_separator"]);
        assert!(add_to_modlist(Some(b"# h\r\n-n\r\n"), "N").is_err());
        assert_eq!(text(&add_to_modlist(None, "N").unwrap())[1], "+N");
    }

    #[test]
    fn masters_and_plugins_are_placed_and_nothing_changes_when_all_are_listed() {
        let plugins = b"FalloutNV.esm\r\nA.esp\r\n";
        let order = b"FalloutNV.esm\r\nA.esp\r\nB.esp\r\n";
        let (p, o) = add_plugins(
            Some(plugins),
            Some(order),
            &["M.esm".into(), "C.esp".into()],
        )
        .unwrap()
        .unwrap();
        assert_eq!(
            text(&o)[1..],
            ["FalloutNV.esm", "M.esm", "A.esp", "B.esp", "C.esp"]
        );
        assert_eq!(text(&p)[1..], ["FalloutNV.esm", "M.esm", "A.esp", "C.esp"]);
        assert!(
            add_plugins(Some(plugins), Some(order), &["a.esp".into()])
                .unwrap()
                .is_none()
        );
    }

    #[test]
    fn inactive_plugins_go_to_the_load_order_only() {
        let plugins = b"FalloutNV.esm\r\nA.esp\r\n";
        let order = b"FalloutNV.esm\r\nA.esp\r\nB.esp\r\n";
        let (p, o) = add_inactive_plugins(
            Some(plugins),
            Some(order),
            &["M.esm".into(), "C.esp".into(), "a.esp".into()],
        )
        .unwrap()
        .unwrap();
        assert_eq!(
            text(&o)[1..],
            ["FalloutNV.esm", "M.esm", "A.esp", "B.esp", "C.esp"]
        );
        assert_eq!(text(&p)[1..], ["FalloutNV.esm", "A.esp"]);
        assert!(
            add_inactive_plugins(Some(plugins), Some(order), &["b.esp".into()])
                .unwrap()
                .is_none()
        );
    }

    #[test]
    fn names_the_code_page_lacks_are_refused() {
        assert!(add_plugins(None, None, &["\u{6f22}.esp".into()]).is_err());
    }
}
