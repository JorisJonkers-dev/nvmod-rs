//! `stage_without`: the Staging tree of a profile without some of its Mods, built into another folder, on a scratch
//! Instance whose base copy, Mods and lists are written as files in code.

use nvmod_instance::NvmodInstance;
use nvmod_stage::{Options, StageError, stage, stage_without};
use nvmod_testkit::{BaseBuilder, TempDir, write_file};
use std::fs;
use std::path::Path;

/// A base copy with one master, and an Instance whose profile `Default` enables `Far` (above) and `Rocks`. `Far`
/// ships a plugin and a mesh that `Rocks` also ships; `Rocks` ships a mesh of its own.
fn scratch() -> (TempDir, TempDir, NvmodInstance) {
    let base = TempDir::new("without-base");
    BaseBuilder::steam().write(base.path());
    write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
    let dir = TempDir::new("without-inst");
    let root = dir.path().join("fnv");
    let instance = NvmodInstance::create(&root, base.path()).expect("create the Instance");
    let w = |p: &str, b: &[u8]| write_file(&root, p, b);
    w("mods/Far/Far.esp", b"far plugin");
    w("mods/Far/meshes/rock.nif", b"far rock");
    w("mods/Rocks/Meshes/Rock.nif", b"rocks rock");
    w("mods/Rocks/meshes/pebble.nif", b"pebble");
    w(
        "profiles/Default/modlist.txt",
        b"# This file was automatically generated by Mod Organizer.\r\n+Far\r\n+Rocks\r\n",
    );
    w(
        "profiles/Default/plugins.txt",
        b"FalloutNV.esm\r\nFar.esp\r\n",
    );
    w(
        "profiles/Default/loadorder.txt",
        b"FalloutNV.esm\r\nFar.esp\r\n",
    );
    (base, dir, instance)
}

fn read(p: &Path) -> Vec<u8> {
    fs::read(p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

#[test]
fn a_tree_without_a_mod_has_the_next_providers_files_and_not_its_plugin() {
    let (_base, dir, instance) = scratch();
    let dest = dir.path().join("pictures/without-far");
    let report = stage_without(
        &instance,
        "Default",
        &["far".to_owned()],
        &dest,
        Options::default(),
    )
    .unwrap();
    assert_eq!(report.left_out, ["Far"], "named as modlist.txt spells it");
    assert_eq!(report.tree, dest.join("data"));
    assert_eq!(read(&dest.join("data/meshes/rock.nif")), b"rocks rock");
    assert_eq!(read(&dest.join("data/meshes/pebble.nif")), b"pebble");
    assert!(!dest.join("data/far.esp").exists());
    assert_eq!(report.plugins, ["FalloutNV.esm"], "{report:?}");
    // The same call with nothing left out gives the whole profile.
    let all = stage_without(
        &instance,
        "Default",
        &[],
        &dir.path().join("pictures/all"),
        Options::default(),
    )
    .unwrap();
    assert_eq!(all.plugins, ["FalloutNV.esm", "Far.esp"]);
    assert_eq!(
        read(&dir.path().join("pictures/all/data/meshes/rock.nif")),
        b"far rock"
    );
}

#[test]
fn the_profile_and_its_own_staging_tree_are_left_as_they_are() {
    let (_base, dir, instance) = scratch();
    stage(&instance, "Default", Options::default()).unwrap();
    let own = instance.staging_dir("Default");
    let lists = |p: &str| read(&instance.profile_dir("Default").join(p));
    let before = (
        read(&own.join("data/meshes/rock.nif")),
        lists("modlist.txt"),
        lists("plugins.txt"),
    );
    stage_without(
        &instance,
        "Default",
        &["Far".to_owned()],
        &dir.path().join("elsewhere"),
        Options::default(),
    )
    .unwrap();
    let after = (
        read(&own.join("data/meshes/rock.nif")),
        lists("modlist.txt"),
        lists("plugins.txt"),
    );
    assert_eq!(before, after);
    assert!(own.join("data/far.esp").is_file());
}

#[test]
fn it_refuses_a_mod_the_profile_does_not_enable_and_a_folder_of_the_instance() {
    let (_base, dir, instance) = scratch();
    let refused = |without: &[&str], dest: &Path| {
        let names: Vec<String> = without.iter().map(|s| (*s).to_owned()).collect();
        match stage_without(&instance, "Default", &names, dest, Options::default()) {
            Err(StageError::Refused(why)) => why,
            other => panic!("expected a refusal, got {other:?}"),
        }
    };
    let why = refused(&["Nope"], &dir.path().join("x"));
    assert!(why.contains("Nope"), "{why}");
    let own = instance.staging_dir("Default");
    assert!(refused(&["Far"], &own).contains("Staging trees"));
    assert!(refused(&["Far"], &own.join("data")).contains("Staging trees"));
    assert!(refused(&["Far"], &instance.profile_dir("Default")).contains("profiles"));
    assert!(refused(&["Far"], &instance.root.join("overwrite/x")).contains("Overwrite"));
    assert!(refused(&["Far"], &instance.root.join("mods/Rocks/x")).contains("mods"));
    assert!(refused(&["Far"], dir.path()).contains("would be replaced whole"));
    assert!(refused(&["Far"], &instance.root).contains("would be replaced whole"));
    assert!(
        instance.root.join("mods/Far/Far.esp").is_file(),
        "nothing removed"
    );
    assert!(
        !dir.path().join("x").exists(),
        "nothing written on a refusal"
    );
}

#[test]
fn a_second_build_replaces_the_tree_whole() {
    let (_base, dir, instance) = scratch();
    let dest = dir.path().join("again");
    stage_without(&instance, "Default", &[], &dest, Options::default()).unwrap();
    assert!(dest.join("data/far.esp").is_file());
    stage_without(
        &instance,
        "Default",
        &["Far".to_owned()],
        &dest,
        Options::default(),
    )
    .unwrap();
    assert!(
        !dest.join("data/far.esp").exists(),
        "no file of the last tree is left"
    );
    assert!(!dir.path().join("again.nvmod-partial").exists());
}

#[test]
fn mods_that_share_a_folder_in_another_case_meet_in_one_folder_and_hidden_files_stay_out() {
    let (_base, dir, instance) = scratch();
    let root = instance.root.clone();
    let w = |p: &str, b: &[u8]| write_file(&root, p, b);
    w("mods/Rocks/NVSE/Plugins/a.dll", b"a");
    w("mods/Far/nvse/plugins/b.dll", b"b");
    w("mods/Far/nvse/plugins/c.dll.mohidden", b"hidden");
    let dest = dir.path().join("shared");
    stage_without(&instance, "Default", &[], &dest, Options::default()).unwrap();
    let plugins = dest.join("data/nvse/plugins");
    assert_eq!(read(&plugins.join("a.dll")), b"a");
    assert_eq!(read(&plugins.join("b.dll")), b"b");
    let names: Vec<String> = fs::read_dir(&plugins)
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    assert!(!names.iter().any(|n| n.starts_with("c.dll")), "{names:?}");
}

#[test]
fn a_folder_whose_name_ends_in_partial_is_built_like_any_other() {
    let (_base, dir, instance) = scratch();
    let dest = dir.path().join("trees.partial");
    stage_without(&instance, "Default", &[], &dest, Options::default()).unwrap();
    let report = stage_without(
        &instance,
        "Default",
        &["Far".to_owned()],
        &dest,
        Options::default(),
    )
    .unwrap();
    assert_eq!(read(&report.tree.join("meshes/rock.nif")), b"rocks rock");
}
