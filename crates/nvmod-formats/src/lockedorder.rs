//! `lockedorder.txt`: MO2's list of plugins pinned to a position. A comment header, then `<plugin name>|<priority>`
//! per line, UTF-8, CRLF when written. The priority is a non-negative integer, the 0-based position the plugin
//! is held at. Entries for plugins that are not installed are kept.

/// The header written when the file has none.
pub const HEADER: &str = "# This file was automatically generated by Mod Organizer.";

/// One locked plugin.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Locked {
    /// The plugin file name as the file spells it.
    pub name: String,
    /// The 0-based position it is held at.
    pub priority: u32,
}

/// The parsed file.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct LockedOrder {
    /// Comment lines, kept in order.
    comments: Vec<String>,
    /// The locks, in file order.
    pub entries: Vec<Locked>,
}

impl LockedOrder {
    /// Read the file's bytes (UTF-8, with or without a byte order mark).
    ///
    /// # Errors
    /// A reason naming the line, for bytes that are not UTF-8 or a line that is not `name|priority`. A file is
    /// refused rather than read loosely, so no lock is dropped by the next write.
    pub fn parse(bytes: &[u8]) -> Result<LockedOrder, String> {
        let bytes = bytes.strip_prefix(&[0xEF, 0xBB, 0xBF]).unwrap_or(bytes);
        let text =
            std::str::from_utf8(bytes).map_err(|e| format!("lockedorder.txt is not UTF-8: {e}"))?;
        let mut out = LockedOrder::default();
        for (index, raw) in text.split('\n').enumerate() {
            let line = raw.trim();
            if line.is_empty() {
                continue;
            }
            if line.starts_with('#') {
                out.comments.push(line.to_owned());
                continue;
            }
            let bad = || {
                format!(
                    "lockedorder.txt line {}: `{line}` is not `name|priority`",
                    index + 1
                )
            };
            let (name, priority) = line.rsplit_once('|').ok_or_else(bad)?;
            let priority: u32 = priority.trim().parse().map_err(|_| bad())?;
            let name = name.trim();
            if name.is_empty() {
                return Err(bad());
            }
            out.set(name, priority);
        }
        Ok(out)
    }

    /// The priority of `name` (compared without case).
    #[must_use]
    pub fn get(&self, name: &str) -> Option<u32> {
        self.entries
            .iter()
            .find(|e| e.name.eq_ignore_ascii_case(name))
            .map(|e| e.priority)
    }

    /// Lock `name` at `priority`, replacing an earlier lock of it.
    pub fn set(&mut self, name: &str, priority: u32) {
        match self
            .entries
            .iter_mut()
            .find(|e| e.name.eq_ignore_ascii_case(name))
        {
            Some(e) => e.priority = priority,
            None => self.entries.push(Locked {
                name: name.to_owned(),
                priority,
            }),
        }
    }

    /// Drop the lock of `name`; true when there was one.
    pub fn remove(&mut self, name: &str) -> bool {
        let before = self.entries.len();
        self.entries.retain(|e| !e.name.eq_ignore_ascii_case(name));
        self.entries.len() != before
    }

    /// The file's bytes: the comment lines (or the default header), then every lock, CRLF.
    #[must_use]
    pub fn render(&self) -> Vec<u8> {
        let mut out = String::new();
        if self.comments.is_empty() {
            out.push_str(HEADER);
            out.push_str("\r\n");
        }
        for comment in &self.comments {
            out.push_str(comment);
            out.push_str("\r\n");
        }
        for e in &self.entries {
            out.push_str(&e.name);
            out.push('|');
            out.push_str(&e.priority.to_string());
            out.push_str("\r\n");
        }
        out.into_bytes()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use nvmod_testkit::{covers, ids};

    #[test]
    fn a_file_round_trips_with_its_header_and_crlf() {
        covers(&[ids::formats::files::LOCKED_ORDER]);
        let bytes = b"# header\r\nB.esp|3\r\nA.esm|0\r\n";
        let parsed = LockedOrder::parse(bytes).unwrap();
        assert_eq!(parsed.get("a.ESM"), Some(0));
        assert_eq!(parsed.render(), bytes);
    }

    #[test]
    fn a_missing_header_is_added_and_a_bom_is_skipped() {
        let parsed = LockedOrder::parse(b"\xEF\xBB\xBFA.esp|1\n").unwrap();
        assert_eq!(
            parsed.render(),
            format!("{HEADER}\r\nA.esp|1\r\n").into_bytes()
        );
    }

    #[test]
    fn set_replaces_and_remove_reports() {
        let mut l = LockedOrder::default();
        l.set("A.esp", 2);
        l.set("a.ESP", 5);
        assert_eq!(l.entries.len(), 1);
        assert_eq!(l.get("A.esp"), Some(5));
        assert!(l.remove("A.ESP") && !l.remove("A.esp"));
    }

    #[test]
    fn bad_lines_and_non_utf8_are_refused() {
        covers(&[ids::formats::files::LOCKED_ORDER]);
        assert!(
            LockedOrder::parse(b"A.esp\r\n")
                .unwrap_err()
                .contains("line 1")
        );
        assert!(LockedOrder::parse(b"A.esp|-1\r\n").is_err());
        assert!(LockedOrder::parse(b"|3\r\n").is_err());
        assert!(
            LockedOrder::parse(b"Caf\xE9.esp|1\r\n")
                .unwrap_err()
                .contains("UTF-8")
        );
    }

    #[test]
    fn a_name_that_holds_a_bar_keeps_it() {
        let l = LockedOrder::parse("a|b.esp|4\r\n".as_bytes()).unwrap();
        assert_eq!(l.entries[0].name, "a|b.esp");
    }
}
