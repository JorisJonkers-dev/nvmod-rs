//! `modlist.txt`: the mods of a profile in priority order. The first line is the highest priority and wins a file
//! conflict (MO2 research, section 2.4).

use std::collections::HashSet;

/// Whether the mod takes part in the merged view.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModState {
    /// `+`, or no prefix.
    Enabled,
    /// `-`.
    Disabled,
    /// `*`: an unmanaged entry such as a DLC. It has no folder in `mods/`.
    Foreign,
}

/// A real mod or a separator.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EntryKind {
    /// A mod folder.
    Mod,
    /// A named group (`<label>_separator`), which holds no files.
    Separator,
}

/// One line of `modlist.txt`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ModlistEntry {
    /// The folder name under `mods/` (case sensitive).
    pub name: String,
    /// Enabled, disabled or foreign.
    pub state: ModState,
    /// Mod or separator.
    pub kind: EntryKind,
}

/// The parsed file, entries in priority order, highest first.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Modlist {
    /// Entries, highest priority first. A repeated name keeps its first position.
    pub entries: Vec<ModlistEntry>,
}

impl Modlist {
    /// Parse the text of a `modlist.txt`: names are trimmed, blank and `#` lines are skipped, the first
    /// occurrence of a name wins.
    #[must_use]
    pub fn parse(text: &str) -> Modlist {
        let mut seen = HashSet::new();
        let mut entries = Vec::new();
        for line in crate::text::lines(text) {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (state, rest) = if let Some(rest) = line.strip_prefix('+') {
                (ModState::Enabled, rest)
            } else if let Some(rest) = line.strip_prefix('-') {
                (ModState::Disabled, rest)
            } else if let Some(rest) = line.strip_prefix('*') {
                (ModState::Foreign, rest)
            } else {
                (ModState::Enabled, line)
            };
            let name = rest.trim();
            if name.is_empty() || !seen.insert(name.to_owned()) {
                continue;
            }
            let kind = if name.ends_with("_separator") {
                EntryKind::Separator
            } else {
                EntryKind::Mod
            };
            entries.push(ModlistEntry {
                name: name.to_owned(),
                state,
                kind,
            });
        }
        Modlist { entries }
    }

    /// The enabled mods that have a folder, highest priority first (separators and foreign entries left out).
    pub fn enabled_mods(&self) -> impl Iterator<Item = &ModlistEntry> {
        self.entries
            .iter()
            .filter(|e| e.state == ModState::Enabled && e.kind == EntryKind::Mod)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use nvmod_testkit::{covers, ids};
    use proptest::prelude::*;

    #[test]
    fn prefixes_separators_and_foreign_entries_are_read() {
        covers(&[ids::mods::lifecycle::MODLIST_FORMAT]);
        let list = Modlist::parse(
            "# This file was automatically generated by Mod Organizer.\r\n+A\r\n-B\r\n-Group_separator\r\n*DLC: X\r\nplain\r\n",
        );
        let got: Vec<_> = list
            .entries
            .iter()
            .map(|e| (e.name.as_str(), e.state, e.kind))
            .collect();
        assert_eq!(
            got,
            [
                ("A", ModState::Enabled, EntryKind::Mod),
                ("B", ModState::Disabled, EntryKind::Mod),
                ("Group_separator", ModState::Disabled, EntryKind::Separator),
                ("DLC: X", ModState::Foreign, EntryKind::Mod),
                ("plain", ModState::Enabled, EntryKind::Mod),
            ]
        );
        let enabled: Vec<_> = list.enabled_mods().map(|e| e.name.as_str()).collect();
        assert_eq!(enabled, ["A", "plain"]);
    }

    #[test]
    fn names_are_trimmed_blanks_skipped_and_duplicates_dropped() {
        let list = Modlist::parse("+  A  \n\n   \n-A\n+\n+B");
        let names: Vec<_> = list.entries.iter().map(|e| e.name.as_str()).collect();
        assert_eq!(names, ["A", "B"]);
        assert_eq!(
            list.entries[0].state,
            ModState::Enabled,
            "the first occurrence wins"
        );
    }

    #[test]
    fn square_brackets_in_names_are_ordinary() {
        let list = Modlist::parse("+[NoDelete] Mod (v1.2)\n");
        assert_eq!(list.entries[0].name, "[NoDelete] Mod (v1.2)");
    }

    proptest! {
        #[test]
        fn parsing_never_panics_and_names_are_unique_and_trimmed(text in ".{0,400}") {
            let list = Modlist::parse(&text);
            let mut names = HashSet::new();
            for entry in &list.entries {
                prop_assert!(names.insert(entry.name.clone()));
                prop_assert_eq!(entry.name.trim(), entry.name.as_str());
                prop_assert!(!entry.name.is_empty());
            }
        }
    }
}
