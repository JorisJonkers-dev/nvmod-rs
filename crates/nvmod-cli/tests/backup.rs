//! `nvmod backup` and the automatic snapshot, run as a program against a scratch Instance made by `nvmod init`.
//! The clock is `NVMOD_NOW`; every file is synthetic.

use nvmod_testkit::{BaseBuilder, TempDir, ZipBuilder, snapshot, write_file};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

const T0: i64 = 1_794_657_600; // 2026-11-14T12:00:00Z

fn nvmod_at(now: i64, args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .env("NVMOD_NOW", now.to_string())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    fn new() -> Scratch {
        let base = TempDir::new("bk-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
        let inst = TempDir::new("bk-inst");
        let (code, _, err) = nvmod_at(
            T0,
            &[
                "init",
                "--base",
                base.path().to_str().unwrap(),
                "--instance",
                inst.path().join("fnv").to_str().unwrap(),
            ],
        );
        assert_eq!(code, 0, "{err}");
        let s = Scratch { _base: base, inst };
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        write_file(&s.root(), "mods/Existing/Existing.esp", b"existing");
        for (name, body) in [
            ("modlist.txt", "+Existing\r\n"),
            ("plugins.txt", "FalloutNV.esm\r\nExisting.esp\r\n"),
            ("loadorder.txt", "FalloutNV.esm\r\nExisting.esp\r\n"),
        ] {
            write_file(
                &s.root(),
                &format!("profiles/Default/{name}"),
                format!("{header}{body}").as_bytes(),
            );
        }
        write_file(
            &s.root(),
            "profiles/Default/fallout.ini",
            b"[General]\r\nsLanguage=ENGLISH\r\n",
        );
        write_file(
            &s.root(),
            "profiles/Default/settings.ini",
            b"[Settings]\r\nx=1\r\n",
        );
        write_file(
            &s.root(),
            "profiles/Default/profile.json",
            b"{\"name\":\"Default\"}",
        );
        write_file(&s.root(), "profiles/Default/saves/Save1.fos", b"a save");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn run(&self, now: i64, args: &[&str]) -> (i32, String, String) {
        let root = self.root();
        let mut all: Vec<&str> = args.to_vec();
        all.extend_from_slice(&["--instance", root.to_str().unwrap()]);
        nvmod_at(now, &all)
    }

    fn json(&self, now: i64, args: &[&str]) -> (i32, Value) {
        let mut all = args.to_vec();
        all.push("--json");
        let (code, out, err) = self.run(now, &all);
        (
            code,
            serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out} / {err}")),
        )
    }

    fn profile_files(&self) -> std::collections::BTreeMap<String, Vec<u8>> {
        snapshot(&self.root().join("profiles/Default"))
    }

    fn ids(&self) -> Vec<String> {
        let (_, v) = self.json(T0, &["backup", "list"]);
        v["snapshots"]
            .as_array()
            .unwrap()
            .iter()
            .map(|s| s["id"].as_str().unwrap().to_owned())
            .collect()
    }
}

#[test]
fn create_change_restore_gives_the_files_back_byte_for_byte() {
    let s = Scratch::new();
    let before = s.profile_files();
    let (code, v) = s.json(T0, &["backup", "create"]);
    assert_eq!(code, 0, "{v}");
    let id = v["snapshot"]["id"].as_str().unwrap().to_owned();
    assert_eq!(id, "20261114T120000Z");
    // Change a list, edit an INI and add a list the snapshot does not have.
    write_file(
        &s.root(),
        "profiles/Default/modlist.txt",
        b"# changed\r\n-Existing\r\n",
    );
    write_file(
        &s.root(),
        "profiles/Default/settings.ini",
        b"[Settings]\r\nx=2\r\n",
    );
    write_file(
        &s.root(),
        "profiles/Default/lockedorder.txt",
        b"Existing.esp\r\n",
    );
    let changed = s.profile_files();
    assert_ne!(changed, before);
    let (code, v) = s.json(T0 + 60, &["backup", "restore", &id]);
    assert_eq!(code, 0, "{v}");
    assert_eq!(
        s.profile_files(),
        before,
        "every file equals the snapshot, the extra list is gone"
    );
    // The state before the restore is itself a snapshot, and restoring it brings the changes back.
    let pre = v["report"]["pre_restore"].as_str().unwrap().to_owned();
    assert_eq!(pre, "20261114T120100Z");
    assert_eq!(
        v["report"]["removed"],
        serde_json::json!(["lockedorder.txt"])
    );
    assert_eq!(s.json(T0 + 120, &["backup", "restore", &pre]).0, 0);
    assert_eq!(s.profile_files(), changed);
}

#[test]
fn snapshots_are_real_copies_of_text_and_inis_and_saves_only_on_request() {
    let s = Scratch::new();
    let (code, v) = s.json(T0, &["backup", "create"]);
    assert_eq!(code, 0, "{v}");
    let dir = s.root().join(".nvmod/backups/Default/20261114T120000Z");
    let names: Vec<&str> = v["snapshot"]["files"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["path"].as_str().unwrap())
        .collect();
    assert_eq!(
        names,
        [
            "fallout.ini",
            "loadorder.txt",
            "modlist.txt",
            "plugins.txt",
            "profile.json",
            "settings.ini"
        ]
    );
    assert!(!dir.join("saves").exists());
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        for name in names {
            let copy = std::fs::metadata(dir.join(name)).unwrap();
            let source = std::fs::metadata(s.root().join("profiles/Default").join(name)).unwrap();
            assert_eq!(copy.nlink(), 1, "{name} in the snapshot is not linked");
            assert_eq!(source.nlink(), 1, "{name} in the profile gained no link");
            assert_ne!(copy.ino(), source.ino());
        }
    }
    let (code, v) = s.json(T0 + 10, &["backup", "create", "--with-saves"]);
    assert_eq!(code, 0, "{v}");
    assert!(v["snapshot"]["with_saves"].as_bool().unwrap());
    assert_eq!(
        std::fs::read(
            s.root()
                .join(".nvmod/backups/Default/20261114T120010Z/saves/Save1.fos")
        )
        .unwrap(),
        b"a save"
    );
}

#[test]
fn a_damaged_snapshot_is_refused_with_exit_3_and_nothing_changes() {
    let s = Scratch::new();
    assert_eq!(s.json(T0, &["backup", "create"]).0, 0);
    write_file(
        &s.root(),
        ".nvmod/backups/Default/20261114T120000Z/modlist.txt",
        b"tampered",
    );
    let before = snapshot(&s.root());
    let (code, _, err) = s.run(T0 + 5, &["backup", "restore", "20261114T120000Z"]);
    assert_eq!(code, 3, "{err}");
    assert!(err.contains("modlist.txt"), "{err}");
    assert_eq!(
        snapshot(&s.root()),
        before,
        "no pre-restore snapshot, no change"
    );
}

#[test]
fn a_failed_restore_puts_the_profile_back_and_exits_4() {
    let s = Scratch::new();
    assert_eq!(s.run(T0, &["stage"]).0, 0);
    assert_eq!(s.json(T0, &["backup", "create"]).0, 0);
    write_file(
        &s.root(),
        "profiles/Default/modlist.txt",
        b"# changed\r\n-Existing\r\n",
    );
    let before = s.profile_files();
    let root = s.root();
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args([
            "backup",
            "restore",
            "20261114T120000Z",
            "--instance",
            root.to_str().unwrap(),
        ])
        .env("NVMOD_NOW", (T0 + 5).to_string())
        .env("NVMOD_FAIL_AT", "backup-stage")
        .output()
        .unwrap();
    assert_eq!(
        out.status.code(),
        Some(4),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert_eq!(
        s.profile_files(),
        before,
        "the files written were taken back"
    );
}

#[test]
#[cfg(unix)]
fn restore_refuses_while_the_game_runs() {
    let s = Scratch::new();
    assert_eq!(s.json(T0, &["backup", "create"]).0, 0);
    let Some(sleep) = ["/usr/bin/sleep", "/bin/sleep"]
        .iter()
        .find(|p| Path::new(p).is_file())
    else {
        return;
    };
    let tools = TempDir::new("bk-game");
    let fake = tools.path().join("FalloutNV.exe");
    // A symlink, not a copy: nothing is written, so no descriptor open for writing can leak into a forked
    // child and make the exec fail with ETXTBSY. The process name (`comm`) is the name it was started under.
    std::os::unix::fs::symlink(sleep, &fake).unwrap();
    let mut child = Command::new(&fake).arg("30").spawn().unwrap();
    let before = snapshot(&s.root());
    let (code, _, err) = s.run(T0 + 5, &["backup", "restore", "latest"]);
    let _ = child.kill();
    let _ = child.wait();
    if cfg!(target_os = "linux") {
        assert_eq!(code, 2, "{err}");
        assert!(err.contains("game is running"), "{err}");
        assert_eq!(snapshot(&s.root()), before);
    }
}

#[test]
fn the_automatic_snapshot_is_taken_when_the_last_one_is_older_than_the_interval() {
    let s = Scratch::new();
    let zip = |name: &str| {
        let path = s.inst.path().join(name);
        ZipBuilder::new().file("A.esp", b"p").write(&path);
        path
    };
    let install = |now: i64, name: &str| {
        let archive = zip(&format!("{name}.zip"));
        s.run(now, &["install", archive.to_str().unwrap()])
    };
    assert_eq!(install(T0, "One").0, 0);
    assert_eq!(
        s.ids(),
        ["20261114T120000Z"],
        "the first writing command snapshots"
    );
    assert_eq!(install(T0 + 600, "Two").0, 0);
    assert_eq!(s.ids().len(), 1, "ten minutes later: still recent");
    // `mods` and `sort --apply` count as writing commands too; a dry run does not.
    assert_eq!(
        s.run(T0 + 7200, &["mods", "disable", "One", "--dry-run"]).0,
        0
    );
    assert_eq!(s.ids().len(), 1);
    assert_eq!(s.run(T0 + 7200, &["mods", "disable", "One"]).0, 0);
    assert_eq!(
        s.ids(),
        ["20261114T140000Z", "20261114T120000Z"],
        "two hours later: a new one"
    );
    // The snapshot holds the state before the command.
    let old = std::fs::read_to_string(
        s.root()
            .join(".nvmod/backups/Default/20261114T140000Z/modlist.txt"),
    )
    .unwrap();
    assert!(old.contains("+One"), "{old}");
    // A longer interval from `.nvmod/backups.json` holds a snapshot back.
    write_file(
        &s.root(),
        ".nvmod/backups.json",
        b"{\"interval_secs\": 86400}",
    );
    assert_eq!(s.run(T0 + 7200 + 7200, &["mods", "enable", "One"]).0, 0);
    assert_eq!(s.ids().len(), 2);
}

#[test]
fn prune_keeps_the_newest_and_one_per_day() {
    let s = Scratch::new();
    for k in (0..40).rev() {
        let (code, v) = s.json(T0 - k * 12 * 3600, &["backup", "create"]);
        assert_eq!(code, 0, "{v}");
    }
    assert_eq!(s.ids().len(), 40);
    let (code, v) = s.json(
        T0,
        &[
            "backup",
            "prune",
            "--keep",
            "5",
            "--days",
            "14",
            "--dry-run",
        ],
    );
    assert_eq!(code, 0);
    assert_eq!(
        (
            v["kept"].as_array().unwrap().len(),
            v["removed"].as_array().unwrap().len()
        ),
        (16, 24)
    );
    assert_eq!(s.ids().len(), 40, "a dry run removes nothing");
    let (code, v) = s.json(T0, &["backup", "prune", "--keep", "5", "--days", "14"]);
    assert_eq!(code, 0);
    assert_eq!(v["removed"].as_array().unwrap().len(), 24);
    assert_eq!(s.ids().len(), 16);
}

#[test]
fn mo2s_own_timestamped_backups_are_listed_and_restorable() {
    let s = Scratch::new();
    write_file(
        &s.root(),
        "profiles/Default/plugins.txt.2026_11_13_08_00_00",
        b"FalloutNV.esm\r\n",
    );
    write_file(
        &s.root(),
        "profiles/Default/modlist.txt.2026_11_13_08_00_00",
        b"+Old\r\n",
    );
    let (code, v) = s.json(T0, &["backup", "list"]);
    assert_eq!(code, 0);
    let one = &v["snapshots"][0];
    assert_eq!(
        (
            one["id"].as_str(),
            one["source"].as_str(),
            one["files"].as_u64()
        ),
        (Some("mo2-2026_11_13_08_00_00"), Some("mo2"), Some(2))
    );
    let (code, v) = s.json(T0, &["backup", "restore", "mo2-2026_11_13_08_00_00"]);
    assert_eq!(code, 0, "{v}");
    assert_eq!(
        std::fs::read(s.root().join("profiles/Default/modlist.txt")).unwrap(),
        b"+Old\r\n"
    );
    assert_eq!(
        std::fs::read(s.root().join("profiles/Default/plugins.txt")).unwrap(),
        b"FalloutNV.esm\r\n"
    );
    assert!(
        s.root().join("profiles/Default/loadorder.txt").exists(),
        "files MO2 did not back up stay"
    );
    // The snapshot made before the restore holds the state that was replaced.
    let pre = v["report"]["pre_restore"].as_str().unwrap();
    assert!(
        std::fs::read_to_string(
            s.root()
                .join(".nvmod/backups/Default")
                .join(pre)
                .join("modlist.txt")
        )
        .unwrap()
        .contains("+Existing")
    );
}

#[test]
fn list_json_matches_the_golden_file() {
    let s = Scratch::new();
    assert_eq!(s.json(T0, &["backup", "create"]).0, 0);
    assert_eq!(
        s.json(T0 + 3600, &["backup", "create", "--with-saves"]).0,
        0
    );
    let (code, out, err) = s.run(T0 + 7200, &["backup", "list", "--json"]);
    assert_eq!(code, 0, "{err}");
    let golden = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/backup-list.json");
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        std::fs::write(&golden, &out).unwrap();
    }
    let expected = std::fs::read_to_string(&golden).expect("golden file; run with UPDATE_GOLDEN=1");
    assert_eq!(
        out, expected,
        "run with UPDATE_GOLDEN=1 and review the diff"
    );
}

#[test]
fn refusals_and_usage_errors_have_their_exit_codes() {
    let s = Scratch::new();
    assert_eq!(
        s.run(T0, &["backup", "restore", "nope"]).0,
        2,
        "an unknown snapshot"
    );
    assert_eq!(s.run(T0, &["backup", "restore", "latest"]).0, 2, "none yet");
    assert_eq!(s.run(T0, &["backup", "restore"]).0, 5);
    assert_eq!(s.run(T0, &["backup", "frobnicate"]).0, 5);
    assert_eq!(s.run(T0, &["backup", "prune", "--keep", "x"]).0, 5);
    assert_eq!(nvmod_at(T0, &["backup", "list"]).0, 5, "no --instance");
    assert_eq!(
        s.run(T0, &["backup", "create", "--profile", "Missing"]).0,
        2
    );
    let nowhere = TempDir::new("bk-none");
    assert_eq!(
        nvmod_at(
            T0,
            &[
                "backup",
                "list",
                "--instance",
                nowhere.path().to_str().unwrap()
            ]
        )
        .0,
        2
    );
}
