//! `nvmod nvse-usage`, run as a program against a scratch Instance made by `nvmod init` and `nvmod stage`. The
//! plugins carry synthetic compiled scripts built in code, the name tables and `capabilities.json` are written
//! here; no game data is used.

use nvmod_testkit::{
    BaseBuilder, PluginBuilder, ScdaBuilder, TempDir, capabilities_json, write_file,
};
use serde_json::Value;
use std::process::Command;

const MARKER: &str = "SECRET-MARKER-7f3a";

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Plugins: `FalloutNV.esm` (no scripts), `Alpha.esp` and `Beta.esp` (scripts that call planted opcodes),
    /// `Gamma.esp` (installed, not active) and `Ghost.esp` (active, not installed).
    fn new() -> Scratch {
        let base = TempDir::new("usage-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "nvse_1_4.dll",
            &nvmod_testkit::PeBuilder::dll().build(),
        );
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("usage-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let alpha = PluginBuilder::new()
            .script(
                ScdaBuilder::new()
                    .call(0x1401)
                    .call(0x1401)
                    .call_on(1, 0x2201)
                    .set_to(&[0x2202])
                    .call(0x3101)
                    .call(0x3922)
                    .call(0x21c4)
                    .call(0x3d80)
                    .call(0x32a0)
                    .call(0x0100)
                    .build(),
                &format!("ScriptName {MARKER}\nGetNVSEVersion"),
            )
            .script(
                ScdaBuilder::new()
                    .if_calls(&[0x3c93], Some(MARKER))
                    .call(0x5000)
                    .call(0x2300)
                    .build(),
                MARKER,
            )
            .build();
        let beta = PluginBuilder::new()
            .script(
                ScdaBuilder::new()
                    .call(0x1401)
                    .call_with_expressions(0x1402, &[&[0x2201]])
                    .build(),
                "x",
            )
            .build();
        write_file(&root, "mods/Core/Alpha.esp", &alpha);
        write_file(&root, "mods/Core/Beta.esp", &beta);
        write_file(
            &root,
            "mods/Core/Gamma.esp",
            &PluginBuilder::new()
                .script(ScdaBuilder::new().call(0x1999).build(), "x")
                .build(),
        );
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n+Core\r\n",
        );
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            b"FalloutNV.esm\r\nAlpha.esp\r\nBeta.esp\r\nGhost.esp\r\n",
        );
        let (code, _, err) = nvmod(&["stage", "--instance", root.to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
        write_file(
            &root,
            "tables/jip.tsv",
            b"# comment\nopcode\tregistration\tname\tdefine\talias\n2201\tCMD\tFileExists\tX\t\n2202\tCMD\tGetTimeStamp\tX\tGTS\n2203\tEMPTY\n",
        );
        write_file(
            &root,
            "tables/names.rs",
            b"pub static NAMES: [(&str, &str); 3] = [\n    (\"GetNVSEVersion\", \"\"),\n    (\"GetBaseObject\", \"gbo\"),\n    (\"GetWeight\", \"\"),\n];\n",
        );
        Scratch { _base: base, inst }
    }

    fn root(&self) -> String {
        self.inst.path().join("fnv").to_str().unwrap().to_owned()
    }

    fn table(&self, name: &str) -> String {
        self.inst
            .path()
            .join("fnv/tables")
            .join(name)
            .to_str()
            .unwrap()
            .to_owned()
    }

    fn capabilities(&self, text: &str) {
        write_file(
            &self.inst.path().join("fnv"),
            "nv-rs/capabilities.json",
            text.as_bytes(),
        );
    }

    fn run(&self, json: bool) -> (i32, String, String) {
        let root = self.root();
        let (jip, nvse) = (self.table("jip.tsv"), self.table("names.rs"));
        let mut args = vec![
            "nvse-usage",
            "--instance",
            &root,
            "--jip-table",
            &jip,
            "--nvse-names",
            &nvse,
        ];
        if json {
            args.push("--json");
        }
        nvmod(&args)
    }
}

fn row<'a>(report: &'a Value, opcode: &str) -> &'a Value {
    report["opcodes"]
        .as_array()
        .unwrap()
        .iter()
        .find(|r| r["opcode"] == opcode)
        .unwrap_or_else(|| panic!("no row for {opcode}: {report}"))
}

fn caps_with(xnvse: &[&str], jip: &[&str]) -> String {
    let names = |list: &[&str]| {
        list.iter()
            .map(|n| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(",")
    };
    format!(
        "{{\"schema_version\":1,\"extenders\":[{{\"id\":\"xnvse\",\"name\":\"xNVSE\",\"commands\":{{\"implemented\":{},\"total\":3,\"implemented_names\":[{}]}}}},{{\"id\":\"jip-ln\",\"name\":\"JIP LN\",\"commands\":{{\"implemented\":{},\"total\":3,\"implemented_names\":[{}]}}}}]}}",
        xnvse.len(),
        names(xnvse),
        jip.len(),
        names(jip)
    )
}

#[test]
fn planted_opcodes_are_counted_with_plugins_and_status() {
    let s = Scratch::new();
    s.capabilities(&caps_with(
        &["GetNVSEVersion", "GetBaseObject"],
        &["fileexists"],
    ));
    let (code, out, err) = s.run(true);
    assert_eq!(code, 0, "{err}");
    let report: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(report["schema"], 1);
    assert_eq!(report["capabilities"], "used");
    assert_eq!(report["plugins_listed"], 4);
    assert_eq!(report["plugins_scanned"], 3);
    assert_eq!(report["scripts_scanned"], 3);

    // 0x1401 is GetBaseObject (its short name is `gbo`): two calls in Alpha, one in Beta; built.
    let r = row(&report, "0x1401");
    assert_eq!(
        (r["calls"].as_u64(), r["block"].as_str()),
        (Some(3), Some("xnvse"))
    );
    assert_eq!(r["name"], "GetBaseObject");
    assert_eq!(r["status"], "built");
    assert_eq!(r["plugins"], serde_json::json!(["Alpha.esp", "Beta.esp"]));
    // 0x1402 is GetWeight: named, not built; reached through an expression argument of a Beta command's sibling.
    let r = row(&report, "0x1402");
    assert_eq!(
        (r["status"].as_str(), r["calls"].as_u64()),
        (Some("missing"), Some(1))
    );
    // JIP LN: FileExists built (Alpha on a reference, Beta nested), GetTimeStamp missing.
    let r = row(&report, "0x2201");
    assert_eq!(
        (r["status"].as_str(), r["calls"].as_u64()),
        (Some("built"), Some(2))
    );
    assert_eq!(r["plugins"], serde_json::json!(["Alpha.esp", "Beta.esp"]));
    let r = row(&report, "0x2202");
    assert_eq!(
        (r["name"].as_str(), r["status"].as_str()),
        (Some("GetTimeStamp"), Some("missing"))
    );
    // A JIP LN opcode with no name in the table cannot be judged.
    assert_eq!(row(&report, "0x2300")["status"], "unchecked");
    // Blocks without a table.
    let r = row(&report, "0x3101");
    assert_eq!(
        (r["block"].as_str(), r["status"].as_str()),
        (Some("johnnyguitar"), Some("no-table"))
    );
    assert_eq!(row(&report, "0x3C93")["block"], "showoff");
    // Blocks are the registered ranges only: a gap between two plugins is unknown, not the lower one's.
    assert_eq!(row(&report, "0x3922")["block"], "knvse");
    assert_eq!(row(&report, "0x21C4")["block"], "mcm");
    assert_eq!(row(&report, "0x3D80")["block"], "unknown");
    assert_eq!(row(&report, "0x32A0")["block"], "unknown");
    let r = row(&report, "0x5000");
    assert_eq!(
        (r["block"].as_str(), r["status"].as_str()),
        (Some("unknown"), Some("no-table"))
    );
    assert!(r["name"].is_null());
    // The game's own opcode, the inactive plugin's opcode: absent.
    let all: Vec<&str> = report["opcodes"]
        .as_array()
        .unwrap()
        .iter()
        .map(|r| r["opcode"].as_str().unwrap())
        .collect();
    assert!(
        !all.contains(&"0x0100") && !all.contains(&"0x1999"),
        "{all:?}"
    );
    // Sorted by calls, most first.
    let calls: Vec<u64> = report["opcodes"]
        .as_array()
        .unwrap()
        .iter()
        .map(|r| r["calls"].as_u64().unwrap())
        .collect();
    assert!(calls.windows(2).all(|w| w[0] >= w[1]), "{calls:?}");
}

#[test]
fn without_capabilities_known_commands_are_unchecked() {
    let s = Scratch::new();
    let (code, out, err) = s.run(true);
    assert_eq!(code, 0, "{err}");
    let report: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(report["capabilities"], "missing");
    assert_eq!(row(&report, "0x1401")["status"], "unchecked");
    assert_eq!(row(&report, "0x3101")["status"], "no-table");
    s.capabilities("not json");
    let (_, out, _) = s.run(true);
    let report: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(report["capabilities"], "invalid");
}

#[test]
fn only_opcodes_names_counts_and_plugin_files_reach_the_output() {
    let s = Scratch::new();
    s.capabilities(&capabilities_json(&[("xnvse", "xNVSE", 1, 3)]));
    for json in [false, true] {
        let (code, out, err) = s.run(json);
        assert_eq!(code, 0, "{err}");
        assert!(!out.contains(MARKER) && !err.contains(MARKER), "{out}");
        assert!(!out.contains("ScriptName"), "{out}");
    }
    let (_, out, _) = s.run(false);
    assert!(out.contains("0x1401") && out.contains("Alpha.esp"), "{out}");
    // The whole JSON document has only these keys.
    let (_, out, _) = s.run(true);
    let report: Value = serde_json::from_str(&out).unwrap();
    let mut keys: Vec<&String> = report.as_object().unwrap().keys().collect();
    keys.sort();
    assert_eq!(
        keys,
        [
            "capabilities",
            "opcodes",
            "plugins_listed",
            "plugins_scanned",
            "schema",
            "scripts_scanned"
        ]
    );
    let mut keys: Vec<&String> = row(&report, "0x1401").as_object().unwrap().keys().collect();
    keys.sort();
    assert_eq!(
        keys,
        ["block", "calls", "name", "opcode", "plugins", "status"]
    );
}

#[test]
fn nothing_is_written_into_the_instance() {
    let s = Scratch::new();
    let before = nvmod_testkit::snapshot(s.inst.path());
    let (code, _, err) = s.run(false);
    assert_eq!(code, 0, "{err}");
    assert_eq!(nvmod_testkit::snapshot(s.inst.path()), before);
}

#[test]
fn usage_errors_and_refusals_have_their_own_exit_codes() {
    let s = Scratch::new();
    assert_eq!(nvmod(&["nvse-usage"]).0, 5);
    assert_eq!(
        nvmod(&["nvse-usage", "--instance", &s.root(), "extra"]).0,
        5
    );
    assert_eq!(
        nvmod(&["nvse-usage", "--instance", &s.root(), "--bogus"]).0,
        5
    );
    let (code, _, err) = nvmod(&["nvse-usage", "--instance", "/nonexistent/nvmod"]);
    assert_eq!(code, 2, "{err}");
    let (code, _, err) = nvmod(&[
        "nvse-usage",
        "--instance",
        &s.root(),
        "--jip-table",
        "/nonexistent/table.tsv",
    ]);
    assert_eq!(code, 2, "{err}");
    let (code, _, err) = nvmod(&["nvse-usage", "--instance", &s.root(), "--profile", "Nope"]);
    assert_eq!(code, 2, "{err}");
}
