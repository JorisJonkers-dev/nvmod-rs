//! `nvmod lod`, run as a program against a scratch Instance. lodwright-rs is a fake shell script that records
//! how it was called and prints the plan lodwright-rs v0.1.0 prints for its synthetic worldspaces (a golden file
//! copied from its tests). No network, no game data.
#![cfg(unix)]

use nvmod_testkit::{BaseBuilder, TempDir, snapshot, write_file, write_script};
use nvmod_tools::{platform, sha256_hex};
use serde_json::Value;
use std::path::PathBuf;
use std::process::Command;

const PLAN: &str = include_str!("golden/lodwright-plan.json");

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Rig {
    instance: TempDir,
    work: TempDir,
}

impl Rig {
    fn new() -> Rig {
        let base = TempDir::new("lod-base");
        let rig = Rig {
            instance: TempDir::new("lod-inst"),
            work: TempDir::new("lod-work"),
        };
        BaseBuilder::steam().write(base.path());
        let root = rig.root();
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        write_file(&root, "profiles/Default/modlist.txt", header.as_bytes());
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            format!("{header}FalloutNV.esm\r\nB.esp\r\n").as_bytes(),
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            format!("{header}FalloutNV.esm\r\nB.esp\r\nInactive.esp\r\n").as_bytes(),
        );
        rig
    }

    fn root(&self) -> PathBuf {
        self.instance.path().join("i")
    }

    /// Make the Staging tree's data folder, which `nvmod stage` would make.
    fn stage(&self) {
        write_file(&self.root(), "staging/Default/data/FalloutNV.esm", b"x");
    }

    /// A fake lodwright that records its arguments and prints `body`.
    fn lodwright(&self, body: &str) -> String {
        let log = self.work.path().join("lodwright.log");
        write_script(
            self.work.path(),
            "lodwright",
            &format!("echo \"$@\" >> {}\n{body}", log.display()),
        )
        .to_str()
        .unwrap()
        .to_owned()
    }

    fn runs(&self) -> Vec<String> {
        std::fs::read_to_string(self.work.path().join("lodwright.log"))
            .unwrap_or_default()
            .lines()
            .map(str::to_owned)
            .collect()
    }

    fn print_plan(&self, plan: &str) -> String {
        let file = self.work.path().join("plan.json");
        std::fs::write(&file, plan).unwrap();
        self.lodwright(&format!("cat {}", file.display()))
    }

    fn lock(&self, program: &str, contracts: &str) -> String {
        let hash = sha256_hex(&std::fs::read(program).unwrap());
        let text = format!(
            "schema_version = 1\n\n[[tool]]\nname = \"lodwright-rs\"\nversion = \"0.1.0\"\ncontracts = {{ {contracts} }}\n\n\
             [tool.attestation]\nrepository = \"o/lodwright-rs\"\n\n[tool.assets.{}]\nurl = \"http://127.0.0.1:9/lodwright\"\nsha256 = \"{hash}\"\n",
            platform()
        );
        let path = self.work.path().join("tools.lock.toml");
        std::fs::write(&path, text).unwrap();
        path.to_str().unwrap().to_owned()
    }

    /// A lock whose pin is from the release that answers the handshake.
    fn lock_handshake(&self, program: &str, contracts: &str) -> String {
        let path = self.lock(program, contracts);
        let text = std::fs::read_to_string(&path).unwrap();
        let text = text.replacen(
            "\n\n[tool.attestation]",
            "\nhandshake_from = \"0.1.0\"\n\n[tool.attestation]",
            1,
        );
        std::fs::write(&path, text).unwrap();
        path
    }

    /// A fake lodwright that answers `contracts --json` with `handshake` and prints `plan` otherwise.
    fn negotiating(&self, handshake: &str, plan: &str) -> String {
        let file = self.work.path().join("plan.json");
        std::fs::write(&file, plan).unwrap();
        self.lodwright(&format!(
            "if [ \"$1\" = contracts ]; then echo '{handshake}'; else cat {}; fi",
            file.display()
        ))
    }

    fn lod(&self, sub: &str, lock: &str, program: &str, extra: &[&str]) -> (i32, String, String) {
        let root = self.root();
        let mut args = vec![
            "lod",
            sub,
            "--instance",
            root.to_str().unwrap(),
            "--lock",
            lock,
            "--lodwright",
            program,
        ];
        args.extend_from_slice(extra);
        nvmod(&args)
    }
}

#[test]
fn plan_prints_the_planned_blocks_and_writes_nothing() {
    let rig = Rig::new();
    rig.stage();
    let program = rig.print_plan(PLAN);
    let lock = rig.lock(&program, "lodwright-plan = 1");
    let before = snapshot(&rig.root());
    let (code, out, err) = rig.lod("plan", &lock, &program, &[]);
    assert_eq!(code, 0, "{out}\n{err}");
    assert!(out.contains("Testland (00000A00): 3 cell(s)"), "{out}");
    assert!(out.contains("level 4: 2 block(s)"), "{out}");
    assert!(out.contains("Island"), "{out}");
    assert_eq!(
        snapshot(&rig.root()),
        before,
        "plan wrote into the Instance"
    );
    // The active plugins in Load order, the Staging data folder, and no Instance in the arguments.
    let runs = rig.runs();
    assert_eq!(runs.len(), 1, "{runs:?}");
    let data = std::fs::canonicalize(rig.root().join("staging/Default/data")).unwrap();
    assert_eq!(
        runs[0],
        format!(
            "plan --data {} --format json --plugin FalloutNV.esm --plugin B.esp",
            data.display()
        )
    );
    assert!(!runs[0].contains("instance"), "{}", runs[0]);
}

#[test]
fn plan_json_carries_the_request_the_plan_and_the_version() {
    let rig = Rig::new();
    rig.stage();
    let program = rig.print_plan(PLAN);
    let lock = rig.lock(&program, "lodwright-plan = 1");
    let (code, out, err) = rig.lod(
        "plan",
        &lock,
        &program,
        &["--json", "--world", "Island", "--blocks"],
    );
    assert_eq!(code, 0, "{err}");
    let doc: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(doc["status"], "planned");
    assert_eq!(doc["schema_version"], 1);
    assert_eq!(doc["request"]["plugins"][1], "B.esp");
    assert_eq!(doc["request"]["settings"]["world"], "Island");
    assert!(doc["request"].get("instance").is_none());
    assert_eq!(doc["plan"]["worlds"][0]["name"], "Testland");
    let runs = rig.runs();
    assert!(runs[0].ends_with("--world Island --blocks"), "{runs:?}");
}

#[test]
fn a_plan_of_an_unknown_schema_version_is_refused() {
    let rig = Rig::new();
    rig.stage();
    let newer = PLAN.replacen("\"schema_version\":1", "\"schema_version\":2", 1);
    assert!(newer.contains("\"schema_version\":2"));
    let program = rig.print_plan(&newer);
    let lock = rig.lock(&program, "lodwright-plan = 1");
    let (code, out, err) = rig.lod("plan", &lock, &program, &[]);
    assert_eq!(code, 2, "{out}");
    assert!(err.contains("schema") && err.contains('2'), "{err}");
    assert_eq!(out, "");
}

#[test]
fn a_plan_that_breaks_the_contract_is_a_tool_failure() {
    let rig = Rig::new();
    rig.stage();
    let program = rig.print_plan("{\"worlds\":[{\"name\":1}]}");
    let lock = rig.lock(&program, "lodwright-plan = 1");
    let (code, _, err) = rig.lod("plan", &lock, &program, &[]);
    assert_eq!(code, 4, "{err}");
    assert!(err.contains("malformed"), "{err}");
}

