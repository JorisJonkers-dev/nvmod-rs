#[test]
fn a_program_that_differs_from_the_pin_is_not_run() {
    let rig = Rig::new();
    rig.stage();
    let pinned = rig.print_plan(PLAN);
    let lock = rig.lock(&pinned, "lodwright-plan = 1");
    let other = write_script(rig.work.path(), "other", "echo ran >> other.log\necho '{}'");
    let (code, _, err) = rig.lod("plan", &lock, other.to_str().unwrap(), &[]);
    assert_eq!(code, 3, "{err}");
    assert_eq!(rig.runs(), Vec::<String>::new());
}

