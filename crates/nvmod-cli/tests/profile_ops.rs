fn schema_check(instance: &Value) {
    let path = format!(
        "{}/../../schemas/profile-list.v1.json",
        env!("CARGO_MANIFEST_DIR")
    );
    let schema: Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    let validator = jsonschema::validator_for(&schema).unwrap();
    let errors: Vec<String> = validator
        .iter_errors(instance)
        .map(|e| e.to_string())
        .collect();
    assert!(errors.is_empty(), "{errors:?}\n{instance}");
}

#[test]
fn list_json_has_counts_and_matches_its_schema() {
    let s = Scratch::new();
    write_file(
        &s.root(),
        "profiles/Alpha/plugins.txt",
        format!("{HEADER}FalloutNV.esm\r\nOne.esp\r\n").as_bytes(),
    );
    write_file(
        &s.root(),
        "profiles/Alpha/loadorder.txt",
        format!("{HEADER}FalloutNV.esm\r\nOne.esp\r\nTwo.esp\r\n").as_bytes(),
    );
    s.ok(&["profile", "select", "Beta"]);
    let list = s.list();
    schema_check(&list);
    assert_eq!(list["schema_version"], 1);
    assert_eq!(list["selected"], "Beta");
    let alpha = profile(&list, "Alpha");
    assert_eq!(alpha["selected"], false);
    assert_eq!(alpha["mods_enabled"], 1, "separators are not Mods");
    assert_eq!(alpha["mods_total"], 2);
    assert_eq!(alpha["plugins_active"], 2);
    assert_eq!(alpha["plugins_total"], 3);
    assert_eq!(alpha["local_saves"], false);
    let beta = profile(&list, "Beta");
    assert_eq!(beta["selected"], true);
    assert_eq!(beta["mods_enabled"], 0);
    assert_eq!(beta["plugins_active"], 1);
    let text = s.ok(&["profile", "list"]);
    assert!(
        text.contains("* Beta") && text.contains("  Alpha"),
        "{text}"
    );
}

fn mo2_instance(root: &Path) {
    write_file(
        root,
        "ModOrganizer.ini",
        b"[General]\r\ngameName=TTW\r\nselected_profile=@ByteArray(Example Profile)\r\ngamePath=@ByteArray(D:\\\\Games\\\\Fallout New Vegas)\r\nversion=2.5.2\r\n",
    );
    write_file(root, "mods/Example Mod/meshes/rock.nif", b"rock");
    let p = "profiles/Example Profile";
    write_file(
        root,
        &format!("{p}/modlist.txt"),
        format!("{HEADER}+Example Mod\r\n").as_bytes(),
    );
    write_file(
        root,
        &format!("{p}/plugins.txt"),
        format!("{HEADER}FalloutNV.esm\r\n").as_bytes(),
    );
    write_file(
        root,
        &format!("{p}/loadorder.txt"),
        format!("{HEADER}FalloutNV.esm\r\n").as_bytes(),
    );
    write_file(
        root,
        &format!("{p}/settings.ini"),
        b"[General]\r\nLocalSaves=false\r\n",
    );
    write_file(root, &format!("{p}/saves/a.fos"), b"save");
}

#[test]
fn an_imported_profile_can_be_copied_renamed_and_selected_and_mo2_is_untouched() {
    let mo2 = TempDir::new("po-mo2");
    mo2_instance(mo2.path());
    let base = TempDir::new("po-imp-base");
    BaseBuilder::steam().write(base.path());
    let out = TempDir::new("po-imp-out");
    let root = out.path().join("fnv");
    let before = snapshot(mo2.path());
    let (code, o, err) = run(
        &[
            "import-mo2",
            "--mo2",
            mo2.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
            "--base",
            base.path().to_str().unwrap(),
        ],
        &[],
    );
    assert_eq!(code, 0, "{o} {err}");
    let at = |args: &[&str]| {
        let mut all = args.to_vec();
        all.extend(["--instance", root.to_str().unwrap()]);
        run(&all, &[])
    };
    for args in [
        &["profile", "copy", "Example Profile", "Copy", "--with-saves"][..],
        &["profile", "select", "Copy"],
        &["profile", "rename", "Example Profile", "Renamed"],
    ] {
        let (code, o, err) = at(args);
        assert_eq!(code, 0, "{args:?}: {o} {err}");
    }
    let (code, o, _) = at(&["profile", "list", "--json"]);
    assert_eq!(code, 0);
    let list: Value = serde_json::from_str(&o).unwrap();
    schema_check(&list);
    assert_eq!(list["selected"], "Copy");
    assert_eq!(profile(&list, "Renamed")["mods_enabled"], 1);
    assert_eq!(profile(&list, "Copy")["mods_enabled"], 1);
    // The profile record follows the name.
    let record: Value =
        serde_json::from_slice(&std::fs::read(root.join("profiles/Copy/profile.json")).unwrap())
            .unwrap();
    assert_eq!(record["name"], "Copy");
    assert_eq!(
        snapshot(mo2.path()),
        before,
        "the MO2 instance is only read"
    );
}
