#[test]
fn a_running_game_or_a_held_lock_refuses_a_change_but_not_a_dry_run() {
    let s = Scratch::new();
    s.ok(&["profile", "select", "Beta"]);
    let procs = TempDir::new("po-proc");
    write_file(procs.path(), "4242/comm", b"ModOrganizer.exe\n");
    write_file(
        procs.path(),
        "4242/stat",
        b"4242 (ModOrganizer.exe) S 1 1 1\n",
    );
    let env = [("NVMOD_PROC_DIR", procs.path().to_str().unwrap())];
    let before = s.tree();
    for args in [
        &["profile", "delete", "Alpha"][..],
        &["profile", "rename", "Alpha", "Omega"],
        &["profile", "copy", "Alpha", "Omega"],
        &["profile", "select", "Alpha"],
        &["profile", "set", "LocalSaves", "true"],
    ] {
        let (code, _, err) = s.cmd(args, &env);
        assert_eq!(code, 2, "{args:?}: {err}");
        assert!(err.contains("running"), "{err}");
    }
    let (code, _, err) = s.cmd(&["profile", "delete", "Alpha", "--dry-run"], &env);
    assert_eq!(code, 0, "{err}");
    assert_eq!(s.tree(), before);

    // Another live process holds the Instance lock (the test's own parent stands in for a running game).
    let lock = format!(
        "{{\"pid\":{},\"started\":1,\"command\":\"run Fallout\"}}\n",
        std::process::id()
    );
    write_file(&s.root(), ".nvmod/lock", lock.as_bytes());
    let (code, _, err) = s.cmd(&["profile", "delete", "Alpha"], &[]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains("in use"), "{err}");
    assert_eq!(s.tree(), before);
}

#[test]
fn select_records_the_profile_in_the_instance_file_and_decides_the_default() {
    let s = Scratch::new();
    let (code, _, err) = s.cmd(&["mods", "list"], &[]);
    assert_eq!(code, 2, "two profiles and none selected: {err}");
    let out = s.ok(&["profile", "select", "beta", "--json"]);
    let done: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(done["selected"], "Beta");
    assert_eq!(done["changed"], true);
    let file: Value =
        serde_json::from_slice(&std::fs::read(s.root().join("nvmod-instance.json")).unwrap())
            .unwrap();
    assert_eq!(file["selected_profile"], "Beta");
    s.ok(&["mods", "list"]); // the selected profile is the default now
    let again: Value =
        serde_json::from_str(&s.ok(&["profile", "select", "Beta", "--json"])).unwrap();
    assert_eq!(again["changed"], false);
    let (code, _, err) = s.cmd(&["profile", "select", "Nope"], &[]);
    assert_eq!(code, 2, "{err}");
}

#[test]
fn set_edits_one_line_and_the_reader_returns_it() {
    let s = Scratch::new();
    let path = s.root().join("profiles/Alpha/settings.ini");
    s.ok(&["profile", "set", "LocalSaves", "true", "--profile", "Alpha"]);
    assert_eq!(
        std::fs::read_to_string(&path).unwrap(),
        "; mine\r\n[General]\r\nLocalSaves=true\r\nKeep=me  \r\n",
        "only the value changed"
    );
    assert_eq!(profile(&s.list(), "Alpha")["local_saves"], true);
    s.ok(&[
        "profile",
        "set",
        "localsettings",
        "true",
        "--profile",
        "Alpha",
    ]);
    s.ok(&[
        "profile",
        "set",
        "AutomaticArchiveInvalidation",
        "1",
        "--profile",
        "Alpha",
    ]);
    let p = s.list();
    let alpha = profile(&p, "Alpha");
    assert_eq!(alpha["local_settings"], true);
    assert_eq!(alpha["archive_invalidation"], true);
    let (code, _, err) = s.cmd(
        &[
            "profile",
            "set",
            "LocalSaves",
            "false",
            "--profile",
            "Alpha",
            "--dry-run",
        ],
        &[],
    );
    assert_eq!(code, 0, "{err}");
    assert_eq!(
        profile(&s.list(), "Alpha")["local_saves"],
        true,
        "a dry run writes nothing"
    );
    // A profile without settings.ini gets one.
    s.ok(&["profile", "set", "LocalSaves", "true", "--profile", "Beta"]);
    assert_eq!(
        std::fs::read(s.root().join("profiles/Beta/settings.ini")).unwrap(),
        b"[General]\r\nLocalSaves=true\r\n"
    );
}

