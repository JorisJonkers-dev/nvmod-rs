//! `nvmod ttw`, run as a program against a scratch Instance made by `nvmod init` from a synthetic base copy. The
//! TTW installer is a fake shell script written by the test: it records how it was called, writes a synthetic
//! output folder and, when asked to, a report file. The lock file is written by each test. No network, no game
//! data, no TTW package.
#![cfg(unix)]
use nvmod_testkit::{BaseBuilder, TempDir, snapshot, write_file, write_script};
use nvmod_tools::{Trust, platform, sha256_hex};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    nvmod_env(args, &[])
}

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

/// The installer's behaviour, as the body of the fake script. `$dest` is the `--dest` argument.
const GOOD: &str = r#"
mkdir -p "$dest/Meshes"
echo generated > "$dest/Meshes/ttw.nif"
echo master > "$dest/TaleOfTwoWastelands.esm"
"#;

struct Rig {
    base: TempDir,
    fo3: TempDir,
    instance: TempDir,
    work: TempDir,
}

impl Rig {
    fn new() -> Rig {
        let rig = Rig {
            base: TempDir::new("ttw-base"),
            fo3: TempDir::new("ttw-fo3"),
            instance: TempDir::new("ttw-inst"),
            work: TempDir::new("ttw-work"),
        };
        BaseBuilder::steam().write(rig.base.path());
        write_file(rig.fo3.path(), "Fallout3.exe", b"synthetic fallout 3");
        let root = rig.root();
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            rig.base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        for (file, body) in [
            ("modlist", String::new()),
            ("plugins", "FalloutNV.esm\r\n".to_owned()),
            ("loadorder", "FalloutNV.esm\r\n".to_owned()),
        ] {
            write_file(
                &rig.root(),
                &format!("profiles/Default/{file}.txt"),
                format!("{header}{body}").as_bytes(),
            );
        }
        rig
    }

    fn root(&self) -> PathBuf {
        self.instance.path().join("i")
    }

    fn path(&self, name: &str) -> String {
        self.work.path().join(name).to_str().unwrap().to_owned()
    }

    /// A fake installer that records its arguments and environment, then runs `body`.
    fn installer(&self, body: &str) -> String {
        let log = self.work.path().join("installer.log");
        let script = format!(
            "echo \"$@\" >> {log}\necho \"report=$NVMOD_TTW_REPORT\" >> {log}\n\
             dest=\"\"\nprev=\"\"\nfor a in \"$@\"; do [ \"$prev\" = --dest ] && dest=\"$a\"; prev=\"$a\"; done\n{body}",
            log = log.display()
        );
        write_script(self.work.path(), "ttw-installer", &script)
            .to_str()
            .unwrap()
            .to_owned()
    }

    fn runs(&self) -> Vec<String> {
        std::fs::read_to_string(self.work.path().join("installer.log"))
            .unwrap_or_default()
            .lines()
            .filter(|l| !l.starts_with("report="))
            .map(str::to_owned)
            .collect()
    }

    /// A lock that pins the fake installer at its checksum.
    fn lock_pinned(&self, installer: &str) -> String {
        let hash = sha256_hex(&std::fs::read(installer).unwrap());
        self.write_lock(Some(&hash))
    }

    fn write_lock(&self, hash: Option<&str>) -> String {
        let sha = hash.map_or_else(String::new, |h| format!("sha256 = \"{h}\"\n"));
        let text = format!(
            "schema_version = 1\n\n[[tool]]\nname = \"ttw-installer\"\nversion = \"0.2.0\"\nkind = \"third-party\"\n\
             contracts = {{ ttw-installer-result = 1 }}\n\n[tool.assets.{}]\nurl = \"http://127.0.0.1:9/ttw\"\n{sha}",
            platform()
        );
        let path = self.work.path().join("tools.lock.toml");
        std::fs::write(&path, text).unwrap();
        path.to_str().unwrap().to_owned()
    }

    fn ttw(&self, lock: &str, installer: &str, extra: &[&str]) -> (i32, String, String) {
        self.ttw_env(lock, installer, extra, &[])
    }

    fn ttw_env(
        &self,
        lock: &str,
        installer: &str,
        extra: &[&str],
        env: &[(&str, &str)],
    ) -> (i32, String, String) {
        let root = self.root();
        let mut args = vec![
            "ttw",
            "--instance",
            root.to_str().unwrap(),
            "--fallout3",
            self.fo3.path().to_str().unwrap(),
            "--installer",
            installer,
            "--lock",
            lock,
        ];
        args.extend_from_slice(extra);
        nvmod_env(&args, env)
    }
}

fn mod_installed(rig: &Rig) -> bool {
    rig.root().join("mods/Tale of Two Wastelands").exists()
}

#[test]
fn the_installer_gets_the_fo3_path_and_its_output_becomes_a_mod() {
    let rig = Rig::new();
    let installer = rig.installer(GOOD);
    let lock = rig.lock_pinned(&installer);
    let package = rig.path("TTW.mpi");
    let (code, out, err) = rig.ttw(&lock, &installer, &["--package", &package]);
    assert_eq!(code, 0, "{out}\n{err}");
    let runs = rig.runs();
    assert_eq!(runs.len(), 1, "{runs:?}");
    let base = std::fs::canonicalize(rig.base.path()).unwrap();
    let fo3 = std::fs::canonicalize(rig.fo3.path()).unwrap();
    let words: Vec<&str> = runs[0].split(' ').collect();
    assert_eq!(words[0], "install");
    assert_eq!(
        &words[1..7],
        [
            "--mpi",
            package.as_str(),
            "--fo3",
            fo3.to_str().unwrap(),
            "--fnv",
            base.to_str().unwrap()
        ],
        "{runs:?}"
    );
    assert_eq!(words[7], "--dest");
    let dest = Path::new(words[8]);
    let root = std::fs::canonicalize(rig.root()).unwrap();
    assert!(
        dest.starts_with(&root),
        "the output goes beside the Instance's files: {dest:?}"
    );
    assert!(!dest.exists(), "the scratch output is removed afterwards");
    assert_eq!(
        std::fs::read(
            rig.root()
                .join("mods/Tale of Two Wastelands/Meshes/ttw.nif")
        )
        .unwrap(),
        b"generated\n"
    );
    let modlist = std::fs::read_to_string(rig.root().join("profiles/Default/modlist.txt")).unwrap();
    assert!(modlist.contains("+Tale of Two Wastelands"), "{modlist}");
    let order = std::fs::read_to_string(rig.root().join("profiles/Default/loadorder.txt")).unwrap();
    assert!(order.contains("TaleOfTwoWastelands.esm"), "{order}");
    assert!(
        rig.root()
            .join("staging/Default/data/taleoftwowastelands.esm")
            .is_file()
    );
    assert!(out.contains("Tale of Two Wastelands"), "{out}");
}

#[test]
fn json_carries_the_normalised_result() {
    let rig = Rig::new();
    let installer = rig.installer(&format!(
        "{GOOD}\necho '{{\"installer\":{{\"name\":\"fake\",\"version\":\"9.9\"}},\"fallout3_verified\":true,\"messages\":[\"all checks passed\"]}}' > \"$NVMOD_TTW_REPORT\""
    ));
    let lock = rig.lock_pinned(&installer);
    let (code, out, err) = rig.ttw(&lock, &installer, &["--json"]);
    assert_eq!(code, 0, "{out}\n{err}");
    let doc: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(doc["status"], "installed");
    assert_eq!(doc["mod"], "Tale of Two Wastelands");
    let result = &doc["result"];
    assert_eq!(result["schema_version"], 1);
    assert_eq!(result["outcome"], "success");
    assert_eq!(result["exit_code"], 0);
    assert_eq!(result["fallout3_verified"], true);
    assert_eq!(result["installer"]["name"], "fake");
    assert_eq!(result["installer"]["version"], "9.9");
    assert_eq!(result["files_written"], 2);
    assert_eq!(result["messages"][0], "all checks passed");
    // The record is what the contract accepts.
    let contract = nvmod_tools::builtin("ttw-installer-result").unwrap();
    assert_eq!(contract.check(result), Ok(1));
}

#[test]
fn a_bad_base_game_is_refused_before_the_installer_starts() {
    let rig = Rig::new();
    // The base copy's executable is not the supported version.
    BaseBuilder::steam()
        .exe_version([1, 3, 0, 452])
        .write(rig.base.path());
    let installer = rig.installer(GOOD);
    let lock = rig.lock_pinned(&installer);
    let before = snapshot(&rig.root());
    let (code, _, err) = rig.ttw(&lock, &installer, &[]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains("base.exe"), "{err}");
    assert!(rig.runs().is_empty(), "the installer was not started");
    assert_eq!(snapshot(&rig.root()), before);
}

