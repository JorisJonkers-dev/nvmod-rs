    let installer = rig.installer(GOOD);
    let lock = rig.lock_pinned(&installer);
    let (base, fo3) = (snapshot(rig.base.path()), snapshot(rig.fo3.path()));
    let exe = std::fs::read(rig.base.path().join("FalloutNV.exe")).unwrap();
