#[test]
fn an_installer_without_a_pinned_checksum_is_refused_until_trusted() {
    let rig = Rig::new();
    let installer = rig.installer(GOOD);
    let lock = rig.write_lock(None);
    let before = snapshot(&rig.root());
    let (code, _, err) = rig.ttw(&lock, &installer, &[]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains("nvmod tools trust"), "{err}");
    assert_eq!(rig.runs().len(), 0);
    assert_eq!(snapshot(&rig.root()), before);

    // The owner confirms the checksum they saw; the same installer then runs.
    let hash = sha256_hex(&std::fs::read(&installer).unwrap());
    let mut trust = Trust::load(&rig.root()).unwrap();
    trust
        .record(&rig.root(), "ttw-installer", "0.2.0", &hash)
        .unwrap();
    let (code, out, err) = rig.ttw(&lock, &installer, &[]);
    assert_eq!(code, 0, "{out}\n{err}");
    assert_eq!(rig.runs().len(), 1);
}

