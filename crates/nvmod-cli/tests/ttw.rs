#[test]
fn a_failed_import_is_rolled_back_with_exit_4() {
    for step in ["mod", "lists", "stage"] {
        let rig = Rig::new();
        let installer = rig.installer(GOOD);
        let lock = rig.lock_pinned(&installer);
        let before = snapshot(&rig.root());
        let (code, _, err) = rig.ttw_env(&lock, &installer, &[], &[("NVMOD_FAIL_AT", step)]);
        assert_eq!(code, 4, "{step}: {err}");
        assert!(err.contains("rolled back"), "{step}: {err}");
        // The journal of the undone import stays, marked rolled back; everything else is as it was.
        let mut after = snapshot(&rig.root());
        after.retain(|name, _| !name.starts_with(".nvmod"));
        assert_eq!(after, before, "{step}: the Instance is as it was");
        let journal = std::fs::read_dir(rig.root().join(".nvmod/journal"))
            .unwrap()
            .next()
            .unwrap()
            .unwrap()
            .path()
            .join("journal.json");
        assert!(
            std::fs::read_to_string(journal)
                .unwrap()
                .contains("rolled-back")
        );
    }
}

