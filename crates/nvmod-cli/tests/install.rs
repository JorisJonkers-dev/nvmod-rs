fn fomod_zip(path: &Path, xml: &str, files: &[(&str, &[u8])]) {
    let mut zip = ZipBuilder::new().file("fomod/ModuleConfig.xml", xml.as_bytes());
    for (name, data) in files {
        zip = zip.file(name, data);
    }
    zip.write(path);
}

#[test]
fn a_plain_archive_is_placed_enabled_at_highest_priority_and_staged() {
    let s = Scratch::new();
    let zip = s.archive("Better Rocks.zip");
    ZipBuilder::new()
        .file("Meshes/Rock.nif", b"better rock")
        .file("BetterRocks.esp", b"plugin")
        .write(&zip);
    let (code, report) = s.install_json(&zip, &[]);
    assert_eq!(code, 0, "{report}");
    assert_eq!(report["mod"], "Better Rocks");
    assert_eq!(
        std::fs::read(s.root().join("mods/Better Rocks/Meshes/Rock.nif")).unwrap(),
        b"better rock"
    );
    let modlist = s.text("profiles/Default/modlist.txt");
    assert_eq!(lines(&modlist)[1..], ["+Better Rocks", "+Existing"]);
    assert!(modlist.contains("\r\n") && !modlist.replace("\r\n", "").contains('\n'));
    let plugins = s.text("profiles/Default/plugins.txt");
    assert_eq!(
        lines(&plugins)[1..],
        ["FalloutNV.esm", "Existing.esp", "BetterRocks.esp"]
    );
    let order = s.text("profiles/Default/loadorder.txt");
    assert_eq!(
        lines(&order)[1..],
        ["FalloutNV.esm", "Existing.esp", "BetterRocks.esp"]
    );
    assert_eq!(
        std::fs::read(s.root().join("staging/Default/data/meshes/rock.nif")).unwrap(),
        b"better rock"
    );
}

#[test]
fn a_nexus_named_archive_writes_its_provenance_into_meta_ini() {
    let s = Scratch::new();
    let zip = s.archive("Better Rocks-83815-1-10-2-1699999999.zip");
    ZipBuilder::new()
        .file("Meshes/Rock.nif", b"better rock")
        .write(&zip);
    let (code, report) = s.install_json(&zip, &["--name", "Better Rocks"]);
    assert_eq!(code, 0, "{report}");
    let meta = s.text("mods/Better Rocks/meta.ini");
    assert_eq!(
        meta,
        "[General]\r\ngameName=newvegas\r\ninstallationFile=Better Rocks-83815-1-10-2-1699999999.zip\r\nmodid=83815\r\nversion=1.10.2\r\n"
    );
    assert!(!meta.contains(['/', '\\']), "no directory part: {meta}");
    // The file is MO2's metadata, not game data.
    assert!(!s.root().join("staging/Default/data/meta.ini").exists());
    // A name that is not Nexus style writes no ids.
    let plain = s.archive("Plain Mod.zip");
    ZipBuilder::new().file("a.nif", b"x").write(&plain);
    assert_eq!(s.install_json(&plain, &[]).0, 0);
    assert_eq!(
        s.text("mods/Plain Mod/meta.ini"),
        "[General]\r\ngameName=newvegas\r\ninstallationFile=Plain Mod.zip\r\n"
    );
}

