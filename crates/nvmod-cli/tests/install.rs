#[test]
fn hostile_archives_are_refused_and_change_nothing() {
    let s = Scratch::new();
    let cases: Vec<(&str, Vec<u8>)> = vec![
        (
            "escape.zip",
            ZipBuilder::new().file("../evil.txt", b"x").bytes(),
        ),
        (
            "backslash.zip",
            ZipBuilder::new().file("a\\..\\..\\evil.txt", b"x").bytes(),
        ),
        (
            "absolute.zip",
            ZipBuilder::new().file("/etc/evil.txt", b"x").bytes(),
        ),
        ("link.zip", ZipBuilder::new().symlink("l", "/etc").bytes()),
        (
            "escape.tar",
            TarBuilder::new().file("../evil.txt", b"x").bytes(),
        ),
        ("link.tar", TarBuilder::new().symlink("l", "/etc").bytes()),
    ];
    let before = s.state();
    for (name, bytes) in cases {
        let archive = s.archive(name);
        std::fs::write(&archive, bytes).unwrap();
        let (code, _, err) = s.install(&archive, &[]);
        assert_eq!(code, 2, "{name}: {err}");
        assert_eq!(s.state(), before, "{name}");
    }
    assert!(!s.work.path().join("evil.txt").exists());
}

