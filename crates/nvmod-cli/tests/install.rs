fn a_failed_step_rolls_back_by_itself_with_exit_4() {
    let s = Scratch::new();
    let zip = s.archive("Fails.zip");
    ZipBuilder::new().file("Fails.esp", b"p").write(&zip);
    let before: Vec<_> = ["modlist.txt", "plugins.txt", "loadorder.txt"]
        .iter()
        .map(|f| s.text(&format!("profiles/Default/{f}")))
        .collect();
    let root = s.root();
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args([
            "install",
            zip.to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ])
        .env("NVMOD_FAIL_AT", "stage")
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(4));
    assert!(!s.root().join("mods/Fails").exists());
    let after: Vec<_> = ["modlist.txt", "plugins.txt", "loadorder.txt"]
        .iter()
        .map(|f| s.text(&format!("profiles/Default/{f}")))
        .collect();
    assert_eq!(before, after);
    assert_eq!(
        s.rollback().0,
        2,
        "the automatic rollback leaves nothing to undo"
    );
}

#[test]
fn usage_errors_exit_with_five_and_a_missing_instance_is_a_refusal() {
    assert_eq!(nvmod(&["install"]).0, 5);
    assert_eq!(nvmod(&["install", "a.zip"]).0, 5);
    assert_eq!(nvmod(&["rollback"]).0, 5);
    assert_eq!(
        nvmod(&["install", "a.zip", "--instance", "/nonexistent"]).0,
        2
    );
}
