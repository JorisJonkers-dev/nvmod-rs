//! `nvmod install` and `nvmod rollback`, run as a program against a scratch Instance made by `nvmod init`.
//! Archives are built in code by the testkit; no mod data is used.

use nvmod_testkit::{BaseBuilder, TarBuilder, TempDir, ZipBuilder, snapshot, write_file};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
    work: TempDir,
}

impl Scratch {
    /// An Instance with the profile `Default`: one Mod `Existing` that provides `Existing.esp`.
    fn new() -> Scratch {
        let base = TempDir::new("inst-base");
        BaseBuilder::steam().write(base.path());
        write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
        let inst = TempDir::new("inst-inst");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            inst.path().join("fnv").to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let s = Scratch {
            _base: base,
            inst,
            work: TempDir::new("inst-work"),
        };
        write_file(&s.root(), "mods/Existing/Existing.esp", b"existing");
        write_file(
            &s.root(),
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n+Existing\r\n",
        );
        write_file(
            &s.root(),
            "profiles/Default/plugins.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nExisting.esp\r\n",
        );
        write_file(
            &s.root(),
            "profiles/Default/loadorder.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nExisting.esp\r\n",
        );
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn archive(&self, name: &str) -> PathBuf {
        self.work.path().join(name)
    }

    fn install(&self, archive: &Path, extra: &[&str]) -> (i32, String, String) {
        let root = self.root();
        let mut args = vec![
            "install",
            archive.to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ];
        args.extend_from_slice(extra);
        nvmod(&args)
    }

    fn install_json(&self, archive: &Path, extra: &[&str]) -> (i32, Value) {
        let mut args = vec!["--json"];
        args.extend_from_slice(extra);
        let (code, out, err) = self.install(archive, &args);
        (
            code,
            serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out} / {err}")),
        )
    }

    fn rollback(&self) -> (i32, String, String) {
        nvmod(&["rollback", "--instance", self.root().to_str().unwrap()])
    }

    fn text(&self, relative: &str) -> String {
        String::from_utf8_lossy(&std::fs::read(self.root().join(relative)).unwrap()).into_owned()
    }

    fn state(&self) -> std::collections::BTreeMap<String, Vec<u8>> {
        snapshot(&self.root())
    }
}

fn lines(text: &str) -> Vec<&str> {
    text.split("\r\n").filter(|l| !l.is_empty()).collect()
}

