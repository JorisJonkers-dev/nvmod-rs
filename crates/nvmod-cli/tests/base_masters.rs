//! The masters of the base copy in a Profile: what `nvmod profile create` lists, and what the Doctor and
//! `nvmod plugins enable` do for a Profile that was made without them. The base copies are synthetic: plugin
//! files with generated headers and fake content; nothing is game data.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file};
use nvmod_testkit::{covers, ids};
use serde_json::{Value, json};
use std::path::PathBuf;
use std::process::Command;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";
const CODE: &str = "loadorder.base-master-unlisted";

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    base_dir: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// An Instance of a base copy whose `Data` holds `FalloutNV.esm` and the given files (each a master header).
    fn new(data: &[&str]) -> Scratch {
        let base = TempDir::new("bm-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        for name in data {
            write_file(
                base.path(),
                &format!("Data/{name}"),
                &PluginBuilder::master().build(),
            );
        }
        let inst = TempDir::new("bm-inst");
        let s = Scratch {
            base_dir: base,
            inst,
        };
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            s.base_dir.path().to_str().unwrap(),
            "--instance",
            s.root().to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn run(&self, args: &[&str]) -> (i32, String, String) {
        let root = self.root();
        let mut all = vec![args[0]];
        all.extend_from_slice(&args[1..]);
        all.extend_from_slice(&["--instance", root.to_str().unwrap()]);
        nvmod(&all)
    }

    fn create(&self, name: &str) {
        let (code, _, err) = self.run(&["profile", "create", "--name", name]);
        assert_eq!(code, 0, "{err}");
    }

    fn list_file(&self, profile: &str, file: &str) -> String {
        std::fs::read_to_string(self.root().join("profiles").join(profile).join(file)).unwrap()
    }

    fn plugins(&self, profile: &str) -> Vec<Value> {
        let (code, out, err) = self.run(&["plugins", "list", "--profile", profile, "--json"]);
        assert_eq!(code, 0, "{err}");
        let report: Value = serde_json::from_str(&out).unwrap();
        report["plugins"].as_array().unwrap().clone()
    }

    fn findings(&self, code: &str) -> Vec<Value> {
        let (_, out, err) = self.run(&["doctor", "--json"]);
        let report: Value = serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {err}"));
        report["findings"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|f| f["code"] == code)
            .cloned()
            .collect()
    }
}

fn names(rows: &[Value]) -> Vec<&str> {
    rows.iter().map(|r| r["name"].as_str().unwrap()).collect()
}

const ALL: [&str; 9] = [
    "DeadMoney.esm",
    "HonestHearts.esm",
    "OldWorldBlues.esm",
    "LonesomeRoad.esm",
    "GunRunnersArsenal.esm",
    "CaravanPack.esm",
    "ClassicPack.esm",
    "MercenaryPack.esm",
    "TribalPack.esm",
];

#[test]
fn a_new_profile_lists_every_master_of_the_base_copy_active_and_in_game_order() {
    covers(&[ids::instance::init::BASE_MASTERS_LISTED]);
    // Written in a scrambled order and in lower case, as a Steam copy has them.
    let lower: Vec<String> = ALL.iter().rev().map(|n| n.to_ascii_lowercase()).collect();
    let files: Vec<&str> = lower.iter().map(String::as_str).collect();
    let s = Scratch::new(&files);
    s.create("Default");
    let mut want = String::from(HEADER);
    want += "FalloutNV.esm\r\n";
    for name in ALL {
        want.push_str(name);
        want.push_str("\r\n");
    }
    assert_eq!(s.list_file("Default", "plugins.txt"), want);
    assert_eq!(s.list_file("Default", "loadorder.txt"), want);
    let rows = s.plugins("Default");
    assert_eq!(rows.len(), 10);
    assert!(rows.iter().all(|r| r["active"] == true));
    assert_eq!(rows[0]["name"], "FalloutNV.esm");
    assert_eq!(rows[0]["forced"], true);
    assert_eq!(rows[5]["name"], "GunRunnersArsenal.esm");
    assert_eq!(rows[9]["name"], "TribalPack.esm");
    assert_eq!(s.findings(CODE), Vec::<Value>::new());
}

#[test]
fn a_base_copy_without_dlc_still_gives_one_plugin() {
    let s = Scratch::new(&[]);
    s.create("Default");
    assert_eq!(
        s.list_file("Default", "plugins.txt"),
        format!("{HEADER}FalloutNV.esm\r\n")
    );
    assert_eq!(s.plugins("Default").len(), 1);
    assert_eq!(s.findings(CODE), Vec::<Value>::new());
}

#[test]
fn only_the_masters_that_are_present_are_listed_and_the_others_are_ignored() {
    let s = Scratch::new(&[
        "OLDWORLDBLUES.ESM",
        "deadmoney.esm",
        "Unrelated.esm",
        "Mod.esp",
    ]);
    s.create("Default");
    let rows = s.plugins("Default");
    assert_eq!(
        names(&rows),
        ["FalloutNV.esm", "DeadMoney.esm", "OldWorldBlues.esm"]
    );
}

#[test]
fn each_profile_made_reads_the_base_copy_as_it_is_then() {
    let s = Scratch::new(&["DeadMoney.esm"]);
    s.create("Early");
    write_file(
        s.base_dir.path(),
        "Data/HonestHearts.esm",
        &PluginBuilder::master().build(),
    );
    s.create("Late");
    assert_eq!(
        names(&s.plugins("Early")),
        ["FalloutNV.esm", "DeadMoney.esm"]
    );
    assert_eq!(
        names(&s.plugins("Late")),
        ["FalloutNV.esm", "DeadMoney.esm", "HonestHearts.esm"]
    );
}

fn pair(positive: &[Value], negative: &[Value]) -> String {
    let mut text =
        serde_json::to_string_pretty(&json!({"positive": positive, "negative": negative})).unwrap();
    text.push('\n');
    text
}

fn golden(name: &str, actual: &str) {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/golden")
        .join(name);
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        std::fs::write(&path, actual).unwrap();
    }
    let expected = std::fs::read_to_string(&path).expect("golden file; run with UPDATE_GOLDEN=1");
    assert_eq!(
        actual, expected,
        "run with UPDATE_GOLDEN=1 and review the diff"
    );
}

#[test]
fn the_doctor_names_base_masters_an_existing_profile_does_not_list_and_the_repair_fixes_it() {
    covers(&[ids::doctor::checks::BASE_MASTERS_REPAIR]);
    let s = Scratch::new(&["DeadMoney.esm", "HonestHearts.esm", "TribalPack.esm"]);
    s.create("Default");
    // A Profile as the earlier versions made it: the base game's master only, plus a plugin of a Mod.
    let old = format!("{HEADER}FalloutNV.esm\r\nTribalPack.esm\r\nMod.esp\r\n");
    write_file(&s.root(), "profiles/Default/plugins.txt", old.as_bytes());
    write_file(&s.root(), "profiles/Default/loadorder.txt", old.as_bytes());
    let positive = s.findings(CODE);
    assert_eq!(positive.len(), 1, "{positive:?}");
    assert_eq!(positive[0]["severity"], "warning");
    assert_eq!(positive[0]["subject"], "Default");
    let message = positive[0]["message"].as_str().unwrap();
    assert!(
        message.contains("DeadMoney.esm, HonestHearts.esm")
            && !message.contains("TribalPack.esm that"),
        "{message}"
    );
    assert!(
        message.contains(
            "`nvmod plugins enable DeadMoney.esm HonestHearts.esm --instance <dir> --profile Default`"
        ),
        "{message}"
    );
    // Nothing was rewritten by looking.
    assert_eq!(s.list_file("Default", "plugins.txt"), old);

    // The repair the finding names: each master goes to its place among the base masters.
    let (code, _, err) = s.run(&[
        "plugins",
        "enable",
        "DeadMoney.esm",
        "HonestHearts.esm",
        "--profile",
        "Default",
    ]);
    assert_eq!(code, 0, "{err}");
    let rows = s.plugins("Default");
    assert_eq!(
        names(&rows),
        [
            "FalloutNV.esm",
            "DeadMoney.esm",
            "HonestHearts.esm",
            "TribalPack.esm",
            "Mod.esp"
        ]
    );
    assert!(rows.iter().take(4).all(|r| r["active"] == true));
    let negative = s.findings(CODE);
    assert_eq!(negative, Vec::<Value>::new());
    golden("base-master-unlisted.json", &pair(&positive, &negative));
}

#[test]
fn a_master_that_is_listed_but_inactive_is_a_choice_and_not_reported() {
    let s = Scratch::new(&["DeadMoney.esm"]);
    s.create("Default");
    write_file(
        &s.root(),
        "profiles/Default/plugins.txt",
        format!("{HEADER}FalloutNV.esm\r\n").as_bytes(),
    );
    assert_eq!(s.findings(CODE), Vec::<Value>::new());
}
