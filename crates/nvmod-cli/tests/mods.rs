//! `nvmod mods`, run as a program against a scratch Instance made by `nvmod init`. No game data is used.

use nvmod_testkit::{BaseBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

fn nvmod(args: &[&str]) -> (i32, String, String) {
    nvmod_env(args, &[])
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

const MODLIST: &[u8] =
    b"# This file was automatically generated by Mod Organizer.\r\n+Gamma\r\n-Beta\r\n+Alpha\r\n";

impl Scratch {
    /// Mods Alpha, Beta, Gamma (Gamma wins a conflict over Alpha) and `Ghost` listed without a folder; staged.
    fn new(staged: bool) -> Scratch {
        let base = TempDir::new("mods-base");
        BaseBuilder::steam().write(base.path());
        let inst = TempDir::new("mods-inst");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            inst.path().join("fnv").to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let s = Scratch { _base: base, inst };
        let root = s.root();
        for m in ["Alpha", "Beta", "Gamma"] {
            write_file(&root, &format!("mods/{m}/Textures/Dirt.dds"), m.as_bytes());
        }
        write_file(&root, "profiles/Default/modlist.txt", MODLIST);
        if staged {
            let (code, _, err) = nvmod(&["stage", "--instance", root.to_str().unwrap()]);
            assert_eq!(code, 0, "{err}");
        }
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn run(&self, args: &[&str]) -> (i32, String, String) {
        self.run_env(args, &[])
    }

    fn run_env(&self, args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
        let root = self.root();
        let mut all = vec!["mods"];
        all.extend_from_slice(args);
        all.extend_from_slice(&["--instance", root.to_str().unwrap()]);
        nvmod_env(&all, env)
    }

    fn modlist(&self) -> Vec<u8> {
        fs::read(self.root().join("profiles/Default/modlist.txt")).unwrap()
    }

    fn staged_dirt(&self) -> Vec<u8> {
        fs::read(self.root().join("staging/Default/data/textures/dirt.dds")).unwrap()
    }
}

fn names(v: &Value) -> Vec<String> {
    v["mods"]
        .as_array()
        .unwrap()
        .iter()
        .map(|m| {
            format!(
                "{}{}",
                m["state"].as_str().unwrap().chars().next().unwrap(),
                m["name"].as_str().unwrap()
            )
        })
        .collect()
}

#[test]
fn list_prints_the_priority_order_as_json_and_text() {
    let s = Scratch::new(true);
    let (code, out, err) = s.run(&["list", "--json"]);
    assert_eq!(code, 0, "{err}");
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["profile"], "Default");
    assert_eq!(names(&v), ["eGamma", "dBeta", "eAlpha"]);
    assert_eq!(v["mods"][0]["position"], 1);
    assert_eq!(v["mods"][0]["installed"], true);
    let (code, out, _) = s.run(&["list"]);
    assert_eq!(code, 0);
    assert!(out.contains("+ Gamma") && out.contains("- Beta"), "{out}");
}

#[test]
fn disable_and_enable_edit_only_modlist_stage_again_and_roll_back() {
    let s = Scratch::new(true);
    assert_eq!(s.staged_dirt(), b"Gamma");
    let (code, out, err) = s.run(&["disable", "Gamma", "--json"]);
    assert_eq!(code, 0, "{err}");
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["status"], "changed");
    assert_eq!(v["changed"][0], "Gamma");
    assert!(v["journal"].is_string());
    assert_eq!(
        s.modlist(),
        b"# This file was automatically generated by Mod Organizer.\r\n-Gamma\r\n-Beta\r\n+Alpha\r\n"
    );
    assert_eq!(s.staged_dirt(), b"Alpha", "the Staging tree follows");
    let (code, out, err) = s.run(&["enable", "Beta", "Gamma", "--json"]);
    assert_eq!(code, 0, "{err}");
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["changed"].as_array().unwrap().len(), 2);
    assert_eq!(s.staged_dirt(), b"Gamma");
    // Both changes come back, newest first.
    for expected in [
        b"# This file was automatically generated by Mod Organizer.\r\n-Gamma\r\n-Beta\r\n+Alpha\r\n".to_vec(),
        MODLIST.to_vec(),
    ] {
        let (code, out, err) = nvmod(&["rollback", "--instance", s.root().to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
        assert!(out.contains("undid the Mods change"), "{out}");
        assert_eq!(s.modlist(), expected);
    }
    assert_eq!(s.staged_dirt(), b"Gamma");
}

#[test]
fn reorder_moves_one_entry() {
    let s = Scratch::new(true);
    let (code, out, err) = s.run(&["reorder", "Alpha", "--top", "--json"]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(
        names(&serde_json::from_str(&out).unwrap()),
        ["eAlpha", "eGamma", "dBeta"]
    );
    assert_eq!(s.staged_dirt(), b"Alpha");
    let (code, _, err) = s.run(&["reorder", "Alpha", "--after", "Beta"]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(
        s.modlist(),
        b"# This file was automatically generated by Mod Organizer.\r\n+Gamma\r\n-Beta\r\n+Alpha\r\n"
    );
    let (code, _, err) = s.run(&["reorder", "Gamma", "--position", "2"]);
    assert_eq!(code, 0, "{err}");
    let (code, _, err) = s.run(&["reorder", "Gamma", "--bottom"]);
    assert_eq!(code, 0, "{err}");
    let (code, out, _) = s.run(&["list", "--json"]);
    assert_eq!(code, 0);
    assert_eq!(
        names(&serde_json::from_str(&out).unwrap()),
        ["dBeta", "eAlpha", "eGamma"]
    );
    let (code, out, _) = s.run(&["reorder", "Beta", "--top", "--json"]);
    assert_eq!(code, 0);
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["status"], "unchanged");
    assert!(v["journal"].is_null());
}

#[test]
fn a_dry_run_writes_nothing() {
    let s = Scratch::new(true);
    let before = snapshot(&s.root());
    let (code, out, err) = s.run(&["disable", "Gamma", "--dry-run", "--json"]);
    assert_eq!(code, 0, "{err}");
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["status"], "dry-run");
    assert_eq!(v["dry_run"], true);
    assert_eq!(names(&v), ["dGamma", "dBeta", "eAlpha"]);
    let (code, _, err) = s.run(&["reorder", "Alpha", "--top", "--dry-run"]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(snapshot(&s.root()), before);
}

#[test]
fn a_profile_without_staging_is_not_staged_by_a_change() {
    let s = Scratch::new(false);
    let (code, out, err) = s.run(&["disable", "Alpha", "--json"]);
    assert_eq!(code, 0, "{err}");
    let v: Value = serde_json::from_str(&out).unwrap();
    assert!(v["staged_files"].is_null());
    assert!(!s.root().join("staging").join("Default").exists());
}

#[test]
fn a_failing_step_puts_everything_back_and_exits_4() {
    for step in ["lists", "stage"] {
        let s = Scratch::new(true);
        let (code, _, err) = s.run_env(&["disable", "Gamma"], &[("NVMOD_FAIL_AT", step)]);
        assert_eq!(code, 4, "{step}: {err}");
        assert!(err.contains("rolled back"), "{err}");
        assert_eq!(s.modlist(), MODLIST, "{step}");
        assert_eq!(s.staged_dirt(), b"Gamma", "{step}");
    }
}

#[test]
fn refusals_exit_2_and_usage_errors_exit_5() {
    let s = Scratch::new(true);
    let before = snapshot(&s.root());
    for args in [
        &["enable", "Nope"][..],
        &["disable", "Nope"],
        &["reorder", "Alpha", "--position", "9"],
        &["reorder", "Alpha", "--before", "Alpha"],
        &["enable", "Alpha", "--profile", "Missing"],
    ] {
        let (code, _, err) = s.run(args);
        assert_eq!(code, 2, "{args:?}: {err}");
    }
    assert_eq!(snapshot(&s.root()), before, "a refusal changes nothing");
    // A listed Mod without a folder cannot be enabled.
    write_file(
        &s.root(),
        "profiles/Default/modlist.txt",
        b"-Ghost\r\n+Alpha\r\n",
    );
    let (code, _, err) = s.run(&["enable", "Ghost"]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains("folder"), "{err}");
    for args in [
        &[][..],
        &["frob"],
        &["list", "extra"],
        &["enable"],
        &["reorder", "Alpha"],
        &["reorder", "Alpha", "--top", "--bottom"],
        &["reorder", "Alpha", "--position", "x"],
        &["list", "--bogus"],
    ] {
        let (code, _, err) = s.run(args);
        assert_eq!(code, 5, "{args:?}: {err}");
    }
    let (code, _, _) = nvmod(&["mods", "list"]);
    assert_eq!(code, 5);
}
