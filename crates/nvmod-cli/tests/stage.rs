#[cfg(unix)]
#[test]
fn files_are_hard_linked_where_the_filesystem_allows() {
    use std::os::unix::fs::MetadataExt;
    let s = Scratch::new();
    s.mod_file("Mod", "Meshes/New.nif", b"new");
    s.modlist("Default", "+Mod\r\n");
    let (code, out, _) = s.stage(&[]);
    assert_eq!(code, 0);
    let from_mod = std::fs::metadata(s.root().join("mods/Mod/Meshes/New.nif")).unwrap();
    let staged = std::fs::metadata(s.staged("Default", "meshes/new.nif")).unwrap();
    assert_eq!(from_mod.ino(), staged.ino());
    assert!(staged.nlink() >= 2);
    let from_base = std::fs::metadata(s.base.path().join("Data/Meshes/Rock.nif")).unwrap();
    let staged = std::fs::metadata(s.staged("Default", "meshes/rock.nif")).unwrap();
    assert_eq!(from_base.ino(), staged.ino());
    assert!(out.contains("hard link"), "{out}");
}

#[test]
fn where_links_cannot_be_made_the_files_are_copied_and_the_doctor_reports_it() {
    let s = Scratch::new();
    s.mod_file("Mod", "Meshes/New.nif", b"new");
    s.modlist("Default", "+Mod\r\n");
    let (code, out, _) = s.stage(&["--copy"]);
    assert_eq!(code, 0, "{out}");
    assert!(out.contains("copied"), "{out}");
    assert_eq!(
        std::fs::read(s.staged("Default", "meshes/new.nif")).unwrap(),
        b"new"
    );
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        assert_eq!(
            std::fs::metadata(s.staged("Default", "meshes/new.nif"))
                .unwrap()
                .nlink(),
            1
        );
    }
    let (code, report) = s.doctor(&[]);
    assert_eq!(code, 0, "a warning does not fail by default");
    assert!(
        codes(&report).contains(&"stage.degraded".to_owned()),
        "{report}"
    );
    let (code, _) = s.doctor(&["--fail-on", "warning"]);
    assert_eq!(code, 1);
}

