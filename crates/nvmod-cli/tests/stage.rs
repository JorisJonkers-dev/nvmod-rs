//! `nvmod stage` and the Doctor's view of the Staging tree, run as a program against a scratch Instance made by
//! `nvmod init` from a synthetic base copy. Mods and profiles are written as files, in code.

use nvmod_testkit::{BaseBuilder, TempDir, case_sensitive, snapshot, write_file};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// A Steam base copy with two Data files, and an initialised Instance with an empty profile `Default`.
    fn new() -> Scratch {
        let base = TempDir::new("stage-base");
        BaseBuilder::steam().write(base.path());
        // The vanilla target needs xNVSE's DLL in the base copy (ticket 29).
        write_file(
            base.path(),
            "nvse_1_4.dll",
            &nvmod_testkit::PeBuilder::dll().build(),
        );
        write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
        write_file(base.path(), "Data/Fallout - Meshes.bsa", b"base bsa");
        let inst = TempDir::new("stage-inst");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            inst.path().join("fnv").to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let s = Scratch { base, inst };
        s.modlist("Default", "");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn modlist(&self, profile: &str, lines: &str) {
        write_file(
            &self.root(),
            &format!("profiles/{profile}/modlist.txt"),
            format!("# This file was automatically generated by Mod Organizer.\r\n{lines}")
                .as_bytes(),
        );
    }

    fn mod_file(&self, name: &str, path: &str, bytes: &[u8]) {
        write_file(&self.root(), &format!("mods/{name}/{path}"), bytes);
    }

    fn staged(&self, profile: &str, path: &str) -> PathBuf {
        self.root()
            .join("staging")
            .join(profile)
            .join("data")
            .join(path)
    }

    fn stage(&self, extra: &[&str]) -> (i32, String, String) {
        let root = self.root();
        let mut args = vec!["stage", "--instance", root.to_str().unwrap()];
        args.extend_from_slice(extra);
        nvmod(&args)
    }

    fn doctor(&self, extra: &[&str]) -> (i32, Value) {
        let root = self.root();
        let mut args = vec!["doctor", "--instance", root.to_str().unwrap(), "--json"];
        args.extend_from_slice(extra);
        let (code, out, err) = nvmod(&args);
        (
            code,
            serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out} / {err}")),
        )
    }
}

fn all_paths(dir: &Path) -> Vec<String> {
    snapshot(dir).into_keys().collect()
}

fn codes(report: &Value) -> Vec<String> {
    report["findings"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["code"].as_str().unwrap().to_owned())
        .collect()
}

#[test]
fn every_path_of_the_staging_tree_is_lowercase_and_holds_game_files_and_mods() {
    let s = Scratch::new();
    s.mod_file("Texture Pack", "Textures/Landscape/Dirt.DDS", b"dirt");
    s.mod_file("Texture Pack", "Fallout - Textures.BSA", b"tex bsa");
    s.mod_file("Texture Pack", "meta.ini", b"[General]\nmodid=1\n");
    s.modlist("Default", "+Texture Pack\r\n");
    let (code, _, err) = s.stage(&[]);
    assert_eq!(code, 0, "{err}");
    let tree = s.root().join("staging/Default/data");
    let paths = all_paths(&tree);
    assert!(paths.len() > 3, "{paths:?}");
    for path in &paths {
        assert_eq!(path, &path.to_lowercase(), "{path}");
    }
    assert_eq!(
        std::fs::read(s.staged("Default", "meshes/rock.nif")).unwrap(),
        b"base rock"
    );
    assert_eq!(
        std::fs::read(s.staged("Default", "falloutnv.esm")).unwrap(),
        b"synthetic master"
    );
    assert_eq!(
        std::fs::read(s.staged("Default", "textures/landscape/dirt.dds")).unwrap(),
        b"dirt"
    );
    assert!(
        !s.staged("Default", "meta.ini").exists(),
        "MO2 metadata is not a game file"
    );
}

#[test]
fn the_game_executable_never_enters_the_staging_tree() {
    let s = Scratch::new();
    assert_eq!(s.stage(&[]).0, 0);
    assert!(
        !all_paths(&s.root().join("staging"))
            .iter()
            .any(|p| p.to_lowercase().ends_with(".exe")),
        "no executable is linked or copied"
    );
}

#[test]
fn where_two_mods_provide_a_file_the_later_mod_in_the_load_order_wins() {
    let s = Scratch::new();
    // modlist.txt lists the highest priority first; the load order is the reverse, so the last mod wins.
    s.mod_file("Early", "Meshes/Rock.nif", b"early");
    s.mod_file("Late", "meshes/rock.NIF", b"late");
    s.mod_file("Early", "Only/Early.txt", b"e");
    s.modlist("Default", "+Late\r\n+Early\r\n");
    assert_eq!(s.stage(&[]).0, 0);
    assert_eq!(
        std::fs::read(s.staged("Default", "meshes/rock.nif")).unwrap(),
        b"late"
    );
    assert_eq!(
        std::fs::read(s.staged("Default", "only/early.txt")).unwrap(),
        b"e"
    );

    s.modlist("Default", "+Early\r\n+Late\r\n");
    assert_eq!(s.stage(&[]).0, 0);
    assert_eq!(
        std::fs::read(s.staged("Default", "meshes/rock.nif")).unwrap(),
        b"early"
    );
}

