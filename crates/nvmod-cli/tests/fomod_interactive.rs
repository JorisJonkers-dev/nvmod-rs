//! `nvmod install --interactive`, saved answers, `mods reinstall|reconfigure` and `--on-conflict`, run as a program
//! against a scratch Instance. Archives are built in code; no mod data is used.

use nvmod_testkit::{BaseBuilder, TempDir, ZipBuilder, snapshot, write_file};
use nvmod_testkit::{covers, ids};
use serde_json::Value;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn nvmod_in(args: &[&str], stdin: &str) -> (i32, String, String) {
    let mut child = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    child
        .stdin
        .take()
        .unwrap()
        .write_all(stdin.as_bytes())
        .unwrap();
    let out = child.wait_with_output().unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

fn nvmod(args: &[&str]) -> (i32, String, String) {
    nvmod_in(args, "")
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
    work: TempDir,
}

impl Scratch {
    fn new() -> Scratch {
        let base = TempDir::new("fi-base");
        BaseBuilder::steam().write(base.path());
        let inst = TempDir::new("fi-inst");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            inst.path().join("fnv").to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let s = Scratch {
            _base: base,
            inst,
            work: TempDir::new("fi-work"),
        };
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        write_file(&s.root(), "profiles/Default/modlist.txt", header.as_bytes());
        let masters = format!("{header}FalloutNV.esm\r\n");
        write_file(
            &s.root(),
            "profiles/Default/plugins.txt",
            masters.as_bytes(),
        );
        write_file(
            &s.root(),
            "profiles/Default/loadorder.txt",
            masters.as_bytes(),
        );
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn arg(&self) -> String {
        self.root().to_str().unwrap().to_owned()
    }

    fn archive(&self, name: &str) -> PathBuf {
        self.work.path().join(name)
    }

    fn mod_files(&self, name: &str) -> Vec<String> {
        let base = self.root().join("mods").join(name);
        let mut found = Vec::new();
        walk(&base, &base, &mut found);
        found.sort();
        found
    }
}

fn walk(base: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            walk(base, &path, out);
        } else {
            let rel = path.strip_prefix(base).unwrap();
            let rel = rel.to_string_lossy().replace('\\', "/");
            if rel != "meta.ini" && !rel.starts_with(".nvmod/") {
                out.push(rel);
            }
        }
    }
}

const MULTI: &str = r#"<config><moduleName>Multi</moduleName>
  <requiredInstallFiles><file source="core.txt" destination="core.txt"/></requiredInstallFiles>
  <installSteps order="Explicit">
    <installStep name="Look"><optionalFileGroups order="Explicit">
      <group name="Style" type="SelectExactlyOne"><plugins order="Explicit">
        <plugin name="Red"><description>red one</description>
          <files><file source="red.txt" destination="style.txt"/></files>
          <conditionFlags><flag name="style">red</flag></conditionFlags>
          <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
        <plugin name="Blue"><files><file source="blue.txt" destination="style.txt"/></files>
          <conditionFlags><flag name="style">blue</flag></conditionFlags>
          <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
      </plugins></group>
    </optionalFileGroups></installStep>
    <installStep name="Extras"><visible><dependencies><flagDependency flag="style" value="red"/></dependencies></visible>
      <optionalFileGroups order="Explicit">
        <group name="Bits" type="SelectAny"><plugins order="Explicit">
          <plugin name="Glow"><files><file source="glow.txt" destination="extras/glow.txt"/></files>
            <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
          <plugin name="Dull"><files><file source="dull.txt" destination="extras/dull.txt"/></files>
            <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
        </plugins></group>
      </optionalFileGroups></installStep>
  </installSteps></config>"#;

fn multi_zip(path: &Path, escape: bool) {
    let mut zip = ZipBuilder::new()
        .file("fomod/ModuleConfig.xml", MULTI.as_bytes())
        .file("core.txt", b"core")
        .file("red.txt", b"red")
        .file("blue.txt", b"blue")
        .file("glow.txt", b"glow")
        .file("dull.txt", b"dull");
    if escape {
        zip = zip.file("extra.txt", b"x");
    }
    zip.write(path);
}

#[test]
fn a_scripted_stdin_session_installs_exactly_the_planned_files_and_saves_the_answers() {
    covers(&[ids::mods::fomod::TERMINAL_SESSION]);
    let s = Scratch::new();
    let zip = s.archive("Multi.zip");
    multi_zip(&zip, false);
    let (code, out, err) = nvmod_in(
        &[
            "install",
            zip.to_str().unwrap(),
            "--instance",
            &s.arg(),
            "--interactive",
        ],
        "1\n1\n",
    );
    assert_eq!(code, 0, "{out} / {err}");
    assert!(
        out.contains("Step 1: Look") && out.contains("red one"),
        "{out}"
    );
    assert!(out.contains("Step 2: Extras"), "{out}");
    assert_eq!(
        s.mod_files("Multi"),
        ["core.txt", "extras/glow.txt", "style.txt"]
    );
    let saved: Value = serde_json::from_slice(
        &std::fs::read(s.root().join("mods/Multi/.nvmod/fomod-answers.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(saved["schema_version"], 1);
    assert_eq!(saved["answers"]["Look/Style"][0], "Red");
    assert_eq!(saved["answers"]["Extras/Bits"][0], "Glow");
}

#[test]
fn a_bad_line_is_asked_again_and_the_end_of_input_refuses_without_writing() {
    let s = Scratch::new();
    let zip = s.archive("Multi.zip");
    multi_zip(&zip, false);
    let args = [
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &s.arg(),
        "--interactive",
    ];
    let (code, out, _) = nvmod_in(&args, "9\n1,2\n2\n");
    assert_eq!(code, 0, "{out}");
    assert!(out.contains("there is no option 9") && out.contains("choose 1 to 1"));
    assert_eq!(s.mod_files("Multi"), ["core.txt", "style.txt"]);
    let s2 = Scratch::new();
    let before2 = snapshot(&s2.root());
    let args2 = [
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &s2.arg(),
        "--interactive",
    ];
    let (code, _, err) = nvmod_in(&args2, "1\n");
    assert_eq!(code, 2, "{err}");
    assert_eq!(snapshot(&s2.root()), before2);
}

#[test]
fn reinstall_replays_and_reconfigure_with_one_changed_answer_changes_only_those_files() {
    covers(&[ids::mods::fomod::REINSTALL_RECONFIGURE]);
    let s = Scratch::new();
    let zip = s.archive("Multi.zip");
    multi_zip(&zip, false);
    let inst = s.arg();
    let (code, _, err) = nvmod_in(
        &[
            "install",
            zip.to_str().unwrap(),
            "--instance",
            &inst,
            "--interactive",
        ],
        "1\n1\n",
    );
    assert_eq!(code, 0, "{err}");
    let first = s.mod_files("Multi");

    let (code, out, err) = nvmod(&["mods", "reinstall", "Multi", "--instance", &inst]);
    assert_eq!(code, 0, "{out} / {err}");
    assert_eq!(
        s.mod_files("Multi"),
        first,
        "a replay yields the same files"
    );

    // Same style, other extra: only the extras file changes.
    let (code, out, err) = nvmod_in(
        &[
            "mods",
            "reconfigure",
            "Multi",
            "--instance",
            &inst,
            "--interactive",
        ],
        "\n2\n",
    );
    assert_eq!(code, 0, "{out} / {err}");
    assert!(
        out.contains("[x] Red"),
        "the previous choice is ticked: {out}"
    );
    assert_eq!(
        s.mod_files("Multi"),
        ["core.txt", "extras/dull.txt", "style.txt"]
    );
    assert_eq!(
        std::fs::read(s.root().join("mods/Multi/style.txt")).unwrap(),
        b"red"
    );
    let saved: Value = serde_json::from_slice(
        &std::fs::read(s.root().join("mods/Multi/.nvmod/fomod-answers.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(saved["answers"]["Extras/Bits"][0], "Dull");
}

#[test]
#[allow(clippy::too_many_lines)]
fn replace_keeps_priority_state_and_notes_and_merge_and_rename_leave_the_other_files_alone() {
    let s = Scratch::new();
    let zip = s.archive("Multi.zip");
    multi_zip(&zip, false);
    let answers = s.archive("a.json");
    std::fs::write(&answers, br#"{"answers": {"Look/Style": ["Blue"]}}"#).unwrap();
    let inst = s.arg();
    let a = answers.to_str().unwrap();
    let (code, _, err) = nvmod(&[
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &inst,
        "--answers",
        a,
    ]);
    assert_eq!(code, 0, "{err}");
    // A second Mod installs above it; then a note in meta.ini and a stray file of the first.
    let other = s.archive("Other.zip");
    ZipBuilder::new().file("o.txt", b"o").write(&other);
    let (code, _, err) = nvmod(&["install", other.to_str().unwrap(), "--instance", &inst]);
    assert_eq!(code, 0, "{err}");
    let modlist = s.root().join("profiles/Default/modlist.txt");
    let meta = s.root().join("mods/Multi/meta.ini");
    let mut ini = std::fs::read_to_string(&meta).unwrap_or_default();
    ini.push_str("\n[General]\nnotes=keep me\n");
    std::fs::write(&meta, ini).unwrap();
    write_file(&s.root(), "mods/Multi/mine.txt", b"mine");
    let list_before = std::fs::read_to_string(&modlist).unwrap();

    let (code, _, err) = nvmod(&[
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &inst,
        "--answers",
        a,
    ]);
    assert_eq!(
        code, 2,
        "a name clash is refused without --on-conflict: {err}"
    );

    let (code, out, err) = nvmod(&[
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &inst,
        "--answers",
        a,
        "--on-conflict",
        "replace",
    ]);
    assert_eq!(code, 0, "{out} / {err}");
    assert_eq!(
        std::fs::read_to_string(&modlist).unwrap(),
        list_before,
        "priority and state kept"
    );
    assert!(
        std::fs::read_to_string(&meta)
            .unwrap()
            .contains("notes=keep me")
    );
    assert!(
        !s.root().join("mods/Multi/mine.txt").exists(),
        "replace removes the old files"
    );

    write_file(&s.root(), "mods/Multi/mine.txt", b"mine");
    let (code, out, err) = nvmod(&[
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &inst,
        "--answers",
        a,
        "--on-conflict",
        "merge",
    ]);
    assert_eq!(code, 0, "{out} / {err}");
    assert!(
        s.root().join("mods/Multi/mine.txt").is_file(),
        "merge keeps the old files"
    );

    let (code, out, err) = nvmod(&[
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &inst,
        "--answers",
        a,
        "--on-conflict",
        "rename",
    ]);
    assert_eq!(code, 0, "{out} / {err}");
    assert!(s.root().join("mods/Multi 2/style.txt").is_file());

    let (code, _, err) = nvmod(&[
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &inst,
        "--on-conflict",
        "sideways",
    ]);
    assert_eq!(code, 5, "{err}");
}

#[test]
fn a_destination_that_climbs_out_of_the_mod_folder_is_refused_and_writes_nothing() {
    covers(&[ids::mods::fomod::DESTINATION_ESCAPE_REFUSED]);
    let s = Scratch::new();
    let xml = r#"<config><requiredInstallFiles>
        <file source="x.txt" destination="..\..\escape.txt"/></requiredInstallFiles></config>"#;
    let zip = s.archive("Slip.zip");
    ZipBuilder::new()
        .file("fomod/ModuleConfig.xml", xml.as_bytes())
        .file("x.txt", b"x")
        .write(&zip);
    let before = snapshot(&s.root());
    let (code, out, err) = nvmod(&["install", zip.to_str().unwrap(), "--instance", &s.arg()]);
    assert_eq!(code, 2, "{out} / {err}");
    assert_eq!(snapshot(&s.root()), before);
    assert!(!s.root().join("escape.txt").exists());
}

#[test]
fn the_same_answers_always_yield_the_same_plan() {
    covers(&[ids::mods::fomod::SAME_ANSWERS_SAME_PLAN]);
    let s = Scratch::new();
    let zip = s.archive("Multi.zip");
    multi_zip(&zip, false);
    let answers = s.archive("a.json");
    std::fs::write(
        &answers,
        br#"{"answers": {"Look/Style": ["Red"], "Extras/Bits": ["Dull", "Glow"]}}"#,
    )
    .unwrap();
    let args = [
        "install",
        zip.to_str().unwrap(),
        "--instance",
        &s.arg(),
        "--answers",
        answers.to_str().unwrap(),
        "--dry-run",
        "--json",
    ];
    let (c1, a, _) = nvmod(&args);
    let (c2, b, _) = nvmod(&args);
    assert_eq!((c1, c2), (0, 0));
    let (a, b): (Value, Value) = (
        serde_json::from_str(&a).unwrap(),
        serde_json::from_str(&b).unwrap(),
    );
    assert_eq!(a["files"], b["files"]);
    assert_eq!(a["files"].as_array().unwrap().len(), 4);
}
