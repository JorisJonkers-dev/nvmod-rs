/// Kills the process group `pid` leads: the program and everything it started. Errors are ignored, since the group may
/// already be gone.
fn kill_group(pid: u32) {
    let _ = Command::new("kill")
        .args(["-KILL", "--", &format!("-{pid}")])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
}

/// A child that is killed with its group and reaped when it is dropped, so a panic (a failed assertion, a timeout)
/// leaves no orphan behind.
struct Reap(Option<Child>);

impl Drop for Reap {
    fn drop(&mut self) {
        if let Some(mut child) = self.0.take() {
            kill_group(child.id());
            let _ = child.wait();
        }
    }
}

/// Reads a pipe on a thread into a shared buffer, so the output so far can be reported when a run is killed.
fn collect(mut pipe: impl Read + Send + 'static) -> (Arc<Mutex<Vec<u8>>>, JoinHandle<()>) {
    let buf = Arc::new(Mutex::new(Vec::new()));
    let sink = Arc::clone(&buf);
    let handle = thread::spawn(move || {
        let mut chunk = [0u8; 4096];
        loop {
            match pipe.read(&mut chunk) {
                Ok(0) | Err(_) => break,
                Ok(n) => sink
                    .lock()
                    .expect("output buffer")
                    .extend_from_slice(&chunk[..n]),
            }
        }
    });
    (buf, handle)
}

fn text_of(buf: &Mutex<Vec<u8>>) -> String {
    String::from_utf8_lossy(&buf.lock().expect("output buffer")).into_owned()
}

/// Runs `nvmod` with the arguments in `root`, in an environment of the test's own making: nothing inherited but what
/// is set here. `PATH` is the scratch `bin` folder and the system folders, `HOME` and the state directory are in the
/// scratch root. The program leads its own process group, so a timeout or a panic kills all of it.
fn nvmod_in(root: &Path, args: &[&str]) -> (i32, String, String) {
    let root_str = root.display().to_string();
    let expanded: Vec<String> = args.iter().map(|a| a.replace(TMP, &root_str)).collect();
    let mut child = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(&expanded)
        .current_dir(root)
        .env_clear()
        .env("PATH", format!("{root_str}/bin:/usr/bin:/bin"))
        .env("HOME", root.join("home"))
        .env("NVMOD_STATE_DIR", root.join("state"))
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .process_group(0)
        .spawn()
        .expect("run nvmod");
    let pid = child.id();
    let (out_buf, out_thread) = collect(child.stdout.take().expect("stdout"));
    let (err_buf, err_thread) = collect(child.stderr.take().expect("stderr"));
    let mut reap = Reap(Some(child));
    let started = Instant::now();
    let status = loop {
        let polled = reap
            .0
            .as_mut()
            .expect("the child")
            .try_wait()
            .expect("poll nvmod");
        if let Some(status) = polled {
            break status;
        }
        if started.elapsed() > INVOCATION_TIMEOUT {
            kill_group(pid);
            panic!(
                "nvmod {expanded:?} did not finish within {}s and was killed; output so far:\nstdout:\n{}\nstderr:\n{}",
                INVOCATION_TIMEOUT.as_secs(),
                text_of(&out_buf),
                text_of(&err_buf)
            );
        }
        thread::sleep(Duration::from_millis(20));
    };
    // Whatever the program started and left in its group is killed too; the pipes then close.
    kill_group(pid);
    reap.0 = None;
    out_thread.join().expect("stdout reader");
    err_thread.join().expect("stderr reader");
    (
        status
            .code()
            .expect("an exit code (the run was killed by a signal)"),
        text_of(&out_buf),
        text_of(&err_buf),
    )
}

/// Replaces the release in nvmod's own lines: `nvmod <version>`, as a whole token, so `nvmod 0.8.1` becomes
/// `nvmod <VERSION>` and `nvmod 0.8.10` stays. Versions of tools, schemas and contracts are never replaced.
fn replace_nvmod_version(text: &str, version: &str) -> String {
    let needle = format!("nvmod {version}");
    let bytes = text.as_bytes();
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    while i < text.len() {
        if text[i..].starts_with(&needle) {
            let after = i + needle.len();
            let next = bytes.get(after).copied();
            let word = next.is_some_and(|c| c.is_ascii_alphanumeric());
            let dotted = next == Some(b'.') && bytes.get(after + 1).is_some_and(u8::is_ascii_digit);
            if !word && !dotted {
                let _ = write!(out, "nvmod {VERSION_TOKEN}");
                i = after;
                continue;
            }
        }
        let ch = text[i..].chars().next().expect("a char");
        out.push(ch);
        i += ch.len_utf8();
    }
    out
}

/// Replaces `YYYY-MM-DD` followed by `T` or a space and `hh:mm:ss`, with an optional fraction and zone, by `<TIME>`.
fn replace_timestamps(text: &str) -> String {
    let b = text.as_bytes();
    let digits = |s: usize, n: usize| (s..s + n).all(|k| b.get(k).is_some_and(u8::is_ascii_digit));
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    while i < b.len() {
        let stamp = digits(i, 4)
            && b.get(i + 4) == Some(&b'-')
            && digits(i + 5, 2)
            && b.get(i + 7) == Some(&b'-')
            && digits(i + 8, 2)
            && matches!(b.get(i + 10), Some(b'T' | b' '))
            && digits(i + 11, 2)
            && b.get(i + 13) == Some(&b':')
            && digits(i + 14, 2)
            && b.get(i + 16) == Some(&b':')
            && digits(i + 17, 2);
        if stamp {
            let mut end = i + 19;
            if b.get(end) == Some(&b'.') {
                end += 1;
                while b.get(end).is_some_and(u8::is_ascii_digit) {
                    end += 1;
                }
            }
            if b.get(end) == Some(&b'Z') {
                end += 1;
            } else if matches!(b.get(end), Some(b'+' | b'-'))
                && digits(end + 1, 2)
                && b.get(end + 3) == Some(&b':')
                && digits(end + 4, 2)
            {
                end += 6;
            }
            out.push_str(TIME_TOKEN);
            i = end;
        } else {
            let ch = text[i..].chars().next().expect("a char");
            out.push(ch);
            i += ch.len_utf8();
        }
    }
    out
}

/// Replaces a journal id (`<16 digits>-<6 digits>-<pid>`, which the run's clock and process make) by `<JOURNAL>`.
fn replace_journal_ids(text: &str) -> String {
    let b = text.as_bytes();
    let digits = |s: usize, n: usize| (s..s + n).all(|k| b.get(k).is_some_and(u8::is_ascii_digit));
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    while i < b.len() {
        let before_ok = i == 0 || !b[i - 1].is_ascii_alphanumeric();
        let mut end = i + 16;
        let id = before_ok
            && digits(i, 16)
            && b.get(i + 16) == Some(&b'-')
            && digits(i + 17, 6)
            && b.get(i + 23) == Some(&b'-')
            && {
                let pid = (i + 24..b.len())
                    .take_while(|&k| b[k].is_ascii_digit())
                    .count();
                end = i + 24 + pid;
                pid > 0
            };
        if id {
            out.push_str(JOURNAL_TOKEN);
            i = end;
        } else {
            let ch = text[i..].chars().next().expect("a char");
            out.push(ch);
            i += ch.len_utf8();
        }
    }
    out
}

/// Drops the lines the toolchain prints when a source build runs: cargo's progress, rustc's diagnostics and their
/// source snippets, and blank lines. What remains is nvmod's own standard error. Applied to standard error only.
fn drop_toolchain_output(text: &str) -> String {
    const PREFIXES: [&str; 22] = [
        "Compiling ",
        "Finished ",
        "Running ",
        "Fresh ",
        "Downloaded ",
        "Downloading ",
        "Locking ",
        "Updating ",
        "Checking ",
        "Blocking ",
        "Adding ",
        "Removing ",
        "warning:",
        "error:",
        "error[",
        "note:",
        "help:",
        "--> ",
        "|",
        "= ",
        "^",
        "For more information",
    ];
    let mut out = String::new();
    for line in text.lines() {
        let t = line.trim();
        if t.is_empty() || PREFIXES.iter().any(|p| t.starts_with(p)) {
            continue;
        }
        // A source snippet line: `12 | code`.
        let digits = t.bytes().take_while(u8::is_ascii_digit).count();
        if digits > 0 && t[digits..].starts_with(" |") {
            continue;
        }
        let _ = writeln!(out, "{line}");
    }
    out
}

/// The normaliser of one run. Its digest table is shared by standard output and standard error, so one digest is the
/// same token wherever it occurs in the run.
struct Norm {
    /// The scratch root as given and canonicalised (`/private/var` on macOS), longest first.
    roots: Vec<String>,
    /// The distinct digests seen so far, in order of first appearance.
    digests: Vec<String>,
}

impl Norm {
    fn new(root: &Path) -> Norm {
        let mut roots = vec![root.display().to_string()];
        if let Ok(canonical) = fs::canonicalize(root) {
            roots.push(canonical.display().to_string());
        }
        roots.sort_by_key(|r| std::cmp::Reverse(r.len()));
        roots.dedup();
        Norm {
            roots,
            digests: Vec::new(),
        }
    }

    /// Applies every rule of the README, in order, to one stream of one run.
    fn apply(&mut self, text: &str) -> String {
        let mut out = text.to_owned();
        for r in &self.roots {
            out = out.replace(r.as_str(), TMP);
        }
        // The fake release asset name carries the host platform, so it goes first.
        out = out.replace(FAKE_ASSET, ASSET_TOKEN);
        out = out.replace(&platform(), PLATFORM_TOKEN);
        out = replace_nvmod_version(&out, env!("CARGO_PKG_VERSION"));
        out = replace_journal_ids(&out);
        out = replace_timestamps(&out);
        out = self.replace_digests(&out);
        replace_loopback_port(&out)
    }

    /// Replaces each SHA-256 value (64 lowercase hex digits, as a whole word) by `<SHA256-n>`, where `n` numbers the
    /// distinct digests in order of first appearance. Equal digests keep the same number, so a wrong digest or a swapped
    /// pair still shows as a difference.
    fn replace_digests(&mut self, text: &str) -> String {
        let b = text.as_bytes();
        let is_hex = |c: u8| c.is_ascii_digit() || (b'a'..=b'f').contains(&c);
        let word = |c: u8| c.is_ascii_alphanumeric();
        let mut out = String::with_capacity(text.len());
        let mut i = 0;
        while i < b.len() {
            let whole = i + 64 <= b.len()
                && b[i..i + 64].iter().all(|&c| is_hex(c))
                && (i == 0 || !word(b[i - 1]))
                && b.get(i + 64).is_none_or(|&c| !word(c));
            if whole {
                let digest = &text[i..i + 64];
                let n = if let Some(p) = self.digests.iter().position(|d| d == digest) {
                    p + 1
                } else {
                    self.digests.push(digest.to_owned());
                    self.digests.len()
                };
                let _ = write!(out, "<SHA256-{n}>");
                i += 64;
            } else {
                let ch = text[i..].chars().next().expect("a char");
                out.push(ch);
                i += ch.len_utf8();
            }
        }
        out
    }
}

/// The port of the fake release server, which the OS picks, after `127.0.0.1:`.
fn replace_loopback_port(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(at) = rest.find("127.0.0.1:") {
        let (before, after) = rest.split_at(at + "127.0.0.1:".len());
        out.push_str(before);
        let digits = after.bytes().take_while(u8::is_ascii_digit).count();
        if digits > 0 {
            out.push_str(PORT_TOKEN);
        }
        rest = &after[digits..];
    }
    out.push_str(rest);
    out
}

/// A transcript as a value. Standard output is parsed when it is JSON, so comparisons ignore layout; text is kept as
/// lines. Standard error keeps nvmod's own lines only (see `drop_toolchain_output`).
fn transcript(case: &Case, root: &Path, code: i32, stdout: &str, stderr: &str) -> Value {
    let mut norm = Norm::new(root);
    let stdout = norm.apply(stdout);
    let stdout_value = match serde_json::from_str::<Value>(stdout.trim()) {
        Ok(value) => value,
        Err(_) => match ndjson(&stdout) {
            Some(events) => Value::Array(events),
            None => lines(&stdout),
        },
    };
    let stderr = norm.apply(&drop_toolchain_output(stderr));
    json!({
        "command": case.command,
        "args": case.args,
        "exit_code": code,
        "stdout": stdout_value,
        "stderr": lines(&stderr),
    })
}

/// Whether this run rewrites the transcripts. `NVMOD_BLESS` must be `1` or `true`: any other value, the empty string
/// included, fails. It is refused when `CI` is set, since a transcript is recorded on a workstation and reviewed in the
/// diff, never written by a pipeline.
fn bless_requested() -> bool {
    match std::env::var("NVMOD_BLESS") {
        Err(std::env::VarError::NotPresent) => false,
        Ok(v) if v == "1" || v == "true" => {
            assert!(
                std::env::var_os("CI").is_none(),
                "NVMOD_BLESS is refused when CI is set: record the transcripts on a workstation and review the diff"
            );
            true
        }
        Ok(v) => panic!("NVMOD_BLESS must be 1 or true, not {v:?}"),
        Err(e) => panic!("NVMOD_BLESS: {e}"),
    }
}

/// Standard output that is one JSON document per line (`--json` as a stream of events), as an array of documents.
fn ndjson(text: &str) -> Option<Vec<Value>> {
    let events: Option<Vec<Value>> = text
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str(l).ok())
        .collect();
    events.filter(|e| !e.is_empty())
}

/// Text as an array of lines, so a difference shows as the changed line.
fn lines(text: &str) -> Value {
    Value::Array(text.lines().map(|l| Value::String(l.to_owned())).collect())
}

fn record(case: &Case) -> Value {
    let dir = TempDir::new(&format!("baseline-{}-{}", case.command, case.name));
    let _keep = (case.setup)(dir.path());
    let (code, out, err) = nvmod_in(dir.path(), case.args);
    transcript(case, dir.path(), code, &out, &err)
}

fn baseline_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/baseline")
}

fn transcript_path(case: &Case) -> PathBuf {
    baseline_dir()
        .join(case.command)
        .join(format!("{}.json", case.name))
}

/// Lines of `old` and `new` as a diff: `-` for lines only in the transcript on disk, `+` for lines only in the run,
/// two lines of context around each change.
fn line_diff(old: &str, new: &str) -> String {
    if old.is_empty() && new.is_empty() {
        return String::new();
    }
    let a: Vec<&str> = old.lines().collect();
    let b: Vec<&str> = new.lines().collect();
    let mut lcs = vec![vec![0usize; b.len() + 1]; a.len() + 1];
    for i in (0..a.len()).rev() {
        for j in (0..b.len()).rev() {
            lcs[i][j] = if a[i] == b[j] {
                lcs[i + 1][j + 1] + 1
            } else {
                lcs[i + 1][j].max(lcs[i][j + 1])
            };
        }
    }
    let (mut i, mut j) = (0, 0);
    let mut lines: Vec<(char, &str)> = Vec::new();
    while i < a.len() || j < b.len() {
        if i < a.len() && j < b.len() && a[i] == b[j] {
            lines.push((' ', a[i]));
            i += 1;
            j += 1;
        } else if i < a.len() && (j == b.len() || lcs[i + 1][j] >= lcs[i][j + 1]) {
            lines.push(('-', a[i]));
            i += 1;
        } else {
            lines.push(('+', b[j]));
            j += 1;
        }
    }
    let changed: Vec<bool> = lines.iter().map(|(m, _)| *m != ' ').collect();
    let mut out = String::new();
    let mut last_shown: Option<usize> = None;
    for (k, (mark, text)) in lines.iter().enumerate() {
        let near = (k.saturating_sub(2)..=(k + 2).min(lines.len() - 1)).any(|n| changed[n]);
        if !near {
            continue;
        }
        if last_shown.is_some_and(|l| l + 1 != k) {
            out.push_str("  ...\n");
        }
        let _ = writeln!(out, "{mark} {text}");
        last_shown = Some(k);
    }
    out
}

fn all_transcript_files(dir: &Path, found: &mut BTreeSet<PathBuf>) {
    for entry in fs::read_dir(dir).into_iter().flatten().flatten() {
        let path = entry.path();
        if path.is_dir() {
            all_transcript_files(&path, found);
        } else if path.extension().is_some_and(|e| e == "json") {
            found.insert(path);
        }
    }
}

#[test]
fn every_transcript_replays_against_the_build() {
    let bless = bless_requested();
    let cases = cases();
    let mut failures = Vec::new();
    let mut expected_files = BTreeSet::new();
    for case in &cases {
        let path = transcript_path(case);
        expected_files.insert(path.clone());
        let actual = record(case);
        if bless {
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            let mut recorded = actual.clone();
            recorded["release"] = json!(env!("CARGO_PKG_VERSION"));
            let mut text = serde_json::to_string_pretty(&recorded).unwrap();
            text.push('\n');
            fs::write(&path, text).unwrap();
            continue;
        }
        let Ok(text) = fs::read_to_string(&path) else {
            failures.push(format!(
                "{}/{}: no transcript at {}; record it with NVMOD_BLESS=1",
                case.command,
                case.name,
                path.display()
            ));
            continue;
        };
        let mut expected: Value = serde_json::from_str(&text)
            .unwrap_or_else(|e| panic!("{} is not JSON: {e}", path.display()));
        // The release a transcript was taken from is a note, not compared: the output is normalised instead.
        expected.as_object_mut().map(|o| o.remove("release"));
        if expected != actual {
            failures.push(format!(
                "{}/{} differs (exit {} recorded, {} now):\n{}",
                case.command,
                case.name,
                expected["exit_code"],
                actual["exit_code"],
                line_diff(
                    &serde_json::to_string_pretty(&expected).unwrap(),
                    &serde_json::to_string_pretty(&actual).unwrap()
                )
            ));
        }
    }
    let mut on_disk = BTreeSet::new();
    all_transcript_files(&baseline_dir(), &mut on_disk);
    for stray in on_disk.difference(&expected_files) {
        failures.push(format!(
            "{} has no case in baseline.rs; remove it or add the case",
            stray.display()
        ));
    }
    if bless {
        eprintln!("blessed {} transcripts", cases.len());
        return;
    }
    assert!(
        failures.is_empty(),
        "{} baseline transcript(s) differ:\n\n{}",
        failures.len(),
        failures.join("\n")
    );
}

#[test]
fn normalisation_is_whole_token_and_leaves_other_numbers_alone() {
    assert_eq!(
        replace_nvmod_version("nvmod 0.8.1 and 0.8.1 and nvmod 0.8.10, 0.8.1", "0.8.1"),
        "nvmod <VERSION> and 0.8.1 and nvmod 0.8.10, 0.8.1"
    );
    assert_eq!(
        replace_timestamps("at 2026-11-18T19:25:00Z, 2026-11-18 19:25:00.123+01:00 and 12-34"),
        "at <TIME>, <TIME> and 12-34"
    );
    let root = Path::new("/nonexistent/scratch-root");
    let mut norm = Norm::new(root);
    assert_eq!(norm.apply("/nonexistent/scratch-root/fnv"), "<TMP>/fnv");
    assert_eq!(line_diff("a\nb\nc", "a\nB\nc"), "  a\n- b\n+ B\n  c\n");
    assert_eq!(
        replace_journal_ids("\"journal\": \"0001795027426065-000001-2651920\" and 12-34"),
        "\"journal\": \"<JOURNAL>\" and 12-34"
    );
    assert_eq!(
        replace_loopback_port("http://127.0.0.1:43123/tool"),
        "http://127.0.0.1:<PORT>/tool"
    );
}

#[test]
fn digests_are_numbered_by_first_appearance_so_equal_digests_stay_equal() {
    let a = "a".repeat(64);
    let b = "b".repeat(64);
    let mut norm = Norm::new(Path::new("/nonexistent/scratch-root"));
    assert_eq!(
        norm.apply(&format!("says {a}, download {b}")),
        "says <SHA256-1>, download <SHA256-2>"
    );
    // Standard error of the same run shares the table.
    assert_eq!(
        norm.apply(&format!("again {b} and {a}")),
        "again <SHA256-2> and <SHA256-1>"
    );
    assert_eq!(norm.apply(&format!("x{a}")), format!("x{a}"));
}

