/// Builds the fixture of a case under `root` (the scratch directory) and returns what must stay alive while the
/// command runs (fake servers).
type Setup = fn(&Path) -> Vec<FakeServer>;

struct Case {
    /// The folder of the transcript, the command the case belongs to.
    command: &'static str,
    /// The file stem of the transcript.
    name: &'static str,
    /// The arguments, with `<TMP>` for the scratch directory.
    args: &'static [&'static str],
    setup: Setup,
}

fn nothing(_: &Path) -> Vec<FakeServer> {
    Vec::new()
}

/// The fixture of `nvmod verify`: a steam base copy, then an Instance at `<TMP>/fnv` made by `init`, with a profile
/// and a staged tree. The base copy is at `<TMP>/base`.
