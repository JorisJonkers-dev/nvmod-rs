/// `instance`, with an nv-rs whose executable is not the one its install record names.
fn instance_with_changed_nv_rs(root: &Path) -> Vec<FakeServer> {
    instance(root);
    write_file(
        &root.join("fnv"),
        &format!("nv-rs/bin/{}", nv_viewer_name()),
        b"changed after the install",
    );
    let record = serde_json::json!({ "method": "release", "sha256": sha256_hex(b"as installed") });
    write_file(
        &root.join("fnv"),
        "nv-rs/install.json",
        record.to_string().as_bytes(),
    );
    Vec::new()
}

/// Runs one setup step of a fixture, which must succeed or the fixture is wrong.
fn run_setup_step(args: &[&str], root: &Path) {
    let (code, out, err) = nvmod_in(root, args);
    assert_eq!(code, 0, "fixture step {args:?} failed: {out}{err}");
}

/// A lock pinning `lodwright-rs` to `TOOL_BODY` at the fake server, a linked `loot-rs` and a stand-in third-party
/// tool named `ttw-installer` (a plain name, the real installer is gone) with no checksum, all for this platform. `sha` overrides the pinned checksum.
fn lock_text(url: &str, sha: &str) -> String {
    let platform = platform();
    format!(
        "schema_version = 1\n\n[[tool]]\nname = \"lodwright-rs\"\nversion = \"1.0.0\"\ncontracts = {{ lodwright-plan = 1 }}\n\n\
         [tool.attestation]\nrepository = \"o/lodwright-rs\"\nworkflow = \".github/workflows/release.yml\"\n\n\
         [tool.assets.{platform}]\nurl = \"{url}/tool\"\nsha256 = \"{sha}\"\n\n\
         [[tool]]\nname = \"loot-rs\"\nversion = \"0.1.0\"\nkind = \"linked\"\n[tool.source]\ngit = \"https://github.com/o/loot-rs\"\ntag = \"v0.1.0\"\n\n\
         [[tool]]\nname = \"ttw-installer\"\nversion = \"0.2.0\"\nkind = \"third-party\"\n\n\
         [tool.assets.{platform}]\nurl = \"{url}/tool\"\n"
    )
}

/// A fake release server serving `TOOL_BODY`, the lock that pins it, and a `gh` that accepts every attestation.
fn tools_lock(root: &Path) -> Vec<FakeServer> {
    let body = TOOL_BODY.to_vec();
    let server = FakeServer::start(move |path, _| {
        if path == "tool" {
            Reply::Body(body.clone())
        } else {
            Reply::Status(404)
        }
    });
    fs::write(
        root.join("tools.lock.toml"),
        lock_text(&server.url(), &sha256_hex(TOOL_BODY)),
    )
    .expect("write lock");
    write_script(&root.join("bin"), "gh", "exit 0");
    vec![server]
}

/// `tools_lock`, with the pinned tool fetched into the store.
fn tools_fetched(root: &Path) -> Vec<FakeServer> {
    let servers = tools_lock(root);
    run_setup_step(
        &[
            "tools",
            "fetch",
            "lodwright-rs",
            "--lock",
            "<TMP>/tools.lock.toml",
            "--store",
            "<TMP>/store",
            "--gh",
            "<TMP>/bin/gh",
        ],
        root,
    );
    servers
}

