fn nvse_fixture(s: &Scratch, with_xnvse: bool) -> String {
    let dll = nvmod_testkit::PeBuilder::nvse_plugin().build();
    for name in ["NeedsOldGame", "RecordsNothing", "Fits", "NotInCatalogue"] {
        write_file(
            &s.root(),
            &format!("mods/Core/NVSE/Plugins/{name}.dll"),
            &dll,
        );
    }
    if with_xnvse {
        // The xNVSE of the base copy is 6.3.0.0 (a synthetic DLL).
        write_file(
            s.base.path(),
            "nvse_1_4.dll",
            &nvmod_testkit::PeBuilder::dll()
                .versions([6, 3, 0, 0], [6, 3, 0, 0])
                .build(),
        );
    }
    s.stage();
    let file = s.inst.path().join("catalog.toml");
    fs::write(&file, CATALOG).unwrap();
    file.to_str().unwrap().to_owned()
}

#[test]
fn the_doctor_flags_an_nvse_plugin_that_does_not_match_the_catalogue() {
    let s = Scratch::new();
    let catalog = nvse_fixture(&s, true);
    let (_, findings) = s.doctor(&["--catalog", &catalog]);
    let text = has(
        &findings,
        "plugin.game-version-mismatch",
        "NeedsOldGame.dll",
    )
    .expect("game");
    assert!(
        text.starts_with("warning:") && text.contains("1.3.0.0") && text.contains("1.4.0.525"),
        "{text}"
    );
    let text = has(
        &findings,
        "plugin.xnvse-version-mismatch",
        "NeedsOldGame.dll",
    )
    .expect("xnvse");
    assert!(
        text.contains("6.4.0.0") && text.contains("6.3.0.0"),
        "{text}"
    );
    let text = has(
        &findings,
        "plugin.requirements-unknown",
        "RecordsNothing.dll",
    )
    .expect("unknown");
    assert!(
        text.starts_with("info:") && text.contains("game version it requires or the lowest xNVSE"),
        "{text}"
    );
    for subject in ["Fits.dll", "NotInCatalogue.dll"] {
        assert!(
            findings.iter().all(|(_, sub, _)| sub != subject),
            "{subject}: {findings:?}"
        );
    }
}

