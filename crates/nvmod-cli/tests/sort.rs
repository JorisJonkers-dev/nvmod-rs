#[test]
fn apply_writes_both_lists_and_encodes_the_order_in_file_times() {
    let s = Scratch::new();
    let json = s.sort_json(&["--apply"]);
    assert_eq!(json["applied"]["lists_written"], true);
    assert_eq!(json["applied"]["stamped"], 4);
    assert!(json["applied"]["journal"].is_string());
    let order = String::from_utf8(s.profile_file("loadorder.txt")).unwrap();
    let listed: Vec<&str> = order.lines().skip(1).collect();
    assert_eq!(listed, SORTED);
    let active = String::from_utf8(s.profile_file("plugins.txt")).unwrap();
    let listed: Vec<&str> = active.lines().skip(1).collect();
    assert_eq!(listed, ["FalloutNV.esm", "Base.esp", "Patch.esp"]);
    assert!(order.contains("\r\n") && active.contains("\r\n"));

    let times: Vec<SystemTime> = SORTED[..4].iter().map(|n| mtime(&s.staged(n))).collect();
    assert!(
        times.windows(2).all(|w| w[0] < w[1]),
        "times must be strictly increasing in Load order: {times:?}"
    );
}

#[test]
fn the_mod_folders_are_untouched_when_the_staged_files_get_their_times() {
    let s = Scratch::new();
    let files = ["Patch/Patch.esp", "Core/Base.esp", "Other/Other.esp"];
    for (n, f) in files.iter().enumerate() {
        set_mtime(&s.mod_file(f), 1_500_000_000 + n as u64);
    }
    let before: Vec<(SystemTime, Vec<u8>)> = files
        .iter()
        .map(|f| (mtime(&s.mod_file(f)), fs::read(s.mod_file(f)).unwrap()))
        .collect();
    let mods_before = snapshot(&s.root().join("mods"));
    // FalloutNV.esm of the base copy is hard-linked into the Staging tree too, and must stay as it is.
    let base_master = s.base.path().join("Data/FalloutNV.esm");
    set_mtime(&base_master, 1_400_000_000);
    let base_time = mtime(&base_master);
    let json = s.sort_json(&["--apply"]);
    assert_eq!(json["applied"]["detached"], 4, "{json}");
    assert_eq!(mtime(&base_master), base_time, "the base copy was touched");
    for (f, (time, bytes)) in files.iter().zip(&before) {
        assert_eq!(
            mtime(&s.mod_file(f)),
            *time,
            "{f}: the Mod's file time moved"
        );
        assert_eq!(&fs::read(s.mod_file(f)).unwrap(), bytes);
    }
    assert_eq!(snapshot(&s.root().join("mods")), mods_before);
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        for f in files {
            let mod_inode = fs::metadata(s.mod_file(f)).unwrap();
            let name = f.rsplit('/').next().unwrap();
            let staged = fs::metadata(s.staged(name)).unwrap();
            assert_ne!(mod_inode.ino(), staged.ino(), "{f} is still linked");
            assert_eq!(staged.nlink(), 1);
            assert_eq!(mod_inode.nlink(), 1);
        }
    }
    // Files that are not plugins stay hard links to the Mod.
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        assert_eq!(
            fs::metadata(s.mod_file("Core/Textures/Dirt.dds"))
                .unwrap()
                .ino(),
            fs::metadata(s.staged("textures/dirt.dds")).unwrap().ino()
        );
    }
}

#[test]
fn running_apply_twice_gives_the_same_order_and_changes_nothing() {
    let s = Scratch::new();
    let first = s.sort_json(&["--apply"]);
    let after_first = snapshot(&s.root());
    let times: Vec<SystemTime> = SORTED[..4].iter().map(|n| mtime(&s.staged(n))).collect();
    let second = s.sort_json(&["--apply"]);
    assert_eq!(names(&first), names(&second));
    assert_eq!(second["reordered"], false);
    assert!(second["applied"]["journal"].is_null(), "{second}");
    assert_eq!(second["applied"]["stamped"], 0);
    assert_eq!(second["applied"]["lists_written"], false);
    assert_eq!(snapshot(&s.root()), after_first);
    let again: Vec<SystemTime> = SORTED[..4].iter().map(|n| mtime(&s.staged(n))).collect();
    assert_eq!(times, again);
    let (code, out, _) = s.sort(&["--apply"]);
    assert_eq!(code, 0);
    assert!(out.contains("nothing to change"), "{out}");
}

#[test]
fn rollback_undoes_the_sort() {
    let s = Scratch::new();
    let lists_before = (
        s.profile_file("plugins.txt"),
        s.profile_file("loadorder.txt"),
        s.profile_file("modlist.txt"),
    );
    let mod_times = mtime(&s.mod_file("Core/Base.esp"));
    let (code, _, err) = s.sort(&["--apply"]);
    assert_eq!(code, 0, "{err}");
    assert_ne!(s.profile_file("loadorder.txt"), lists_before.1);
    let (code, out, err) = nvmod(&["rollback", "--instance", s.root().to_str().unwrap()]);
    assert_eq!(code, 0, "{err}");
    assert!(out.contains("undid the Load order sort"), "{out}");
    assert_eq!(s.profile_file("plugins.txt"), lists_before.0);
    assert_eq!(s.profile_file("loadorder.txt"), lists_before.1);
    assert_eq!(s.profile_file("modlist.txt"), lists_before.2);
    assert!(s.mod_file("Core/Base.esp").is_file(), "the Mod stays");
    assert_eq!(mtime(&s.mod_file("Core/Base.esp")), mod_times);
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        assert_eq!(
            fs::metadata(s.staged("base.esp")).unwrap().ino(),
            fs::metadata(s.mod_file("Core/Base.esp")).unwrap().ino(),
            "the Staging tree is linked again"
        );
    }
    let (code, _, err) = nvmod(&["rollback", "--instance", s.root().to_str().unwrap()]);
    assert_eq!(code, 2, "{err}");
}

