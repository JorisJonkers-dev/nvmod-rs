#[test]
fn the_doctor_notices_file_times_that_no_longer_encode_the_order() {
    let s = Scratch::new();
    s.sort_json(&["--apply"]);
    // Rebuilding the Staging tree links the plugins to the Mods again, with the Mods' own times.
    set_mtime(&s.mod_file("Core/Base.esp"), 1_900_000_000);
    set_mtime(&s.mod_file("Patch/Patch.esp"), 1_800_000_000);
    s.stage();
    let (_, findings) = s.doctor(&[]);
    let text = has(&findings, "loadorder.times-out-of-order", "Default").expect("times");
    assert!(text.contains("nvmod sort --apply"), "{text}");
    s.sort_json(&["--apply"]);
    let (_, findings) = s.doctor(&[]);
    assert!(has(&findings, "loadorder.times-out-of-order", "Default").is_none());
}

