impl Scratch {
    fn doctor(&self, extra: &[&str]) -> (i32, Vec<(String, String, String)>) {
        let root = self.root();
        let mut args = vec!["doctor", "--instance", root.to_str().unwrap(), "--json"];
        args.extend_from_slice(extra);
        let (code, out, err) = nvmod(&args);
        let report: Value =
            serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out} / {err}"));
        let findings = report["findings"]
            .as_array()
            .unwrap()
            .iter()
            .map(|f| {
                (
                    f["code"].as_str().unwrap().to_owned(),
                    f["subject"].as_str().unwrap().to_owned(),
                    format!(
                        "{}: {}",
                        f["severity"].as_str().unwrap(),
                        f["message"].as_str().unwrap()
                    ),
                )
            })
            .collect();
        (code, findings)
    }

    fn masterlist_arg(&self) -> String {
        self.masterlist.to_str().unwrap().to_owned()
    }
}

fn has(findings: &[(String, String, String)], code: &str, subject: &str) -> Option<String> {
    findings
        .iter()
        .find(|(c, s, _)| c == code && s == subject)
        .map(|(.., text)| text.clone())
}

#[test]
fn the_doctor_reports_a_missing_master_and_a_wrong_load_order() {
    let s = Scratch::new();
    let ml = s.masterlist_arg();
    let (code, findings) = s.doctor(&["--masterlist", &ml]);
    assert_eq!(code, 1, "a missing master is an error: {findings:?}");
    let text = has(&findings, "loadorder.missing-master", "Patch.esp").expect("missing master");
    assert!(
        text.starts_with("error:") && text.contains("Base.esp loads after it"),
        "{text}"
    );
    let text = has(&findings, "loadorder.differs-from-loot", "Default").expect("differs");
    assert!(
        text.starts_with("warning:") && text.contains("Base.esp"),
        "{text}"
    );

    // Without a masterlist the comparison still runs, on the headers only, and is only information.
    let (_, findings) = s.doctor(&[]);
    let text = has(&findings, "loadorder.differs-from-loot", "Default").expect("differs");
    assert!(
        text.starts_with("info:") && text.contains("no --masterlist"),
        "{text}"
    );

    // A master that is in no list at all.
    write_file(
        &s.root(),
        "mods/Other/Orphan.esp",
        &PluginBuilder::new().requires("Absent.esm").build(),
    );
    write_file(
        &s.root(),
        "profiles/Default/plugins.txt",
        b"FalloutNV.esm\r\nOrphan.esp\r\n",
    );
    write_file(
        &s.root(),
        "profiles/Default/loadorder.txt",
        b"FalloutNV.esm\r\nOrphan.esp\r\n",
    );
    s.stage();
    let (_, findings) = s.doctor(&[]);
    let text = has(&findings, "loadorder.missing-master", "Orphan.esp").expect("orphan");
    assert!(
        text.contains("Absent.esm is not in the Load order"),
        "{text}"
    );
}

