//! `nvmod sweep` against a scratch Instance made by `nvmod init`: a fake writer creates, replaces, writes in place
//! and deletes files of the Staging tree, and the sweep takes the output into Overwrite. Synthetic files only.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, snapshot, write_file};
use nvmod_testkit::{covers, ids};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Mods `Core` (Textures/Dirt.dds, Config/core.ini) and `Tool Output`, no Overwrite; staged.
    fn new() -> Scratch {
        let base = TempDir::new("sw-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("sw-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod_env(
            &[
                "init",
                "--base",
                base.path().to_str().unwrap(),
                "--instance",
                root.to_str().unwrap(),
            ],
            &[],
        );
        assert_eq!(code, 0, "{err}");
        write_file(&root, "mods/Core/Textures/Dirt.dds", b"core dirt");
        write_file(&root, "mods/Core/Config/core.ini", b"core ini");
        write_file(&root, "mods/Tool Output/meta.ini", b"[General]\r\n");
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            format!("{HEADER}+Tool Output\r\n+Core\r\n").as_bytes(),
        );
        write_file(&root, "profiles/Default/plugins.txt", b"FalloutNV.esm\r\n");
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"FalloutNV.esm\r\n",
        );
        let s = Scratch { _base: base, inst };
        let (code, _, err) = nvmod_env(&["stage", "--instance", root.to_str().unwrap()], &[]);
        assert_eq!(code, 0, "{err}");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn data(&self, rel: &str) -> PathBuf {
        self.root().join("staging/Default/data").join(rel)
    }

    fn sweep_env(&self, args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
        let root = self.root();
        let mut all = vec!["sweep"];
        all.extend_from_slice(args);
        all.extend_from_slice(&["--instance", root.to_str().unwrap()]);
        nvmod_env(&all, env)
    }

    fn json(&self, args: &[&str]) -> Value {
        let mut all = args.to_vec();
        all.push("--json");
        let (code, out, err) = self.sweep_env(&all, &[]);
        assert_eq!(code, 0, "{args:?}: {err}");
        serde_json::from_str(&out).unwrap()
    }

    fn read(&self, rel: &str) -> String {
        fs::read_to_string(self.root().join(rel)).unwrap()
    }

    /// Everything that is kept: Mods, Overwrite, the profile and the built tree.
    fn state(&self) -> BTreeMap<String, Vec<u8>> {
        snapshot(&self.root())
            .into_iter()
            .filter(|(k, _)| !k.starts_with(".nvmod") && !k.contains(".json"))
            .collect()
    }

    /// A program that writes a temporary file and renames it over the target (the link breaks).
    fn replace(&self, rel: &str, bytes: &[u8]) {
        let target = self.data(rel);
        let tmp = target.with_extension("tmp-writer");
        fs::write(&tmp, bytes).unwrap();
        fs::rename(&tmp, &target).unwrap();
    }

    /// A program that rewrites the file it opened (the Mod's own file changes with it).
    fn write_in_place(&self, rel: &str, bytes: &[u8]) {
        fs::write(self.data(rel), bytes).unwrap();
    }

    fn create(&self, rel: &str, bytes: &[u8]) {
        let path = self.data(rel);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, bytes).unwrap();
    }
}

fn kinds(r: &Value) -> Vec<(String, String)> {
    r["changes"].as_array().map_or_default(|c| {
        c.iter()
            .map(|c| {
                (
                    c["kind"].as_str().unwrap().to_owned(),
                    c["path"].as_str().unwrap().to_owned(),
                )
            })
            .collect()
    })
}

fn pair(k: &str, p: &str) -> (String, String) {
    (k.to_owned(), p.to_owned())
}

#[test]
fn nothing_to_sweep_changes_nothing() {
    let s = Scratch::new();
    let before = s.state();
    let r = s.json(&[]);
    assert_eq!(r["status"], "unchanged");
    assert_eq!(s.state(), before);
}

#[test]
fn a_created_file_goes_to_overwrite_with_its_folders_and_the_tree_shows_it_from_there() {
    covers(&[ids::staging::sweep::TO_OVERWRITE]);
    let s = Scratch::new();
    s.create("logs/deep/run.log", b"log");
    let dry = s.json(&["--dry-run"]);
    assert_eq!(dry["status"], "dry-run");
    assert_eq!(kinds(&dry), [pair("new", "logs/deep/run.log")]);
    assert!(s.data("logs/deep/run.log").is_file());
    assert!(!s.root().join("overwrite").exists());
    let r = s.json(&[]);
    assert_eq!(r["status"], "changed");
    assert_eq!(s.read("overwrite/logs/deep/run.log"), "log");
    assert_eq!(fs::read(s.data("logs/deep/run.log")).unwrap(), b"log");
    assert_eq!(s.json(&[])["status"], "unchanged");
}

#[test]
fn a_case_variant_of_an_existing_folder_uses_the_existing_spelling() {
    let s = Scratch::new();
    s.create("TEXTURES/New.dds", b"new");
    s.json(&[]);
    assert_eq!(s.read("overwrite/Textures/New.dds"), "new");
    // Compare the stored spelling: `exists()` is case-insensitive on Windows and macOS.
    let names: Vec<String> = fs::read_dir(s.root().join("overwrite"))
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    assert_eq!(names, ["Textures"]);
}

#[test]
fn a_replaced_file_keeps_the_mod_intact_and_its_new_content_lands_in_overwrite() {
    covers(&[ids::staging::sweep::REPLACED_FILE]);
    let s = Scratch::new();
    s.replace("textures/dirt.dds", b"program dirt");
    let r = s.json(&[]);
    assert_eq!(kinds(&r), [pair("replaced", "textures/dirt.dds")]);
    assert_eq!(r["changes"][0]["provider"], "Core");
    assert_eq!(s.read("mods/Core/Textures/Dirt.dds"), "core dirt");
    assert_eq!(s.read("overwrite/Textures/Dirt.dds"), "program dirt");
    assert_eq!(
        fs::read(s.data("textures/dirt.dds")).unwrap(),
        b"program dirt"
    );
    assert_eq!(s.json(&[])["status"], "unchanged");
}

#[test]
fn a_deleted_file_is_restored_from_the_provider_and_reported() {
    covers(&[ids::staging::sweep::DELETED_RESTORED]);
    let s = Scratch::new();
    fs::remove_file(s.data("config/core.ini")).unwrap();
    let r = s.json(&[]);
    assert_eq!(kinds(&r), [pair("deleted-by-program", "config/core.ini")]);
    assert_eq!(r["changes"][0]["provider"], "Core");
    assert_eq!(fs::read(s.data("config/core.ini")).unwrap(), b"core ini");
    assert_eq!(s.read("mods/Core/Config/core.ini"), "core ini");
    assert_eq!(s.json(&[])["status"], "unchanged");
}

#[test]
fn a_file_written_in_place_is_reported_and_protect_stages_it_as_a_copy_from_then_on() {
    covers(&[ids::staging::sweep::PROTECT]);
    let s = Scratch::new();
    s.write_in_place("config/core.ini", b"changed ini");
    let r = s.json(&["--protect", "config/*.ini"]);
    assert_eq!(kinds(&r), [pair("modified-in-place", "config/core.ini")]);
    assert_eq!(r["changes"][0]["provider"], "Core");
    // The Mod's file changed (as under Mod Organizer); nothing was moved.
    assert_eq!(s.read("mods/Core/Config/core.ini"), "changed ini");
    assert!(!s.root().join("overwrite").exists());
    assert!(
        s.read("profiles/Default/nvmod-protect.txt")
            .contains("config/*.ini")
    );
    // The protected path is a copy now: a program writing in place leaves the Mod alone.
    s.write_in_place("config/core.ini", b"second write");
    let again = s.json(&[]);
    assert_eq!(kinds(&again), [pair("replaced", "config/core.ini")]);
    assert_eq!(s.read("mods/Core/Config/core.ini"), "changed ini");
    assert_eq!(s.read("overwrite/Config/core.ini"), "second write");
}

#[test]
fn a_custom_target_takes_the_output_instead_of_overwrite() {
    covers(&[ids::staging::sweep::CUSTOM_TARGET]);
    let s = Scratch::new();
    s.create("out/result.txt", b"result");
    s.replace("textures/dirt.dds", b"program dirt");
    s.json(&["--to", "Tool Output"]);
    assert_eq!(s.read("mods/Tool Output/out/result.txt"), "result");
    assert_eq!(s.read("mods/Tool Output/Textures/Dirt.dds"), "program dirt");
    assert!(!s.root().join("overwrite").exists());
}

#[test]
fn a_sweep_is_not_rolled_back_so_what_a_program_wrote_is_never_lost() {
    covers(&[ids::staging::sweep::NEVER_ROLLED_BACK]);
    let s = Scratch::new();
    s.create("logs/run.log", b"log");
    s.json(&[]);
    let (code, _, err) = nvmod_env(&["rollback", "--instance", s.root().to_str().unwrap()], &[]);
    assert_eq!(code, 2, "nothing else to roll back: {err}");
    assert_eq!(s.read("overwrite/logs/run.log"), "log");
}

/// The writer's work: a created file, a replaced file, a deleted file and an in-place write.
fn program(s: &Scratch) {
    s.create("logs/run.log", b"log");
    s.replace("textures/dirt.dds", b"program dirt");
    fs::remove_file(s.data("config/core.ini")).unwrap();
}

#[test]
fn an_interrupted_sweep_gives_the_same_final_tree_when_it_runs_again() {
    covers(&[ids::staging::sweep::REPEATABLE]);
    let clean = Scratch::new();
    program(&clean);
    clean.json(&[]);
    let expected = clean.state();
    for point in ["mod", "lists", "stage"] {
        let s = Scratch::new();
        program(&s);
        let (code, _, _) = s.sweep_env(&[], &[("NVMOD_FAIL_AT", point)]);
        assert_eq!(code, 4, "{point}");
        s.json(&[]);
        assert_eq!(s.state(), expected, "after a stop at {point}");
    }
    // A stop that left half the moves done (the process was killed): the file is already in Overwrite.
    let s = Scratch::new();
    program(&s);
    fs::create_dir_all(s.root().join("overwrite/logs")).unwrap();
    fs::rename(
        s.data("logs/run.log"),
        s.root().join("overwrite/logs/run.log"),
    )
    .unwrap();
    s.json(&[]);
    assert_eq!(s.state(), expected, "after a killed sweep");
}

#[test]
fn the_doctor_reports_an_unswept_tree() {
    covers(&[ids::doctor::checks::UNSWEPT_TREE]);
    let s = Scratch::new();
    let doctor = |s: &Scratch| {
        let (_, out, _) = nvmod_env(
            &["doctor", "--instance", s.root().to_str().unwrap(), "--json"],
            &[],
        );
        out
    };
    assert!(!doctor(&s).contains("stage.unswept"));
    s.create("logs/run.log", b"log");
    assert!(doctor(&s).contains("stage.unswept"));
    s.json(&[]);
    assert!(!doctor(&s).contains("stage.unswept"));
}
