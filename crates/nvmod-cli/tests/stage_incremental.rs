//! Incremental staging (#72), run as a program against a scratch Instance of 300 synthetic Mods.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::collections::BTreeMap;
use std::process::Command;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";
const MODS: usize = 300;

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
    listed: Vec<String>,
}

impl Scratch {
    /// 300 Mods of two files each (one path shared by all of them), a plugin in the base; not staged yet.
    fn new() -> Scratch {
        let base = TempDir::new("inc-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("inc-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod_env(
            &[
                "init",
                "--base",
                base.path().to_str().unwrap(),
                "--instance",
                root.to_str().unwrap(),
            ],
            &[],
        );
        assert_eq!(code, 0, "{err}");
        let mut s = Scratch {
            _base: base,
            inst,
            listed: Vec::new(),
        };
        for n in 0..MODS {
            let name = format!("Mod{n:03}");
            write_file(&root, &format!("mods/{name}/Meshes/m{n}.nif"), b"nif");
            write_file(
                &root,
                &format!("mods/{name}/Meshes/shared.nif"),
                name.as_bytes(),
            );
            s.listed.push(name);
        }
        write_file(&root, "profiles/Default/plugins.txt", b"FalloutNV.esm\r\n");
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"FalloutNV.esm\r\n",
        );
        s.write_modlist();
        s
    }

    fn write_modlist(&self) {
        let lines: Vec<String> = self
            .listed
            .iter()
            .rev()
            .map(|n| format!("+{n}\r\n"))
            .collect();
        let lines = lines.join("");
        write_file(
            &self.root(),
            "profiles/Default/modlist.txt",
            format!("{HEADER}{lines}").as_bytes(),
        );
    }

    fn root(&self) -> std::path::PathBuf {
        self.inst.path().join("fnv")
    }

    /// Add a Mod of `files` files and list it as the highest priority.
    fn enable_new_mod(&mut self, name: &str, files: usize) {
        for n in 0..files {
            write_file(
                &self.root(),
                &format!("mods/{name}/Textures/t{n}.dds"),
                b"dds",
            );
        }
        self.listed.push(name.to_owned());
        self.write_modlist();
    }

    fn stage(&self, extra: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
        let root = self.root();
        let mut args = vec!["stage", "--instance", root.to_str().unwrap(), "--json"];
        args.extend_from_slice(extra);
        nvmod_env(&args, env)
    }

    fn staged(&self, extra: &[&str]) -> Value {
        let (code, out, err) = self.stage(extra, &[]);
        assert_eq!(code, 0, "{err}");
        serde_json::from_str(&out).unwrap()
    }

    /// The tree of the Profile, by path: the content of each file.
    fn tree(&self) -> BTreeMap<String, Vec<u8>> {
        snapshot(&self.root())
            .into_iter()
            .filter(|(k, _)| k.starts_with("staging/Default/data"))
            .collect()
    }

    /// The manifest without the file ids of copies (every copy is a new file with a new id).
    fn manifest(&self) -> Value {
        let text = std::fs::read_to_string(self.root().join("staging/Default.json")).unwrap();
        let mut value: Value = serde_json::from_str(&text).unwrap();
        for record in value["records"].as_object_mut().unwrap().values_mut() {
            if record["links"] == 1 {
                record["id"] = 0.into();
            }
        }
        value
    }
}

#[test]
fn enabling_one_mod_changes_about_its_files_not_the_whole_tree() {
    let mut s = Scratch::new();
    let first = s.staged(&[]);
    assert_eq!(first["mode"], "full");
    s.enable_new_mod("Added", 20);
    let r = s.staged(&[]);
    assert_eq!(r["mode"], "incremental");
    assert_eq!(r["operations"], 20);
    assert_eq!(r["files"], first["files"].as_u64().unwrap() + 20);
    let again = s.staged(&[]);
    assert_eq!(again["mode"], "incremental");
    assert_eq!(again["operations"], 0);
}

#[test]
fn a_changed_winner_replaces_one_file_and_matches_a_full_build() {
    let mut s = Scratch::new();
    s.staged(&[]);
    // A new Mod that overrides the shared path: one replaced path, plus its own new file.
    write_file(&s.root(), "mods/Late/Meshes/shared.nif", b"late");
    write_file(&s.root(), "mods/Late/Meshes/own.nif", b"own");
    s.listed.push("Late".to_owned());
    s.write_modlist();
    let r = s.staged(&[]);
    assert_eq!(r["operations"], 2);
    let (incremental_tree, incremental_manifest) = (s.tree(), s.manifest());
    let full = s.staged(&["--full"]);
    assert_eq!(full["mode"], "full");
    assert_eq!(s.tree(), incremental_tree);
    assert_eq!(s.manifest(), incremental_manifest);
}

#[test]
fn disabling_a_mod_removes_what_only_it_provided_and_empty_folders() {
    let mut s = Scratch::new();
    s.enable_new_mod("Added", 3);
    s.staged(&[]);
    s.listed.pop();
    s.write_modlist();
    let r = s.staged(&[]);
    assert_eq!(r["mode"], "incremental");
    assert_eq!(r["operations"], 3);
    assert!(!s.root().join("staging/Default/data/textures").exists());
    let before = s.tree();
    assert_eq!(s.staged(&["--full"])["files"], r["files"]);
    assert_eq!(s.tree(), before);
}

#[test]
fn a_failure_inside_a_run_leaves_the_old_tree_and_exit_4() {
    let mut s = Scratch::new();
    s.staged(&[]);
    let old = s.tree();
    s.enable_new_mod("Added", 20);
    let (code, _, err) = s.stage(&[], &[("NVMOD_FAIL_AT", "stage-op")]);
    assert_eq!(code, 4, "{err}");
    assert_eq!(s.tree(), old);
    assert!(!s.root().join("staging/Default.ops.json").exists());
    assert_eq!(s.staged(&[])["operations"], 20);
}

#[test]
fn a_killed_run_is_undone_by_the_next_run_which_then_gives_the_new_tree() {
    let mut reference = Scratch::new();
    reference.staged(&[]);
    reference.enable_new_mod("Added", 20);
    reference.staged(&["--full"]);
    let new_tree = reference.tree();
    let new_files = reference.staged(&[])["files"].clone();
    for point in ["0", "1", "10", "19", "20"] {
        let mut s = Scratch::new();
        s.staged(&[]);
        s.enable_new_mod("Added", 20);
        let (code, _, _) = s.stage(&[], &[("NVMOD_STAGE_KILL_AT", point)]);
        assert_eq!(code, 4, "kill at {point}");
        assert!(s.root().join("staging/Default.ops.json").is_file());
        let (_, doctor, _) = nvmod_env(
            &["doctor", "--instance", s.root().to_str().unwrap(), "--json"],
            &[],
        );
        assert!(doctor.contains("stage.interrupted"), "kill at {point}");
        let r = s.staged(&[]);
        assert_eq!(r["files"], new_files, "kill at {point}");
        assert_eq!(s.tree(), new_tree, "after a kill at {point}");
        assert!(!s.root().join("staging/Default.ops.json").exists());
    }
}

#[test]
fn copy_mode_stays_incremental_and_a_change_of_mode_builds_everything_again() {
    let mut s = Scratch::new();
    let first = s.staged(&["--copy"]);
    assert_eq!(first["linked"], 0);
    s.enable_new_mod("Added", 5);
    let r = s.staged(&["--copy"]);
    assert_eq!(r["mode"], "incremental");
    assert_eq!(r["operations"], 5);
    assert_eq!(r["linked"], 0);
    assert_eq!(r["copied"], r["files"]);
    let (_, doctor, _) = nvmod_env(
        &["doctor", "--instance", s.root().to_str().unwrap(), "--json"],
        &[],
    );
    assert!(doctor.contains("stage.degraded"));
    let linked = s.staged(&[]);
    assert_eq!(linked["mode"], "full");
    assert_eq!(linked["copied"], 0);
}

#[test]
fn a_stale_or_missing_manifest_builds_everything() {
    let mut s = Scratch::new();
    s.staged(&[]);
    s.enable_new_mod("Added", 2);
    std::fs::write(s.root().join("staging/Default.json"), "{ not json").unwrap();
    assert_eq!(s.staged(&[])["mode"], "full");
    std::fs::remove_file(s.root().join("staging/Default.json")).unwrap();
    assert_eq!(s.staged(&[])["mode"], "full");
    assert_eq!(s.staged(&[])["mode"], "incremental");
}
