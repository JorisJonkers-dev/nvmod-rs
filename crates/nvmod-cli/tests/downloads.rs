//! `nvmod downloads ...`, run as a program against a scratch Instance made by `nvmod init`. Archives are built in
//! code by the testkit and `.meta` files are written here; no mod data is used.

use nvmod_testkit::{BaseBuilder, TempDir, ZipBuilder, write_file};
use serde_json::Value;
use std::path::PathBuf;
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    fn new() -> Scratch {
        let base = TempDir::new("dlcli-base");
        BaseBuilder::steam().write(base.path());
        let inst = TempDir::new("dlcli-inst");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            inst.path().join("fnv").to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let s = Scratch { _base: base, inst };
        write_file(
            &s.root(),
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n",
        );
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn arg(&self) -> String {
        self.root().to_str().unwrap().to_owned()
    }
}

fn json(args: &[&str]) -> Value {
    let (code, out, err) = nvmod(args);
    assert_eq!(code, 0, "{err}");
    serde_json::from_str(&out).unwrap()
}

fn validate(schema: &str, instance: &Value) {
    let schema: Value = serde_json::from_str(&std::fs::read_to_string(schema).unwrap()).unwrap();
    let validator = jsonschema::validator_for(&schema).unwrap();
    let errors: Vec<String> = validator
        .iter_errors(instance)
        .map(|e| e.to_string())
        .collect();
    assert!(errors.is_empty(), "{errors:?}\n{instance}");
}

fn schema(name: &str) -> String {
    format!("{}/../../schemas/{name}", env!("CARGO_MANIFEST_DIR"))
}

#[test]
fn list_json_matches_its_schema_and_names_with_brackets_work() {
    let s = Scratch::new();
    let dl = s.root().join("downloads");
    std::fs::create_dir_all(&dl).unwrap();
    ZipBuilder::new()
        .file("Rocks.esp", b"p")
        .write(&dl.join("[Rocks] Pack (v2)-77-2-0-1699999999.zip"));
    write_file(&dl, "Loose [x].7z", b"x");
    write_file(
        &dl,
        "Loose [x].7z.meta",
        b"[General]\r\nmodID=5\r\nfileID=6\r\nremoved=true\r\n",
    );
    write_file(
        &s.root(),
        "mods/Rocks/meta.ini",
        b"[General]\r\nmodid=77\r\ninstallationFile=C:\\\\Users\\\\x\\\\Downloads\\\\[Rocks] Pack (v2)-77-2-0-1699999999.zip\r\n",
    );
    let root = s.arg();
    let value = json(&["downloads", "list", "--instance", &root, "--json"]);
    validate(&schema("downloads-list.v1.json"), &value);
    let archives = value["archives"].as_array().unwrap();
    assert_eq!(archives.len(), 2);
    let rocks = archives
        .iter()
        .find(|a| a["file"] == "[Rocks] Pack (v2)-77-2-0-1699999999.zip")
        .unwrap();
    assert_eq!(rocks["state"], "installed");
    assert_eq!(rocks["matched_mod"]["name"], "Rocks");
    assert_eq!(rocks["matched_mod"]["by"], "installation-file");
    assert_eq!(rocks["nexus_mod_id"], 77);
    let loose = archives
        .iter()
        .find(|a| a["file"] == "Loose [x].7z")
        .unwrap();
    assert_eq!(loose["state"], "hidden");
    assert_eq!(loose["nexus_file_id"], 6);
    assert!(!value["archives"].to_string().contains("Users"));

    let value = json(&[
        "downloads",
        "list",
        "--instance",
        &root,
        "--unmatched",
        "--json",
    ]);
    validate(&schema("downloads-list.v1.json"), &value);
    let files: Vec<&str> = value["archives"]
        .as_array()
        .unwrap()
        .iter()
        .map(|a| a["file"].as_str().unwrap())
        .collect();
    assert_eq!(files, ["Loose [x].7z"]);
    assert_eq!(value["mods_without_archive"], serde_json::json!([]));

    let (code, out, _) = nvmod(&["downloads", "list", "--instance", &root]);
    assert_eq!(code, 0);
    assert!(
        out.contains("[Rocks] Pack (v2)-77-2-0-1699999999.zip"),
        "{out}"
    );
}

#[test]
fn show_with_hash_and_a_path_inside_the_folder() {
    let s = Scratch::new();
    let dl = s.root().join("downloads");
    std::fs::create_dir_all(&dl).unwrap();
    write_file(&dl, "abc.zip", b"abc");
    let root = s.arg();
    let value = json(&[
        "downloads",
        "show",
        "abc.zip",
        "--instance",
        &root,
        "--hash",
        "--json",
    ]);
    validate(&schema("downloads-show.v1.json"), &value);
    assert_eq!(value["archive"]["md5"], "900150983cd24fb0d6963f7d28e17f72");
    let by_path = dl.join("abc.zip");
    let value = json(&[
        "downloads",
        "show",
        by_path.to_str().unwrap(),
        "--instance",
        &root,
        "--json",
    ]);
    assert_eq!(value["archive"]["file"], "abc.zip");
    assert_eq!(value["archive"]["md5"], Value::Null);

    let elsewhere = TempDir::new("dlcli-elsewhere");
    write_file(elsewhere.path(), "abc.zip", b"abc");
    let other = elsewhere.path().join("abc.zip");
    let (code, _, err) = nvmod(&[
        "downloads",
        "show",
        other.to_str().unwrap(),
        "--instance",
        &root,
    ]);
    assert_eq!(code, 2, "{err}");
}

#[test]
fn install_marks_the_meta_and_hide_unhide_forget_work() {
    let s = Scratch::new();
    let dl = s.root().join("downloads");
    std::fs::create_dir_all(&dl).unwrap();
    ZipBuilder::new()
        .file("Better.esp", b"p")
        .write(&dl.join("Better.zip"));
    ZipBuilder::new()
        .file("Other.esp", b"p")
        .write(&dl.join("Other.zip"));
    let root = s.arg();

    let (code, _, err) = nvmod(&[
        "downloads",
        "install",
        "Better.zip",
        "--instance",
        &root,
        "--dry-run",
    ]);
    assert_eq!(code, 0, "{err}");
    assert!(!s.root().join("mods/Better").exists());
    assert!(!dl.join("Better.zip.meta").exists());

    let value = json(&[
        "downloads",
        "install",
        "Better.zip",
        "--instance",
        &root,
        "--json",
    ]);
    assert_eq!(value["install"]["mod"], "Better");
    assert_eq!(value["meta"]["written"], true);
    assert_eq!(
        std::fs::read(dl.join("Better.zip.meta")).unwrap(),
        b"[General]\r\ninstalled=true\r\n"
    );

    let value = json(&[
        "downloads",
        "hide",
        "Other.zip",
        "--instance",
        &root,
        "--json",
    ]);
    assert_eq!(value["changed"], true);
    let listed = json(&["downloads", "list", "--instance", &root, "--json"]);
    let states: Vec<(&str, &str)> = listed["archives"]
        .as_array()
        .unwrap()
        .iter()
        .map(|a| (a["file"].as_str().unwrap(), a["state"].as_str().unwrap()))
        .collect();
    assert_eq!(
        states,
        [("Better.zip", "installed"), ("Other.zip", "hidden")]
    );
    json(&[
        "downloads",
        "unhide",
        "Other.zip",
        "--instance",
        &root,
        "--json",
    ]);

    let value = json(&[
        "downloads",
        "forget",
        "Other.zip",
        "--instance",
        &root,
        "--json",
    ]);
    assert!(
        value["trashed_to"]
            .as_str()
            .unwrap()
            .starts_with(".nvmod/trash/downloads/")
    );
    assert!(!dl.join("Other.zip").exists());

    // The Instance lock is released again, and a path outside the folder is refused.
    let (code, _, err) = nvmod(&["downloads", "forget", "../x.zip", "--instance", &root]);
    assert_eq!(code, 2, "{err}");
    let (code, _, _) = nvmod(&["downloads", "bogus"]);
    assert_eq!(code, 5);
    let (code, _, _) = nvmod(&["downloads", "list"]);
    assert_eq!(code, 5);
}

#[test]
fn the_downloads_option_names_another_folder() {
    let s = Scratch::new();
    let elsewhere = TempDir::new("dlcli-other");
    write_file(elsewhere.path(), "Far.zip", b"x");
    let root = s.arg();
    let value = json(&[
        "downloads",
        "list",
        "--instance",
        &root,
        "--downloads",
        elsewhere.path().to_str().unwrap(),
        "--json",
    ]);
    assert_eq!(value["archives"][0]["file"], "Far.zip");
    let (code, _, _) = nvmod(&[
        "downloads",
        "list",
        "--instance",
        &root,
        "--downloads",
        "no-such-folder",
    ]);
    assert_eq!(code, 2);
}

#[test]
fn every_extraction_limit_applies_to_a_downloads_install() {
    let s = Scratch::new();
    let dl = s.root().join("downloads");
    std::fs::create_dir_all(&dl).unwrap();
    ZipBuilder::new()
        .file("a/b/one.txt", &[1; 40])
        .file("two.txt", &[2; 40])
        .write(&dl.join("Limits.zip"));
    let root = s.arg();
    // (flag, a value that refuses, a value just at the limit that installs)
    let cases = [
        ("--max-extract-bytes", "79", "80"),
        ("--max-extract-entries", "1", "2"),
        ("--max-extract-entry-bytes", "39", "40"),
        ("--max-extract-depth", "2", "3"),
        ("--max-extract-operations", "1", "100"),
        ("--max-extract-seconds", "0", "60"),
    ];
    for (flag, refuse, _) in cases {
        let (code, _, err) = nvmod(&[
            "downloads",
            "install",
            "Limits.zip",
            "--instance",
            &root,
            flag,
            refuse,
        ]);
        assert_eq!(code, 2, "{flag} {refuse}: {err}");
        assert!(err.contains(flag), "{flag} should be named in: {err}");
        assert!(!s.root().join("mods/Limits").exists(), "{flag}");
    }
    for (flag, _, allow) in cases {
        let name = format!("Limits {}", flag.trim_start_matches("--max-extract-"));
        let (code, _, err) = nvmod(&[
            "downloads",
            "install",
            "Limits.zip",
            "--instance",
            &root,
            flag,
            allow,
            "--name",
            &name,
        ]);
        assert_eq!(code, 0, "{flag} {allow}: {err}");
    }
    let (code, _, err) = nvmod(&[
        "downloads",
        "install",
        "Limits.zip",
        "--instance",
        &root,
        "--max-extract-ratio",
        "x",
    ]);
    assert_eq!(code, 5, "{err}");
}
