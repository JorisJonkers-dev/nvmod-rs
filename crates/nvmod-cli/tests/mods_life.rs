//! `nvmod mods remove|rename|create|clone|hide|unhide|note`, the separators and the categories, run as a program
//! against a scratch Instance made by `nvmod init`. Plugins and files are synthetic; no game data is used.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";
/// A mod name with characters that mean something to a glob or a list line. Windows file names cannot hold `*`
/// or `?`, so there the name has braces in their place.
#[cfg(not(windows))]
const ODD: &str = "[Odd] Mod v1 *x?";
#[cfg(windows)]
const ODD: &str = "[Odd] Mod v1 {x}";
const CATEGORIES: &[u8] = b"1|Animations|4,51|0\r\n2|Armour|5|0\r\n3|Sub|6|2\r\n";

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Mods `Extra` (C.esp needing B.esp, Textures/Dirt.dds), `Core` (A.esm, B.esp needing A.esm), `Plain`
    /// (Textures/Dirt.dds, Textures/Only.dds), a Mod with brackets and spaces in its name, and a separator; staged.
    fn new() -> Scratch {
        let base = TempDir::new("life-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("life-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod_env(
            &[
                "init",
                "--base",
                base.path().to_str().unwrap(),
                "--instance",
                root.to_str().unwrap(),
            ],
            &[],
        );
        assert_eq!(code, 0, "{err}");
        write_file(&root, "mods/Core/A.esm", &PluginBuilder::master().build());
        write_file(
            &root,
            "mods/Core/B.esp",
            &PluginBuilder::new().requires("A.esm").build(),
        );
        write_file(
            &root,
            "mods/Extra/C.esp",
            &PluginBuilder::new().requires("B.esp").build(),
        );
        write_file(&root, "mods/Extra/Textures/Dirt.dds", b"Extra");
        write_file(&root, "mods/Plain/Textures/Dirt.dds", b"Plain");
        write_file(&root, "mods/Plain/Textures/Only.dds", b"Only");
        write_file(&root, &format!("mods/{ODD}/Meshes/m.nif"), b"odd");
        write_file(&root, "mods/Group_separator/meta.ini", b"[General]\r\n");
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            format!("{HEADER}+Extra\r\n+Core\r\n-Group_separator\r\n+Plain\r\n+{ODD}\r\n")
                .as_bytes(),
        );
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            b"FalloutNV.esm\r\nA.esm\r\nB.esp\r\nC.esp\r\n",
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"FalloutNV.esm\r\nA.esm\r\nB.esp\r\nC.esp\r\n",
        );
        let s = Scratch { _base: base, inst };
        let (code, _, err) = nvmod_env(&["stage", "--instance", root.to_str().unwrap()], &[]);
        assert_eq!(code, 0, "{err}");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn run(&self, args: &[&str]) -> (i32, String, String) {
        self.run_env(args, &[])
    }

    fn run_env(&self, args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
        let root = self.root();
        let mut all = vec!["mods"];
        all.extend_from_slice(args);
        all.extend_from_slice(&["--instance", root.to_str().unwrap()]);
        nvmod_env(&all, env)
    }

    fn json(&self, args: &[&str]) -> Value {
        let mut all = args.to_vec();
        all.push("--json");
        let (code, out, err) = self.run(&all);
        assert_eq!(code, 0, "{args:?}: {err}");
        serde_json::from_str(&out).unwrap()
    }

    fn rollback(&self) {
        let (code, _, err) = nvmod_env(
            &["rollback", "--instance", self.root().to_str().unwrap()],
            &[],
        );
        assert_eq!(code, 0, "{err}");
    }

    fn modlist(&self) -> String {
        fs::read_to_string(self.root().join("profiles/Default/modlist.txt")).unwrap()
    }

    fn file(&self, rel: &str) -> String {
        fs::read_to_string(self.root().join(rel)).unwrap()
    }

    fn tree(&self) -> BTreeMap<String, Vec<u8>> {
        snapshot(&self.root())
            .into_iter()
            // The manifest of a built tree holds the file ids and times of the files it linked: not byte-identical
            // after the tree is built again.
            .filter(|(k, _)| {
                !(k.starts_with(".nvmod") || (k.starts_with("staging/") && k.contains(".json")))
            })
            .collect()
    }

    fn staged(&self, rel: &str) -> Option<Vec<u8>> {
        fs::read(self.root().join("staging/Default/data").join(rel)).ok()
    }
}

#[test]
fn remove_then_rollback_restores_every_file_and_list_line() {
    let s = Scratch::new();
    let before = s.tree();
    let r = s.json(&["remove", "Plain"]);
    assert_eq!(r["status"], "changed");
    assert!(!s.root().join("mods/Plain").exists());
    assert!(!s.modlist().contains("Plain"));
    assert!(s.staged("textures/only.dds").is_none());
    assert_eq!(s.staged("textures/dirt.dds").unwrap(), b"Extra");
    let trash = format!(
        ".nvmod/trash/{}/Plain/Textures/Only.dds",
        r["journal"].as_str().unwrap()
    );
    assert!(s.root().join(trash).is_file());
    s.rollback();
    assert_eq!(s.tree(), before);
}

#[test]
fn removing_a_mod_other_plugins_need_names_the_dependants_and_needs_force() {
    let s = Scratch::new();
    let before = s.tree();
    let (code, _, err) = s.run(&["remove", "Core"]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains("C.esp") && err.contains("--force"), "{err}");
    assert_eq!(s.tree(), before);
    let r = s.json(&["remove", "Core", "--force"]);
    assert_eq!(r["dependants"], serde_json::json!(["C.esp"]));
    assert_eq!(r["plugins_dropped"], serde_json::json!(["A.esm", "B.esp"]));
    let plugins = s.file("profiles/Default/plugins.txt");
    assert!(plugins.contains("C.esp") && !plugins.contains("B.esp") && !plugins.contains("A.esm"));
    assert!(!s.file("profiles/Default/loadorder.txt").contains("B.esp"));
    s.rollback();
    assert_eq!(s.tree(), before);
}

