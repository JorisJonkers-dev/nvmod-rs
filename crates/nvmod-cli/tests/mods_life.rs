#[test]
fn a_clone_named_like_a_backup_is_not_listed_and_not_staged() {
    let s = Scratch::new();
    let before_list = s.modlist();
    let staged = s
        .tree()
        .keys()
        .filter(|k| k.starts_with("staging/"))
        .count();
    let r = s.json(&["clone", "Plain"]);
    assert_eq!(r["name"], "Plain backup");
    assert_eq!(s.modlist(), before_list);
    assert_eq!(s.file("mods/Plain backup/Textures/Only.dds"), "Only");
    assert!(r["staged_files"].is_null() || r["listed"] == false);
    let again = s.json(&["clone", "Plain"]);
    assert_eq!(again["name"], "Plain backup1");
    let named = s.json(&["clone", "Plain", "--name", "Plain backup7"]);
    assert_eq!(named["name"], "Plain backup7");
    assert_eq!(s.modlist(), before_list);
    assert_eq!(
        s.tree()
            .keys()
            .filter(|k| k.starts_with("staging/"))
            .count(),
        staged
    );
    let (code, _, _) = s.run(&["clone", "Plain", "--name", "Plain backup"]);
    assert_eq!(code, 2);
    // A backup is addressed by its folder name, and can be removed and rolled back.
    let before = s.tree();
    let (code, _, err) = s.run(&["remove", "Plain backup1"]);
    assert_eq!(code, 0, "{err}");
    assert!(!s.root().join("mods/Plain backup1").exists());
    s.rollback();
    assert_eq!(s.tree(), before);
}

#[test]
fn a_clone_with_another_name_is_listed_disabled_below_the_original_and_can_hard_link() {
    let s = Scratch::new();
    let r = s.json(&["clone", "Plain", "--name", "Plain tweaked", "--hardlink"]);
    assert_eq!(r["listed"], true);
    assert!(s.modlist().contains("+Plain\r\n-Plain tweaked\r\n"));
    assert_eq!(s.staged("textures/dirt.dds").unwrap(), b"Extra");
    // A hard link is a plain file that shares its data with the original, so a write through the clone shows in
    // the original. The check holds on every platform, unlike a link count.
    let linked = s.root().join("mods/Plain tweaked/Textures/Only.dds");
    assert!(
        fs::symlink_metadata(&linked).unwrap().is_file(),
        "not a symlink"
    );
    fs::write(&linked, b"Linked").unwrap();
    assert_eq!(
        fs::read(s.root().join("mods/Plain/Textures/Only.dds")).unwrap(),
        b"Linked",
        "hard linked"
    );
}

#[test]
fn hide_and_unhide_round_trip_a_file_and_the_staging_tree_follows() {
    let s = Scratch::new();
    let before = s.tree();
    assert_eq!(s.staged("textures/dirt.dds").unwrap(), b"Extra");
    let (code, _, err) = s.run(&["hide", "Extra", "Textures/Dirt.dds"]);
    assert_eq!(code, 0, "{err}");
    assert!(
        s.root()
            .join("mods/Extra/Textures/Dirt.dds.mohidden")
            .is_file()
    );
    assert_eq!(s.staged("textures/dirt.dds").unwrap(), b"Plain");
    for args in [
        &["hide", "Extra", "Textures/Dirt.dds"][..],
        &["hide", "Extra", "../Core/A.esm"],
        &["hide", "Extra", "meta.ini"],
        &["hide", "Extra", "Textures/Dirt.dds.mohidden"],
        &["unhide", "Extra", "Textures/Nope.dds"],
    ] {
        let (code, _, err) = s.run(args);
        assert_eq!(code, 2, "{args:?}: {err}");
    }
    let (code, _, err) = s.run(&["unhide", "Extra", "Textures/Dirt.dds"]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(s.staged("textures/dirt.dds").unwrap(), b"Extra");
    assert_eq!(s.tree(), before);
    // Rolling the hide back also works.
    let (code, _, _) = s.run(&["hide", "Extra", "Textures/Dirt.dds"]);
    assert_eq!(code, 0);
    s.rollback();
    assert_eq!(s.tree(), before);
    // The conflict report reflects a hidden file.
    let conflicts = |s: &Scratch| -> usize {
        let (code, out, err) = nvmod_env(
            &[
                "conflicts",
                "--instance",
                s.root().to_str().unwrap(),
                "--json",
            ],
            &[],
        );
        assert_eq!(code, 0, "{err}");
        let v: Value = serde_json::from_str(&out).unwrap();
        v["conflicts"].as_array().unwrap().len()
    };
    assert_eq!(conflicts(&s), 1);
    let (code, _, _) = s.run(&["hide", "Extra", "Textures/Dirt.dds"]);
    assert_eq!(code, 0);
    assert_eq!(conflicts(&s), 0);
}

