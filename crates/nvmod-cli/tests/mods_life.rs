#[test]
fn a_separator_has_mo2s_form_and_removing_it_leaves_the_other_lines() {
    let s = Scratch::new();
    let before_list = s.modlist();
    let before = s.tree();
    let (code, _, err) = s.run(&["separator", "add", "Gameplay [core]", "--before", "Core"]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(
        s.modlist(),
        format!(
            "{HEADER}+Extra\r\n-Gameplay [core]_separator\r\n+Core\r\n-Group_separator\r\n+Plain\r\n+{ODD}\r\n"
        )
    );
    assert_eq!(
        s.file("mods/Gameplay [core]_separator/meta.ini"),
        "[General]\r\nmodid=0\r\nversion=\r\nnewestVersion=\r\ncategory=0\r\ninstallationFile=\r\n"
    );
    assert_eq!(
        fs::read_dir(s.root().join("mods/Gameplay [core]_separator"))
            .unwrap()
            .count(),
        1
    );
    let list = s.json(&["list"]);
    assert_eq!(list["mods"][1]["kind"], "separator");
    let (code, _, err) = s.run(&["separator", "rename", "Gameplay [core]", "Core things"]);
    assert_eq!(code, 0, "{err}");
    assert!(s.modlist().contains("-Core things_separator\r\n"));
    assert!(
        s.root()
            .join("mods/Core things_separator/meta.ini")
            .is_file()
    );
    let (code, _, err) = s.run(&["separator", "remove", "Core things"]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(s.modlist(), before_list);
    assert!(!s.root().join("mods/Core things_separator").exists());
    for args in [
        &["separator", "add", "Group", "--top"][..],
        &["separator", "add", "Group", "--after", "Nope"],
        &["separator", "add", "New"],
        &["separator", "remove", "Plain"],
        &["separator", "rename", "Nope", "x"],
    ] {
        let (code, _, err) = s.run(args);
        assert!(code == 2 || code == 5, "{args:?}: {code} {err}");
    }
    let (code, _, _) = s.run(&["separator", "add", "Group", "--after", "Core"]);
    assert_eq!(code, 2, "a separator of that label exists");
    s.rollback();
    s.rollback();
    s.rollback();
    assert_eq!(s.tree(), before);
}

