#[test]
fn rename_updates_the_folder_and_the_line_and_refuses_an_existing_name() {
    let s = Scratch::new();
    let before = s.tree();
    for to in [
        "Core",
        "core",
        "Group_separator",
        "a/b",
        "New backup2",
        "X_separator",
        " pad",
    ] {
        let (code, _, err) = s.run(&["rename", "Plain", to]);
        assert_eq!(code, 2, "{to}: {err}");
    }
    assert_eq!(s.tree(), before, "a refusal changes nothing");
    let (code, _, err) = s.run(&["rename", ODD, "Odd [2] renamed"]);
    assert_eq!(code, 0, "{err}");
    assert!(s.modlist().contains("+Odd [2] renamed\r\n"));
    assert!(s.root().join("mods/Odd [2] renamed/Meshes/m.nif").is_file());
    assert!(!s.root().join("mods").join(ODD).exists());
    assert_eq!(s.staged("meshes/m.nif").unwrap(), b"odd");
    s.rollback();
    assert_eq!(s.tree(), before);
}

