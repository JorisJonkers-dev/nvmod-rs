fn a_failing_step_puts_everything_back_and_exits_4() {
    for step in ["mod", "lists", "stage"] {
        for args in [
            &["remove", "Core", "--force"][..],
            &["rename", "Plain", "Other"],
            &["separator", "add", "S", "--after", "Core"],
            &["clone", "Plain", "--name", "Plain two"],
        ] {
            let s = Scratch::new();
            let before = s.tree();
            let (code, _, err) = s.run_env(args, &[("NVMOD_FAIL_AT", step)]);
            if code == 0 {
                continue; // this action has no such step
            }
            assert_eq!(code, 4, "{step} {args:?}: {err}");
            assert_eq!(s.tree(), before, "{step} {args:?}");
        }
    }
}

#[test]
fn a_dry_run_writes_nothing_and_usage_errors_exit_5() {
    let s = Scratch::new();
    let before = s.tree();
    for args in [
        &["remove", "Plain", "--dry-run"][..],
        &["rename", "Plain", "Z", "--dry-run"],
        &["create", "Z", "--dry-run"],
        &["clone", "Plain", "--dry-run"],
        &["hide", "Extra", "Textures/Dirt.dds", "--dry-run"],
        &["note", "Plain", "x", "--dry-run"],
        &["separator", "add", "S", "--top", "--dry-run"],
    ] {
        let (code, out, err) = s.run(args);
        assert!(code == 0 || code == 5, "{args:?}: {code} {err} {out}");
    }
    assert_eq!(s.tree(), before);
    let r = s.json(&["remove", "Plain", "--dry-run"]);
    assert_eq!(r["status"], "dry-run");
    for args in [
        &["remove"][..],
        &["rename", "Plain"],
        &["clone"],
        &["category"],
        &["separator", "add"],
    ] {
        let (code, _, _) = s.run(args);
        assert_eq!(code, 5, "{args:?}");
    }
}
