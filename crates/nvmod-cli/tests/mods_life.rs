#[test]
fn categories_are_set_listed_filtered_and_the_file_is_untouched() {
    let s = Scratch::new();
    write_file(&s.root(), "categories.dat", CATEGORIES);
    let (code, _, err) = s.run(&["category", "set", "Plain", "2", "1"]);
    assert_eq!(code, 0, "{err}");
    assert!(s.file("mods/Plain/meta.ini").contains("category=\"2,1,\""));
    let (code, _, _) = s.run(&["category", "set", "Core", "3"]);
    assert_eq!(code, 0);
    let (code, _, err) = s.run(&["category", "set", "Extra", "9"]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains('9'), "{err}");
    let (code, _, _) = s.run(&["category", "set", "Extra", "x"]);
    assert_eq!(code, 5);
    assert_eq!(
        fs::read(s.root().join("categories.dat")).unwrap(),
        CATEGORIES
    );
    // An id the file does not know (written by hand or another tool) is reported with no name, not dropped.
    write_file(
        &s.root(),
        &format!("mods/{ODD}/meta.ini"),
        b"[General]\r\ncategory=\"7,\"\r\n",
    );
    let v = s.json(&["list"]);
    let plain = v["mods"]
        .as_array()
        .unwrap()
        .iter()
        .find(|m| m["name"] == "Plain")
        .unwrap();
    assert_eq!(
        plain["categories"],
        serde_json::json!([{"id": 2, "name": "Armour"}, {"id": 1, "name": "Animations"}])
    );
    let odd = v["mods"]
        .as_array()
        .unwrap()
        .iter()
        .find(|m| m["name"] == ODD)
        .unwrap();
    assert_eq!(
        odd["categories"],
        serde_json::json!([{"id": 7, "name": null}])
    );
    let v = s.json(&["list", "--category", "1"]);
    let names: Vec<&str> = v["mods"]
        .as_array()
        .unwrap()
        .iter()
        .map(|m| m["name"].as_str().unwrap())
        .collect();
    assert_eq!(names, ["Plain"]);
    let (code, _, _) = s.run(&["list", "--category", "abc"]);
    assert_eq!(code, 2);
    let (code, _, _) = s.run(&["category", "set", "Plain"]);
    assert_eq!(code, 0);
    assert!(!s.file("mods/Plain/meta.ini").contains("category"));
    assert_eq!(
        fs::read(s.root().join("categories.dat")).unwrap(),
        CATEGORIES
    );
}

// The game guard reads the run of this Instance from `.nvmod/lock`, written here with the pid of this test program:
// a live process that is not called `nv-viewer`, standing in for a long-running game.
fn hold(root: &std::path::Path, command: &str) {
    write_file(
        root,
        ".nvmod/lock",
        format!(
            r#"{{"pid":{},"started":1,"command":"{command}"}}"#,
            std::process::id()
        )
        .as_bytes(),
    );
}

#[test]
fn a_running_game_of_the_instance_refuses_a_change_but_not_a_dry_run() {
    let s = Scratch::new();
    hold(&s.root(), "run raul --play-mode");
    let before = s.tree();
    let (code, _, err) = s.run_env(&["remove", "Plain"], &[]);
    assert_eq!(code, 2, "{err}");
    assert!(
        err.contains("running") && err.contains("raul --play-mode"),
        "{err}"
    );
    let (code, _, err) = s.run_env(&["remove", "Plain", "--dry-run"], &[]);
    assert_eq!(code, 0, "{err}");
    assert_eq!(s.tree(), before);
}

#[test]
fn a_game_of_another_instance_does_not_refuse_a_change() {
    let s = Scratch::new();
    // The game runs from another Instance (its lock is there), and a process named like the game is in the
    // process list: neither concerns this Instance.
    hold(&s.inst.path().join("other"), "run nv-rs");
    let procs = TempDir::new("ml-proc");
    write_file(procs.path(), "4242/comm", b"nv-viewer\n");
    write_file(procs.path(), "4242/stat", b"4242 (nv-viewer) S 1 1 1\n");
    let env = [("NVMOD_PROC_DIR", procs.path().to_str().unwrap())];
    let (code, _, err) = s.run_env(&["remove", "Plain"], &env);
    assert_eq!(code, 0, "{err}");
}

