//! What is built in per target (ticket 29), run as a program: `nvmod catalog` and `nvmod doctor --instance` on
//! scratch Instances of both targets. The catalogue and the installed nv-rs's `capabilities.json` are synthetic
//! and written here; every number in a test is made up for the test.

// Tests start the built `nvmod` binary itself; the runner rule (ADR-0005) is for the product code.
#![allow(clippy::disallowed_methods)]

use nvmod_testkit::{
    BaseBuilder, PeBuilder, PluginBuilder, TempDir, capabilities_json, write_file,
};
use serde_json::Value;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

const PROV: &str = "[plugin.provenance]\nsource = \"test fixture\"\nverified_on = \"2026-11-14\"\nverified = false\n";

/// `core` is the extender itself; `alpha` is partly built in, `beta` fully; `gamma` is absent on nv-rs; `delta`
/// says nothing about nv-rs.
fn catalogue() -> String {
    let entry = |id: &str, name: &str, dll: &str, extra: &str| {
        format!("[[plugin]]\nid = \"{id}\"\nname = \"{name}\"\ndll = \"{dll}\"\n{extra}\n{PROV}\n")
    };
    let builtin = |kind: &str, extender: &str| {
        format!("[plugin.provided_by.nv-rs]\nkind = \"{kind}\"\nextender = \"{extender}\"\n")
    };
    let mut text = String::from("schema = 1\n");
    text += &entry(
        "core",
        "Core Extender",
        "nvse_1_4.dll",
        &format!(
            "role = \"extender\"\n{}",
            builtin("builtin-partial", "ext-core")
        ),
    );
    text += &entry(
        "alpha",
        "Alpha Plugin",
        "Alpha.dll",
        &builtin("builtin-partial", "ext-a"),
    );
    text += &entry(
        "beta",
        "Beta Plugin",
        "Beta.dll",
        &builtin("builtin-full", "ext-b"),
    );
    text += &entry(
        "gamma",
        "Gamma Plugin",
        "Gamma.dll",
        "[plugin.provided_by.nv-rs]\nkind = \"absent\"\n",
    );
    text += &entry("delta", "Delta Plugin", "Delta.dll", "");
    text
}

struct Scratch {
    base: TempDir,
    inst: TempDir,
    catalog: String,
}

impl Scratch {
    /// An Instance of `target` with one Mod holding all four plugin DLLs, staged. The base copy has no xNVSE.
    fn new(target: &str) -> Scratch {
        let base = TempDir::new("builtin-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("builtin-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let file = root.join("nvmod-instance.json");
        let text = fs::read_to_string(&file).unwrap();
        let mut json: Value = serde_json::from_str(&text).unwrap();
        json["target"] = target.into();
        fs::write(&file, serde_json::to_string_pretty(&json).unwrap()).unwrap();
        let dll = PeBuilder::nvse_plugin().build();
        for name in ["Alpha", "Beta", "Gamma", "Delta"] {
            write_file(&root, &format!("mods/Core/NVSE/Plugins/{name}.dll"), &dll);
        }
        write_file(&root, "mods/Core/Base.esp", &PluginBuilder::new().build());
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n+Core\r\n",
        );
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nBase.esp\r\n",
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nBase.esp\r\n",
        );
        let (code, _, err) = nvmod(&["stage", "--instance", root.to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
        let catalog = inst.path().join("catalog.toml");
        fs::write(&catalog, catalogue()).unwrap();
        let catalog = catalog.to_str().unwrap().to_owned();
        Scratch {
            base,
            inst,
            catalog,
        }
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn capabilities(&self, text: &str) {
        write_file(&self.root(), "nv-rs/capabilities.json", text.as_bytes());
    }

    fn doctor(&self) -> Value {
        let root = self.root();
        let (_, out, err) = nvmod(&[
            "doctor",
            "--instance",
            root.to_str().unwrap(),
            "--catalog",
            &self.catalog,
            "--json",
        ]);
        serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out} / {err}"))
    }
}

/// `(severity, message)` of the first finding with this code and subject.
fn finding(report: &Value, code: &str, subject: &str) -> Option<(String, String)> {
    report["findings"]
        .as_array()
        .unwrap()
        .iter()
        .find(|f| f["code"] == code && f["subject"] == subject)
        .map(|f| {
            (
                f["severity"].as_str().unwrap().to_owned(),
                f["message"].as_str().unwrap().to_owned(),
            )
        })
}

fn codes(report: &Value) -> Vec<String> {
    report["findings"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["code"].as_str().unwrap().to_owned())
        .collect()
}

const FULL: [(&str, &str, u64, u64); 3] = [
    ("ext-core", "Core Extender", 9, 10),
    ("ext-a", "Alpha Extender", 7, 10),
    ("ext-b", "Beta Extender", 5, 5),
];

#[test]
fn on_the_vanilla_target_the_extender_dll_is_required_and_nothing_is_built_in() {
    let s = Scratch::new("vanilla");
    s.capabilities(&capabilities_json(&FULL));
    let report = s.doctor();
    let (severity, message) =
        finding(&report, "extender.missing", "nvse_1_4.dll").expect("missing");
    assert_eq!(severity, "error", "{message}");
    assert!(
        message.contains("Core Extender") && message.contains("vanilla"),
        "{message}"
    );
    write_file(
        s.base.path(),
        "nvse_1_4.dll",
        &PeBuilder::dll()
            .versions([6, 3, 0, 0], [6, 3, 0, 0])
            .build(),
    );
    let report = s.doctor();
    let all = codes(&report);
    assert!(!all.contains(&"extender.missing".to_owned()), "{all:?}");
    for code in all {
        assert!(
            !code.starts_with("capabilities.")
                && code != "extender.coverage"
                && code != "plugin.redundant-on-nv-rs"
                && code != "plugin.unable-to-load-on-nv-rs"
                && code != "plugin.nv-rs-unknown",
            "{code}"
        );
    }
    assert_eq!(report["target"], "vanilla");
    assert!(report["nv_rs"].is_null());
}

#[test]
fn on_nv_rs_no_extender_dll_is_required_and_coverage_comes_from_capabilities_json() {
    let s = Scratch::new("nv-rs");
    s.capabilities(&capabilities_json(&FULL));
    let report = s.doctor();
    assert!(finding(&report, "extender.missing", "nvse_1_4.dll").is_none());
    assert_eq!(report["target"], "nv-rs");
    assert_eq!(report["nv_rs"]["capabilities"]["status"], "used");
    assert!(
        report["nv_rs"]["capabilities"]["path"]
            .as_str()
            .unwrap()
            .ends_with("nv-rs/capabilities.json")
    );
    let ext = report["nv_rs"]["extenders"].as_array().unwrap();
    let a = ext.iter().find(|e| e["id"] == "ext-a").unwrap();
    assert_eq!(
        (
            a["implemented"].as_u64(),
            a["total"].as_u64(),
            a["missing"].as_u64()
        ),
        (Some(7), Some(10), Some(3))
    );
    let (severity, message) =
        finding(&report, "extender.coverage", "Alpha Plugin").expect("coverage");
    assert!(
        severity == "warning" && message.contains("7 of 10") && message.contains("3 missing"),
        "{severity}: {message}"
    );
    assert!(
        message.contains("capabilities.json"),
        "says which coverage it used: {message}"
    );
    let (_, message) = finding(&report, "extender.coverage", "Core Extender").expect("core");
    assert!(
        message.contains("9 of 10") && message.contains("1 missing"),
        "{message}"
    );
    let (severity, message) =
        finding(&report, "extender.coverage", "Beta Plugin").expect("complete");
    assert!(
        severity == "info" && message.contains("5 of 5") && !message.contains("missing"),
        "{message}"
    );
}

#[test]
fn on_nv_rs_a_plugin_dll_that_is_built_in_is_redundant() {
    let s = Scratch::new("nv-rs");
    s.capabilities(&capabilities_json(&FULL));
    let report = s.doctor();
    for dll in ["Alpha.dll", "Beta.dll"] {
        let (severity, message) = finding(&report, "plugin.redundant-on-nv-rs", dll).expect(dll);
        assert_eq!(severity, "info");
        assert!(
            message.contains("built in") && message.contains("not needed"),
            "{message}"
        );
    }
    assert!(finding(&report, "plugin.redundant-on-nv-rs", "Delta.dll").is_none());
}

#[test]
fn on_nv_rs_a_plugin_the_catalogue_marks_absent_is_unable_to_load_by_name() {
    let s = Scratch::new("nv-rs");
    s.capabilities(&capabilities_json(&FULL));
    let report = s.doctor();
    let (severity, message) =
        finding(&report, "plugin.unable-to-load-on-nv-rs", "Gamma.dll").expect("gamma");
    assert_eq!(severity, "error");
    assert!(message.contains("Gamma Plugin"), "{message}");
    // The same file on the vanilla target is not a problem.
    let v = Scratch::new("vanilla");
    assert!(finding(&v.doctor(), "plugin.unable-to-load-on-nv-rs", "Gamma.dll").is_none());
}

#[test]
fn on_nv_rs_an_external_plugin_is_reported_unknown_and_never_as_loading() {
    let s = Scratch::new("nv-rs");
    s.capabilities(&capabilities_json(&FULL));
    let report = s.doctor();
    let (severity, message) = finding(&report, "plugin.nv-rs-unknown", "Delta.dll").expect("delta");
    assert_eq!(severity, "info");
    assert!(
        message.contains("unknown")
            && message.contains("Delta Plugin")
            && !message.contains("loads on nv-rs"),
        "{message}"
    );
}

#[test]
fn a_missing_capabilities_file_is_a_warning_that_says_no_coverage_was_used() {
    let s = Scratch::new("nv-rs");
    let report = s.doctor();
    let (severity, message) = finding(&report, "capabilities.missing", "nv-rs").expect("missing");
    assert_eq!(severity, "warning");
    assert!(
        message.contains("no coverage") && message.contains("capabilities.json"),
        "{message}"
    );
    assert_eq!(report["nv_rs"]["capabilities"]["status"], "missing");
    assert!(report["nv_rs"]["capabilities"]["path"].is_string());
    assert!(!codes(&report).contains(&"extender.coverage".to_owned()));
    // The DLLs are still classified from the catalogue.
    assert!(finding(&report, "plugin.redundant-on-nv-rs", "Alpha.dll").is_some());
    assert!(finding(&report, "plugin.unable-to-load-on-nv-rs", "Gamma.dll").is_some());
}

#[test]
fn a_capabilities_file_that_cannot_be_used_or_lacks_an_extender_is_a_warning() {
    let s = Scratch::new("nv-rs");
    s.capabilities("not json");
    let report = s.doctor();
    let (severity, message) = finding(&report, "capabilities.invalid", "nv-rs").expect("invalid");
    assert_eq!(severity, "warning");
    assert!(message.contains("no coverage"), "{message}");
    assert_eq!(report["nv_rs"]["capabilities"]["status"], "invalid");

    s.capabilities(&capabilities_json(&[("ext-core", "Core Extender", 9, 10)]));
    let report = s.doctor();
    let (severity, message) = finding(&report, "capabilities.stale", "nv-rs").expect("stale");
    assert!(
        severity == "warning" && message.contains("ext-a") && message.contains("ext-b"),
        "{message}"
    );
    assert_eq!(report["nv_rs"]["capabilities"]["status"], "stale");
    // What the file does say is still used.
    assert!(finding(&report, "extender.coverage", "Core Extender").is_some());
}

#[test]
fn the_file_wins_over_the_catalogue_when_a_fully_built_in_extender_is_not_complete() {
    let s = Scratch::new("nv-rs");
    s.capabilities(&capabilities_json(&[
        ("ext-core", "Core Extender", 10, 10),
        ("ext-a", "Alpha Extender", 7, 10),
        ("ext-b", "Beta Extender", 4, 5),
    ]));
    let report = s.doctor();
    let (severity, message) = finding(&report, "extender.coverage", "Beta Plugin").expect("beta");
    assert_eq!(severity, "warning");
    assert!(
        message.contains("4 of 5")
            && message.contains("1 missing")
            && message.contains("fully built in"),
        "{message}"
    );
}

#[test]
fn the_catalogue_lists_what_provides_each_entry_per_target() {
    let (code, out, _) = nvmod(&["catalog", "--json"]);
    assert_eq!(code, 0);
    let json: Value = serde_json::from_str(&out).unwrap();
    let plugins = json["plugins"].as_array().unwrap();
    let jip = plugins.iter().find(|p| p["id"] == "jip-ln").unwrap();
    assert_eq!(jip["provided_by"]["vanilla"]["kind"], "external");
    assert_eq!(jip["provided_by"]["nv-rs"]["kind"], "builtin-partial");
    assert_eq!(jip["provided_by"]["nv-rs"]["extender"], "jip-ln");
    // No coverage number is typed into the catalogue.
    assert!(
        !out.contains("implemented") && !out.contains("\"total\""),
        "{out}"
    );
    let (_, text, _) = nvmod(&["catalog"]);
    assert!(text.contains("nv-rs: builtin-partial"), "{text}");
}

#[test]
fn the_catalogue_shows_the_coverage_of_the_installed_nv_rs_when_given_an_instance() {
    let s = Scratch::new("nv-rs");
    s.capabilities(&capabilities_json(&FULL));
    let root = s.root();
    let (code, out, err) = nvmod(&[
        "catalog",
        "--catalog",
        &s.catalog,
        "--instance",
        root.to_str().unwrap(),
    ]);
    assert_eq!(code, 0, "{err}");
    assert!(
        out.contains("7 of 10") && out.contains("capabilities.json"),
        "{out}"
    );
    let (_, out, _) = nvmod(&["catalog", "--catalog", &s.catalog]);
    assert!(
        out.contains("Alpha.dll") && !out.contains("7 of 10"),
        "{out}"
    );
}

#[test]
fn on_the_vanilla_target_the_extender_dll_is_checked_against_the_catalogue_version() {
    let s = Scratch::new("vanilla");
    write_file(
        s.base.path(),
        "nvse_1_4.dll",
        &PeBuilder::dll()
            .versions([6, 3, 0, 0], [6, 3, 0, 0])
            .build(),
    );
    let report = s.doctor();
    let (severity, message) =
        finding(&report, "extender.version-unknown", "nvse_1_4.dll").expect("unknown");
    assert!(
        severity == "info" && message.contains("unknown"),
        "{message}"
    );
    let with_version = catalogue().replace(
        "role = \"extender\"",
        "role = \"extender\"\nversion = \"6.4.0.0\"",
    );
    fs::write(&s.catalog, with_version).unwrap();
    let report = s.doctor();
    let (severity, message) =
        finding(&report, "extender.version-mismatch", "nvse_1_4.dll").expect("mismatch");
    assert!(
        severity == "warning" && message.contains("6.4.0.0") && message.contains("6.3.0.0"),
        "{message}"
    );
    let right = catalogue().replace(
        "role = \"extender\"",
        "role = \"extender\"\nversion = \"6.3.0.0\"",
    );
    fs::write(&s.catalog, right).unwrap();
    let all = codes(&s.doctor());
    assert!(
        !all.iter().any(|c| c.starts_with("extender.version")),
        "{all:?}"
    );
}
