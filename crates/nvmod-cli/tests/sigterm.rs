//! SIGTERM and SIGINT during a writing command, against the real binary: the step in flight is rolled back, the
//! `finished` record says so, and the exit code is 4. A step is held open by the test hook `NVMOD_PAUSE_AT=<step>`, which creates `NVMOD_PAUSE_FILE`
//! when the step is reached. No game data is used.
#![cfg(unix)]
use nvmod_testkit::{
    BaseBuilder, Mo2Builder, ModSpec, PeBuilder, PluginBuilder, TempDir, ZipBuilder, snapshot,
    write_file,
};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};
use std::time::{Duration, Instant};

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

/// Run `nvmod args`, hold it at `step`, send `signal` (`TERM` or `INT`) and return what it printed.
fn interrupt(args: &[String], step: &str, signal: &str, work: &Path) -> Output {
    let marker = work.join("paused");
    let _ = std::fs::remove_file(&marker);
    let child = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .env("NVMOD_PAUSE_AT", step)
        .env("NVMOD_PAUSE_FILE", &marker)
        .env_remove("NVMOD_FAIL_AT")
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    let start = Instant::now();
    while !marker.exists() {
        assert!(
            start.elapsed() < Duration::from_secs(60),
            "the command never reached step `{step}`"
        );
        std::thread::sleep(Duration::from_millis(10));
    }
    // The kill program sends the signal: the standard library has none and this repository forbids unsafe.
    let status = Command::new("kill")
        .args([format!("-{signal}"), child.id().to_string()])
        .status()
        .unwrap();
    assert!(status.success());
    child.wait_with_output().unwrap()
}

/// A snapshot of an Instance without `.nvmod` (the journals stay as the record of what happened).
fn without_journal(
    mut state: std::collections::BTreeMap<String, Vec<u8>>,
) -> std::collections::BTreeMap<String, Vec<u8>> {
    state.retain(|k, _| !k.starts_with(".nvmod"));
    state
}

fn strings(words: &[&str]) -> Vec<String> {
    words.iter().map(|w| (*w).to_owned()).collect()
}

fn last_json_line(out: &Output) -> Value {
    let text = String::from_utf8_lossy(&out.stdout);
    let line = text.lines().last().unwrap_or_default();
    serde_json::from_str(line)
        .unwrap_or_else(|e| panic!("{e}: {text} / {}", String::from_utf8_lossy(&out.stderr)))
}

fn base_copy() -> TempDir {
    let base = TempDir::new("sigterm-base");
    BaseBuilder::steam().write(base.path());
    write_file(base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
    write_file(
        base.path(),
        "Data/FalloutNV.esm",
        &PluginBuilder::master().build(),
    );
    base
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
    work: TempDir,
}

impl Scratch {
    /// An Instance with one Mod `Existing`, staged, and a Load order that `sort --apply` changes.
    fn new() -> Scratch {
        let base = base_copy();
        let inst = TempDir::new("sigterm-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        write_file(
            &root,
            "mods/Patch/Patch.esp",
            &PluginBuilder::new().requires("Base.esp").build(),
        );
        write_file(&root, "mods/Core/Base.esp", &PluginBuilder::new().build());
        write_file(&root, "mods/Core/Textures/Dirt.dds", b"dirt");
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            format!("{header}+Patch\r\n+Core\r\n").as_bytes(),
        );
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            format!("{header}FalloutNV.esm\r\nPatch.esp\r\nBase.esp\r\n").as_bytes(),
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            format!("{header}FalloutNV.esm\r\nPatch.esp\r\nBase.esp\r\n").as_bytes(),
        );
        let (code, _, err) = nvmod(&["stage", "--instance", root.to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
        let work = TempDir::new("sigterm-work");
        std::fs::write(
            work.path().join("masterlist.yaml"),
            "globals:\n  - {type: say, content: 'Masterlist for tests'}\nplugins: []\n",
        )
        .unwrap();
        Scratch {
            _base: base,
            inst,
            work,
        }
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn root_str(&self) -> String {
        self.root().to_str().unwrap().to_owned()
    }

    fn zip(&self, name: &str) -> String {
        let path = self.work.path().join(name);
        ZipBuilder::new()
            .file("Late.esp", &PluginBuilder::new().build())
            .write(&path);
        path.to_str().unwrap().to_owned()
    }

    fn journals(&self) -> Vec<Value> {
        let dir = self.root().join(".nvmod/journal");
        let Ok(entries) = std::fs::read_dir(dir) else {
            return Vec::new();
        };
        let mut ids: Vec<_> = entries.flatten().map(|e| e.path()).collect();
        ids.sort();
        ids.iter()
            .map(|p| {
                serde_json::from_slice(&std::fs::read(p.join("journal.json")).unwrap()).unwrap()
            })
            .collect()
    }
}

#[test]
fn sigterm_during_install_rolls_the_step_back_and_exits_4() {
    let s = Scratch::new();
    let before = snapshot(&s.root());
    let args = strings(&[
        "install",
        &s.zip("Late.zip"),
        "--instance",
        &s.root_str(),
        "--json",
    ]);
    let out = interrupt(&args, "lists", "TERM", s.work.path());
    assert_eq!(out.status.code(), Some(4), "{out:?}");
    let record = last_json_line(&out);
    assert_eq!(record["event"], "finished");
    assert_eq!(record["outcome"], "rolled-back");
    assert_eq!(record["interrupted"], true);
    assert_eq!(record["exit_code"], 4);
    assert!(!s.root().join("mods/Late").exists());
    let journals = s.journals();
    assert_eq!(journals.len(), 1);
    assert_eq!(journals[0]["status"], "rolled-back");
    // Everything but the journal itself is as it was.
    let after = without_journal(snapshot(&s.root()));
    let before = without_journal(before);
    assert!(before == after, "the Instance is not as it was");
}

#[test]
fn sigint_is_handled_like_sigterm_and_text_output_names_the_outcome() {
    let s = Scratch::new();
    let args = strings(&["install", &s.zip("Late.zip"), "--instance", &s.root_str()]);
    let out = interrupt(&args, "stage", "INT", s.work.path());
    assert_eq!(out.status.code(), Some(4), "{out:?}");
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(
        err.contains("interrupted") && err.contains("rolled back"),
        "{err}"
    );
    assert!(!s.root().join("mods/Late").exists());
    assert_eq!(s.journals()[0]["status"], "rolled-back");
}

#[test]
fn sigterm_during_mods_and_sort_apply_restores_the_profile_files() {
    let s = Scratch::new();
    let before = snapshot(&s.root());
    let args = strings(&[
        "mods",
        "disable",
        "Patch",
        "--instance",
        &s.root_str(),
        "--json",
    ]);
    let out = interrupt(&args, "stage", "TERM", s.work.path());
    assert_eq!(out.status.code(), Some(4), "{out:?}");
    assert_eq!(last_json_line(&out)["outcome"], "rolled-back");
    let args = strings(&[
        "sort",
        "--instance",
        &s.root_str(),
        "--masterlist",
        s.work.path().join("masterlist.yaml").to_str().unwrap(),
        "--apply",
        "--json",
    ]);
    let out = interrupt(&args, "sort-times", "TERM", s.work.path());
    assert_eq!(out.status.code(), Some(4), "{out:?}");
    assert_eq!(last_json_line(&out)["outcome"], "rolled-back");
    let after = without_journal(snapshot(&s.root()));
    let before = without_journal(before);
    assert_eq!(
        before.keys().collect::<Vec<_>>(),
        after.keys().collect::<Vec<_>>()
    );
    for file in ["modlist.txt", "plugins.txt", "loadorder.txt"] {
        let key = format!("profiles/Default/{file}");
        assert_eq!(before[&key], after[&key], "{file}");
    }
    assert!(s.journals().iter().all(|j| j["status"] == "rolled-back"));
}

#[test]
fn sigterm_during_import_mo2_removes_the_new_instance() {
    let base = base_copy();
    let mo2 = TempDir::new("sigterm-mo2");
    Mo2Builder::new(base.path())
        .mod_dir(ModSpec::new("Existing").file("Existing.esp", &PluginBuilder::new().build()))
        .profile(
            "Default",
            &["+Existing"],
            &["FalloutNV.esm", "Existing.esp"],
        )
        .write(mo2.path());
    let out_dir = TempDir::new("sigterm-import");
    let instance = out_dir.path().join("fnv");
    let args = strings(&[
        "import-mo2",
        "--mo2",
        mo2.path().to_str().unwrap(),
        "--instance",
        instance.to_str().unwrap(),
        "--base",
        base.path().to_str().unwrap(),
        "--json",
    ]);
    let out = interrupt(&args, "import-mod", "TERM", out_dir.path());
    assert_eq!(out.status.code(), Some(4), "{out:?}");
    assert_eq!(last_json_line(&out)["outcome"], "rolled-back");
    assert!(!instance.exists(), "the half-made Instance is removed");
}
