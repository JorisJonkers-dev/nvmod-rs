#[test]
fn a_detached_run_keeps_the_instance_locked_until_the_program_ends() {
    let s = Scratch::new();
    let tool = s.tool("t.exe");
    s.exec_add("T", &tool, &[]);
    let (code, out, err) = s.run(&["T"], &[("FAKE_SLEEP", "2")]);
    assert_eq!(code, 0, "{err}");
    assert!(out.contains("stays locked"), "{out}");
    let r = s.r();
    let (code, _, err) = nvmod(&["stage", "--instance", &r]);
    assert_eq!(code, 2, "{err}");
    assert!(err.contains("run T (program)"), "{err}");
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(20);
    loop {
        let (code, _, _) = nvmod(&["stage", "--instance", &r]);
        if code == 0 {
            break;
        }
        assert!(
            std::time::Instant::now() < deadline,
            "the lock never went stale"
        );
        std::thread::sleep(std::time::Duration::from_millis(200));
    }
}

