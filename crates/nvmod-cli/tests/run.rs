#[test]
fn import_lists_mapped_paths_and_refuses_other_drives_with_a_finding() {
    let s = Scratch::new();
    let mo2 = TempDir::new("run-mo2");
    mo2_fixture(mo2.path(), s.base.path());
    let ini_before = std::fs::read(mo2.path().join("ModOrganizer.ini")).unwrap();
    let r = s.r();
    let (code, out, err) = nvmod(&[
        "exec",
        "import",
        "--mo2",
        mo2.path().to_str().unwrap(),
        "--instance",
        &r,
        "--json",
    ]);
    assert_eq!(code, 0, "{err}");
    let doc: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(doc["findings"][0]["code"], "exec.unmapped-path");
    assert_eq!(doc["findings"][0]["subject"], "Fallout Launcher");
    assert_eq!(
        std::fs::read(mo2.path().join("ModOrganizer.ini")).unwrap(),
        ini_before,
        "the MO2 ini is only read"
    );
    let (code, out, _) = nvmod(&["exec", "list", "--instance", &r, "--json"]);
    assert_eq!(code, 0);
    let doc: Value = serde_json::from_str(&out).unwrap();
    let list = doc["executables"].as_array().unwrap();
    assert_eq!(list.len(), 2);
    assert_eq!(list[0]["title"], "FNVEdit");
    assert_eq!(
        list[0]["binary"],
        s.base.path().join("tools/FNVEdit.exe").to_str().unwrap()
    );
    assert_eq!(list[0]["steam_app_id"], 22380);
    assert_eq!(list[0]["hidden"], true);
    assert_eq!(
        list[0]["working_directory"],
        s.base.path().join("tools").to_str().unwrap()
    );
    // A second import adds nothing.
    let (code, out, _) = nvmod(&[
        "exec",
        "import",
        "--mo2",
        mo2.path().to_str().unwrap(),
        "--instance",
        &r,
        "--json",
    ]);
    assert_eq!(code, 0);
    let doc: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(doc["executables"].as_array().unwrap().len(), 2);
}

#[test]
fn exec_add_edit_and_remove_round_trip() {
    let s = Scratch::new();
    s.exec_add("Tool", &s.tool("t.exe"), &["--arguments", "-a \"b c\""]);
    let r = s.r();
    let (code, _, err) = nvmod(&[
        "exec",
        "add",
        "--instance",
        &r,
        "--title",
        "tool",
        "--binary",
        "/x",
    ]);
    assert_eq!((code, err.contains("exists already")), (2, true));
    let (code, _, _) = nvmod(&[
        "exec",
        "add",
        "--instance",
        &r,
        "--title",
        "game",
        "--binary",
        "/x",
    ]);
    assert_eq!(code, 2);
    let (code, _, err) = nvmod(&[
        "exec",
        "edit",
        "TOOL",
        "--instance",
        &r,
        "--new-title",
        "Renamed",
        "--steam-app-id",
        "5",
        "--hidden",
    ]);
    assert_eq!(code, 0, "{err}");
    let (_, out, _) = nvmod(&["exec", "list", "--instance", &r, "--json"]);
    let doc: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(doc["executables"][0]["title"], "Renamed");
    assert_eq!(doc["executables"][0]["steam_app_id"], 5);
    let (code, _, _) = nvmod(&["exec", "remove", "renamed", "--instance", &r]);
    assert_eq!(code, 0);
    let (code, _, _) = nvmod(&["exec", "remove", "renamed", "--instance", &r]);
    assert_eq!(code, 2);
}

