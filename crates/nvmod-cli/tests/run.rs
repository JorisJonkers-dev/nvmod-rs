//! `nvmod exec` and `nvmod run` as a program against a scratch Instance made by `nvmod init` from a synthetic base
//! copy. The "Proton" is a shell script that records what it was given; the real game is never started.
#![cfg(unix)]

use nvmod_testkit::{BaseBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

const SENTINEL: &[u8] = b"SENTINEL FalloutNV.exe";

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

fn nvmod(args: &[&str]) -> (i32, String, String) {
    nvmod_env(args, &[])
}

fn script(path: &Path, body: &str) {
    use std::os::unix::fs::PermissionsExt;
    std::fs::write(path, format!("#!/bin/sh\n{body}\n")).unwrap();
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).unwrap();
}

struct Scratch {
    base: TempDir,
    inst: TempDir,
    /// The fake Proton, and the file it records into.
    proton: PathBuf,
    record: PathBuf,
}

impl Scratch {
    fn new() -> Scratch {
        let base = TempDir::new("run-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "nvse_1_4.dll",
            &nvmod_testkit::PeBuilder::dll().build(),
        );
        write_file(base.path(), "FalloutNV.exe", SENTINEL);
        write_file(base.path(), "Data/Meshes/Rock.nif", b"base rock");
        let inst = TempDir::new("run-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let (code, _, err) = nvmod(&[
            "profile",
            "create",
            "--instance",
            root.to_str().unwrap(),
            "--name",
            "Default",
        ]);
        assert_eq!(code, 0, "{err}");
        write_file(&root, "mods/Tex/textures/a.dds", b"tex");
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            b"# This file was automatically generated by Mod Organizer.\r\n+Tex\r\n",
        );
        let proton = inst.path().join("fake-proton.sh");
        let record = inst.path().join("record.txt");
        // Records its arguments, folder, the variables of interest and what the staged Data folder holds; sleeps
        // when FAKE_SLEEP is set; exits with FAKE_EXIT.
        script(
            &proton,
            r#"{
printf 'args=%s\n' "$*"
printf 'pwd=%s\n' "$(pwd)"
printf 'prefix=%s\n' "$STEAM_COMPAT_DATA_PATH"
printf 'appid=%s\n' "$SteamAppId"
printf 'data=%s\n' "$NVMOD_DATA_DIR"
printf 'profile=%s\n' "$NVMOD_PROFILE"
printf 'sees_tex=%s\n' "$(test -f "$NVMOD_DATA_DIR/textures/a.dds" && echo yes || echo no)"
printf 'sees_base=%s\n' "$(test -f "$NVMOD_DATA_DIR/meshes/rock.nif" && echo yes || echo no)"
} > "$FAKE_RECORD"
[ -n "$FAKE_SLEEP" ] && sleep "$FAKE_SLEEP"
exit "${FAKE_EXIT:-0}""#,
        );
        Scratch {
            base,
            inst,
            proton,
            record,
        }
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn r(&self) -> String {
        self.root().to_str().unwrap().to_owned()
    }

    fn tool(&self, name: &str) -> PathBuf {
        let path = self.inst.path().join("tools").join(name);
        write_file(self.inst.path(), &format!("tools/{name}"), b"MZ tool");
        path
    }

    fn exec_add(&self, title: &str, binary: &Path, extra: &[&str]) {
        let mut args = vec![
            "exec",
            "add",
            "--instance",
            "",
            "--title",
            title,
            "--binary",
            binary.to_str().unwrap(),
        ];
        let r = self.r();
        args[3] = &r;
        args.extend_from_slice(extra);
        let (code, _, err) = nvmod(&args);
        assert_eq!(code, 0, "{err}");
    }

    fn run(&self, args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
        let r = self.r();
        let mut all = vec!["run"];
        all.extend_from_slice(&args[..1]);
        all.extend_from_slice(&["--instance", &r, "--proton", self.proton.to_str().unwrap()]);
        all.extend_from_slice(&args[1..]);
        let mut e = vec![("FAKE_RECORD", self.record.to_str().unwrap())];
        e.extend_from_slice(env);
        nvmod_env(&all, &e)
    }

    fn recorded(&self) -> std::collections::BTreeMap<String, String> {
        std::fs::read_to_string(&self.record)
            .unwrap()
            .lines()
            .filter_map(|l| l.split_once('='))
            .map(|(k, v)| (k.to_owned(), v.to_owned()))
            .collect()
    }
}

