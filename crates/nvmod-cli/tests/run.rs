#[test]
fn run_goes_through_proton_with_the_prefix_app_id_folder_and_staged_data() {
    let s = Scratch::new();
    let tool = s.tool("FNVEdit.exe");
    let wd = s.inst.path().join("tools");
    s.exec_add(
        "FNVEdit",
        &tool,
        &[
            "--arguments",
            "-D:\"%DATA%\" -x",
            "--steam-app-id",
            "42",
            "--working-dir",
            wd.to_str().unwrap(),
        ],
    );
    let (code, out, err) = s.run(
        &["FNVEdit", "--wait", "--", "--extra", "two words"],
        &[("FAKE_EXIT", "7")],
    );
    assert_eq!(
        code, 7,
        "the program's exit code passes through with --wait: {out}{err}"
    );
    let rec = s.recorded();
    let data = s.root().join("staging/Default/data");
    let wine_data = format!("Z:{}", data.display()).replace('/', "\\");
    assert_eq!(
        rec["args"],
        format!("run {} -D:{wine_data} -x --extra two words", tool.display())
    );
    // The shell's `pwd` gives the folder with its links resolved (`/private/var/...` on macOS).
    assert_eq!(Path::new(&rec["pwd"]), std::fs::canonicalize(&wd).unwrap());
    assert_eq!(rec["prefix"], s.root().join("compatdata").to_str().unwrap());
    assert_eq!(rec["appid"], "42");
    assert_eq!(rec["data"], data.to_str().unwrap());
    assert_eq!(rec["profile"], "Default");
    assert_eq!(
        (rec["sees_tex"].as_str(), rec["sees_base"].as_str()),
        ("yes", "yes"),
        "the staged Data folder is the one seen"
    );
    assert!(
        !s.root().join(".nvmod").exists(),
        "the lock is released after --wait"
    );
}

#[test]
fn the_game_entry_agrees_with_verify() {
    let s = Scratch::new();
    let r = s.r();
    let proton = s.proton.to_str().unwrap();
    let (_, out, _) = nvmod(&["verify", "--instance", &r, "--proton", proton, "--json"]);
    let verify: Value = serde_json::from_str(&out).unwrap();
    let linux = verify["launch_plan"]["entries"]
        .as_array()
        .unwrap()
        .iter()
        .find(|e| e["platform"] == "linux")
        .unwrap()
        .clone();
    let (code, out, err) = s.run(&["game", "--dry-run", "--json"], &[]);
    assert_eq!(code, 0, "{err}");
    let run: Value = serde_json::from_str(&out).unwrap();
    let cmd = &run["command"];
    assert_eq!(cmd["program"], linux["program"]);
    assert_eq!(cmd["args"], linux["args"]);
    assert_eq!(cmd["working_dir"], linux["working_dir"]);
    for (k, v) in linux["env"].as_object().unwrap() {
        assert_eq!(&cmd["env"][k], v, "{k}");
    }
}

/// Regular files (not links) under `root` whose bytes are the sentinel.
fn real_copies_of_the_exe(root: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).unwrap().flatten() {
            let kind = entry.file_type().unwrap();
            if kind.is_dir() {
                stack.push(entry.path());
            } else if kind.is_file() && std::fs::read(entry.path()).unwrap() == SENTINEL {
                found.push(entry.path());
            }
        }
    }
    found
}

/// A fake nv-viewer that records its arguments, folder, variables and what its run folder shows.
fn fake_viewer(path: &Path) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    script(
        path,
        r#"{
printf 'args=%s\n' "$*"
printf 'pwd=%s\n' "$(pwd)"
printf 'd3d9=%s\n' "$NV_D3D9"
printf 'profile_file=%s\n' "$NV_LINUX_PROFILE"
printf 'userdata_line=%s\n' "$(cat "$NV_LINUX_PROFILE")"
printf 'sees_tex=%s\n' "$(test -f "$1/Data/textures/a.dds" && echo yes || echo no)"
printf 'sees_base=%s\n' "$(test -f "$1/Data/meshes/rock.nif" && echo yes || echo no)"
printf 'exe_bytes=%s\n' "$(cat "$1/FalloutNV.exe")"
} > "$FAKE_RECORD"
echo viewer says hello
exit "${FAKE_EXIT:-0}""#,
    );
}

#[test]
fn nv_rs_runs_natively_from_a_run_folder_and_nothing_is_copied() {
    let s = Scratch::new();
    let viewer = s.root().join("nv-rs/bin/nv-viewer");
    fake_viewer(&viewer);
    let state = s.inst.path().join("state");
    let state_s = state.to_str().unwrap();
    let (code, out, err) = s.run(&["nv-rs", "--wait"], &[("XDG_STATE_HOME", state_s)]);
    assert_eq!(code, 0, "{err}");
    // nvmod works in the Instance and base copy it resolved through links, as the program's folder shows; on
    // macOS the temporary folder `/var/...` is `/private/var/...`.
    let root = std::fs::canonicalize(s.root()).unwrap();
    let base = std::fs::canonicalize(s.base.path()).unwrap();
    let run = root.join("run/Default");
    let rec = s.recorded();
    // Compared with links resolved on both sides: which spelling of the folder a value has is not the point.
    let real = |p: &str| std::fs::canonicalize(p).unwrap_or_else(|e| panic!("{p}: {e}"));
    assert_eq!(real(&rec["args"]), run);
    assert_eq!(real(&rec["pwd"]), run);
    assert_eq!(real(&rec["profile_file"]), run.join("linux_profile.txt"));
    let userdata = rec["userdata_line"]
        .strip_prefix("userdata = ")
        .expect("a userdata line");
    assert_eq!(real(userdata), run.join("userdata"));
    assert_eq!(rec["d3d9"], "wgpu");
    assert_eq!(
        (rec["sees_tex"].as_str(), rec["sees_base"].as_str()),
        ("yes", "yes")
    );
    // The executable is a link to the base copy's, never a copy.
    assert_eq!(rec["exe_bytes"], String::from_utf8_lossy(SENTINEL));
    assert_eq!(
        std::fs::canonicalize(std::fs::read_link(run.join("FalloutNV.exe")).unwrap()).unwrap(),
        base.join("FalloutNV.exe")
    );
    assert_eq!(
        std::fs::canonicalize(std::fs::read_link(run.join("Data")).unwrap()).unwrap(),
        root.join("staging/Default/data")
    );
    assert_eq!(real_copies_of_the_exe(s.inst.path()), Vec::<PathBuf>::new());
    assert_eq!(real_copies_of_the_exe(s.base.path()).len(), 1);
    // The profile's lists are placed in the run folder's user data, and the output is logged.
    assert!(
        run.join("userdata/AppData/Local/FalloutNV/plugins.txt")
            .is_file()
    );
    let log = std::fs::read_dir(state.join("nv-rs/logs"))
        .unwrap()
        .flatten()
        .next()
        .unwrap()
        .path();
    let text = std::fs::read_to_string(&log).unwrap();
    assert!(text.starts_with("# nvmod run "), "{text}");
    assert!(text.contains("viewer says hello"), "{text}");
    assert!(out.contains(log.to_str().unwrap()), "{out}");
    // Not installed: refused with the way forward.
    std::fs::remove_file(&viewer).unwrap();
    let (code, _, err) = s.run(
        &["nv-rs", "--wait"],
        &[("NVMOD_NV_RS_ROOT", "/nonexistent")],
    );
    assert_eq!((code, err.contains("install-nv-rs")), (2, true));
}

