#[test]
fn locks_are_written_kept_for_absent_plugins_and_rolled_back() {
    let s = Scratch::new();
    let profile = s.root().join("profiles/Default");
    let before = snapshot(&profile);
    let (code, out, err) = s.run(&["lock", "D.esp", "2", "--json"]);
    assert_eq!(code, 0, "{err}");
    let r: Value = serde_json::from_str(&out).unwrap();
    assert!(r["journal"].is_string());
    assert_eq!(s.text("lockedorder.txt"), format!("{HEADER}D.esp|1\r\n"));
    assert_eq!(s.text("loadorder.txt").lines().nth(2), Some("D.esp"));
    assert_eq!(s.list()["plugins"][1]["locked"], 2);
    // A locked plugin is not moved by hand.
    assert_eq!(s.run(&["move", "D.esp", "--bottom"]).0, 2);
    // A lock of an absent plugin survives later edits.
    let mut text = s.text("lockedorder.txt");
    text.push_str("Gone.esp|7\r\n");
    write_file(
        &s.root(),
        "profiles/Default/lockedorder.txt",
        text.as_bytes(),
    );
    assert_eq!(s.run(&["enable", "A.esm"]).0, 0);
    assert!(s.text("lockedorder.txt").contains("Gone.esp|7"));
    assert_eq!(s.list()["locks"][1]["listed"], false);
    // Unlock removes only that entry; rollback restores every file byte for byte.
    assert_eq!(s.run(&["unlock", "D.esp"]).0, 0);
    assert_eq!(s.text("lockedorder.txt"), format!("{HEADER}Gone.esp|7\r\n"));
    let root = s.root();
    for _ in 0..3 {
        let (code, _, err) = nvmod(&["rollback", "--instance", root.to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
    }
    assert_eq!(snapshot(&profile), before);
}

