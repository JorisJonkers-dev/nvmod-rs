#[test]
fn crlf_and_the_header_round_trip() {
    let s = Scratch::new();
    let (plugins, order) = (s.file("plugins.txt"), s.file("loadorder.txt"));
    assert!(plugins.starts_with(HEADER.as_bytes()) && plugins.windows(2).any(|w| w == b"\r\n"));
    // Enabling and disabling again writes the very same bytes (header, CRLF, order).
    assert_eq!(s.run(&["enable", "A.esm"]).0, 0);
    assert_eq!(s.run(&["disable", "A.esm"]).0, 0);
    assert_eq!(
        (s.file("plugins.txt"), s.file("loadorder.txt")),
        (plugins, order)
    );
    // Nothing to change writes nothing and makes no journal.
    let (code, out, _) = s.run(&["enable", "D.esp", "--json"]);
    assert_eq!(code, 0);
    let r: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(r["status"], "unchanged");
    assert!(r["journal"].is_null());
}

