#[test]
fn dry_run_writes_nothing_and_a_failed_step_is_rolled_back() {
    let s = Scratch::new();
    let before = snapshot(&s.root());
    let (code, out, _) = s.run(&["enable", "C.esp", "--with-masters", "--dry-run", "--json"]);
    assert_eq!(code, 0);
    let r: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(
        (r["status"].as_str(), r["dry_run"].as_bool()),
        (Some("dry-run"), Some(true))
    );
    assert_eq!(snapshot(&s.root()), before);
    for step in ["sort-lists", "sort-times"] {
        let root = s.root();
        let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
            .args([
                "plugins",
                "enable",
                "A.esm",
                "--instance",
                root.to_str().unwrap(),
            ])
            .env("NVMOD_FAIL_AT", step)
            .output()
            .unwrap();
        assert_eq!(out.status.code(), Some(4), "{step}");
        let after = snapshot(&s.root());
        let journals = |m: &std::collections::BTreeMap<String, Vec<u8>>| {
            m.keys()
                .filter(|k| !k.starts_with(".nvmod/"))
                .cloned()
                .collect::<Vec<_>>()
        };
        assert_eq!(journals(&after), journals(&before), "{step}");
        assert_eq!(
            s.file("plugins.txt"),
            before["profiles/Default/plugins.txt"],
            "{step}"
        );
    }
}

