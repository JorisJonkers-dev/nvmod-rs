//! `nvmod sort` and a requirement the masterlist names on a script extender plugin: one line per requirement, and
//! on nv-rs a built-in extender (per the installed nv-rs's `capabilities.json`) is a note, not an error. The
//! masterlist, the plugins and the capabilities file are synthetic and written here.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, capabilities_json, write_file};
use serde_json::Value;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

const MASTERLIST: &str = r"
plugins:
  - name: 'Needs\.esp'
    req:
      - name: 'NVSE/Plugins/jip_nvse.dll'
        display: '[JIP LN NVSE Plugin](https://www.nexusmods.com/newvegas/mods/58277/)'
      - name: 'NVSE/Plugins/johnnyguitar.dll'
        display: '[JohnnyGuitar NVSE](https://www.nexusmods.com/newvegas/mods/66927/)'
      - name: 'NVSE/Plugins/nobody.dll'
        display: 'Nobody Knows This'
      - name: 'Plain.esp'
";

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    inst: TempDir,
}

impl Scratch {
    fn new(target: &str, caps: Option<&str>) -> Scratch {
        let base = TempDir::new("sortreq-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "nvse_1_4.dll",
            &nvmod_testkit::PeBuilder::dll().build(),
        );
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("sortreq-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let file = root.join("nvmod-instance.json");
        let mut json: Value = serde_json::from_str(&fs::read_to_string(&file).unwrap()).unwrap();
        json["target"] = target.into();
        fs::write(&file, serde_json::to_string_pretty(&json).unwrap()).unwrap();
        write_file(&root, "mods/Needs/Needs.esp", &PluginBuilder::new().build());
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            format!("{header}+Needs\r\n").as_bytes(),
        );
        for list in ["plugins.txt", "loadorder.txt"] {
            write_file(
                &root,
                &format!("profiles/Default/{list}"),
                format!("{header}FalloutNV.esm\r\nNeeds.esp\r\n").as_bytes(),
            );
        }
        if let Some(caps) = caps {
            write_file(&root, "nv-rs/capabilities.json", caps.as_bytes());
        }
        write_file(inst.path(), "masterlist.yaml", MASTERLIST.as_bytes());
        let (code, _, err) = nvmod(&["stage", "--instance", root.to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
        drop(base);
        Scratch { inst }
    }

    fn preview(&self) -> (String, Value) {
        let root: PathBuf = self.inst.path().join("fnv");
        let masterlist = self.inst.path().join("masterlist.yaml");
        let base = [
            "sort",
            "--instance",
            root.to_str().unwrap(),
            "--masterlist",
            masterlist.to_str().unwrap(),
        ];
        let (code, text, err) = nvmod(&base);
        assert_eq!(code, 0, "{err}");
        let mut json_args = base.to_vec();
        json_args.push("--json");
        let (code, json, err) = nvmod(&json_args);
        assert_eq!(code, 0, "{err}");
        (text, serde_json::from_str(&json).unwrap())
    }
}

/// Every line the preview shows for `Needs.esp`: messages (`kind`, text) and findings (`kind`, text).
fn lines(report: &Value) -> Vec<(String, String)> {
    let entry = report["order"]
        .as_array()
        .unwrap()
        .iter()
        .find(|p| p["name"] == "Needs.esp")
        .expect("Needs.esp is in the order");
    let mut all = Vec::new();
    for key in ["messages", "generated_messages", "findings"] {
        for m in entry[key].as_array().unwrap() {
            all.push((
                m["kind"].as_str().unwrap().to_owned(),
                m["text"].as_str().unwrap().to_owned(),
            ));
        }
    }
    all
}

fn about<'a>(all: &'a [(String, String)], needle: &str) -> Vec<&'a (String, String)> {
    all.iter().filter(|(_, t)| t.contains(needle)).collect()
}

#[test]
fn on_vanilla_each_requirement_is_one_error_line_and_nothing_is_built_in() {
    let s = Scratch::new(
        "vanilla",
        Some(&capabilities_json(&[("jip-ln", "JIP LN", 10, 12)])),
    );
    let (text, report) = s.preview();
    let all = lines(&report);
    for needle in [
        "JIP LN NVSE Plugin",
        "JohnnyGuitar NVSE",
        "Nobody Knows This",
        "Plain",
    ] {
        let hits = about(&all, needle);
        assert_eq!(hits.len(), 1, "{needle}: {all:?}");
        assert_eq!(hits[0].0, "error", "{needle}");
        assert!(hits[0].1.contains("is missing"), "{}", hits[0].1);
        assert_eq!(
            text.matches(needle).count(),
            1,
            "{needle} once in the text:\n{text}"
        );
    }
    assert!(!text.contains("built in on nv-rs"), "{text}");
    assert!(!text.contains("[problem]"), "{text}");
}

#[test]
fn on_nv_rs_a_built_in_extender_is_a_note_with_its_coverage_and_the_rest_keeps_its_message() {
    let s = Scratch::new(
        "nv-rs",
        Some(&capabilities_json(&[("jip-ln", "JIP LN", 10, 12)])),
    );
    let (text, report) = s.preview();
    let all = lines(&report);
    let jip = about(&all, "JIP LN NVSE Plugin");
    assert_eq!(jip.len(), 1, "{all:?}");
    assert_eq!(jip[0].0, "say");
    assert!(
        jip[0]
            .1
            .contains("built in on nv-rs, 10 of 12 commands implemented, 2 missing"),
        "{}",
        jip[0].1
    );
    assert!(!jip[0].1.contains("is missing"), "{}", jip[0].1);
    // The catalogue maps JohnnyGuitar to nothing built in, and the last two are not in it: loot-rs's message stays.
    for needle in ["JohnnyGuitar NVSE", "Nobody Knows This", "Plain"] {
        let hits = about(&all, needle);
        assert_eq!(hits.len(), 1, "{needle}: {all:?}");
        assert_eq!(hits[0].0, "error", "{needle}");
        assert!(hits[0].1.contains("is missing"), "{}", hits[0].1);
    }
    assert!(!text.contains("[problem]"), "{text}");
    assert_eq!(text.matches("JIP LN NVSE Plugin").count(), 1, "{text}");
}

#[test]
fn on_nv_rs_without_a_capabilities_file_it_is_still_built_in_per_the_catalogue_without_numbers() {
    let s = Scratch::new("nv-rs", None);
    let (_, report) = s.preview();
    let all = lines(&report);
    let jip = about(&all, "JIP LN NVSE Plugin");
    assert_eq!(jip.len(), 1, "{all:?}");
    assert_eq!(jip[0].0, "say");
    assert!(jip[0].1.contains("built in on nv-rs"), "{}", jip[0].1);
    assert!(jip[0].1.contains("no coverage"), "{}", jip[0].1);
}
