//! `nvmod import-mo2`, run as a program against a scratch MO2 instance written in code. The example instance
//! mirrors `docs/research/fixtures/mo2-instance/` of NV-Linux-Modding (a separator, a disabled mod, a mod without a
//! folder, a foreign DLC entry, an inactive plugin). Nothing here depends on the machine or on any game file.

use nvmod_testkit::{BaseBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

const MODLIST: &str = "# This file was automatically generated by Mod Organizer.\r\n+Example Patch\r\n-Disabled Example\r\n+Example Mod\r\n-Example Group_separator\r\n+Another Example Mod\r\n*DLC: ExamplePack\r\n";
const PLUGINS: &[u8] = b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nExamplePack.esm\r\nExample Mod.esp\r\nExample Patch.esp\r\n";
const LOADORDER: &[u8] = b"# This file was automatically generated by Mod Organizer.\r\nFalloutNV.esm\r\nExamplePack.esm\r\nExample Mod.esp\r\nInactive Example.esp\r\nExample Patch.esp\r\n";

struct World {
    mo2: TempDir,
    out: TempDir,
    base: TempDir,
}

impl World {
    fn new() -> World {
        let mo2 = TempDir::new("imp-mo2");
        let r = mo2.path();
        write_file(
            r,
            "ModOrganizer.ini",
            b"[General]\r\ngameName=TTW\r\nselected_profile=@ByteArray(Example Profile)\r\ngamePath=@ByteArray(D:\\\\Games\\\\Fallout New Vegas)\r\nversion=2.5.2\r\n",
        );
        write_file(r, "mods/Example Mod/meshes/rock.nif", b"rock");
        write_file(
            r,
            "mods/Example Mod/meta.ini",
            b"[General]\r\nmodid=12345\r\n",
        );
        write_file(r, "mods/Example Patch/NVSE/Plugins/patch.dll", b"patch");
        write_file(r, "mods/Example Patch/Example Patch.esp", b"esp");
        write_file(r, "mods/Example Mod/Example Mod.esp", b"esp");
        write_file(r, "mods/Disabled Example/Disabled Example.esp", b"esp");
        write_file(r, "mods/Example Group_separator/meta.ini", b"[General]\r\n");
        write_file(r, "overwrite/NVSE/.keep", b"");
        let p = "profiles/Example Profile";
        write_file(r, &format!("{p}/modlist.txt"), MODLIST.as_bytes());
        write_file(r, &format!("{p}/plugins.txt"), PLUGINS);
        write_file(r, &format!("{p}/loadorder.txt"), LOADORDER);
        write_file(
            r,
            &format!("{p}/lockedorder.txt"),
            b"Example Patch.esp|4\r\n",
        );
        write_file(r, &format!("{p}/fallout.ini"), b"[General]\r\n");
        let base = TempDir::new("imp-base");
        BaseBuilder::steam().write(base.path());
        World {
            mo2,
            out: TempDir::new("imp-out"),
            base,
        }
    }

    fn profile_file(&self, name: &str, bytes: &[u8]) {
        write_file(
            self.mo2.path(),
            &format!("profiles/Example Profile/{name}"),
            bytes,
        );
    }

    fn instance(&self) -> PathBuf {
        self.out.path().join("fnv")
    }

    fn import(&self, extra: &[&str]) -> (i32, String, String) {
        let (mo2, inst, base) = (
            self.mo2.path().to_str().unwrap().to_owned(),
            self.instance().to_str().unwrap().to_owned(),
            self.base.path().to_str().unwrap().to_owned(),
        );
        let mut args = vec![
            "import-mo2",
            "--mo2",
            &mo2,
            "--instance",
            &inst,
            "--base",
            &base,
            "--json",
        ];
        args.extend_from_slice(extra);
        nvmod(&args)
    }
}

fn json(out: &str) -> Value {
    serde_json::from_str(out).unwrap_or_else(|e| panic!("{e}: {out}"))
}

fn entries(report: &Value, key: &str) -> Vec<(String, String)> {
    report[key]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| {
            (
                f["code"].as_str().unwrap().to_owned(),
                f["subject"].as_str().unwrap().to_owned(),
            )
        })
        .collect()
}

fn lines(path: &Path) -> Vec<String> {
    nvmod_formats::plugins::parse_plugin_list(&std::fs::read(path).unwrap())
}

#[test]
fn the_example_instance_imports_with_the_same_mods_and_load_order() {
    let w = World::new();
    let before = snapshot(w.mo2.path());
    let (code, out, err) = w.import(&[]);
    assert_eq!(code, 0, "{out} {err}");
    assert_eq!(
        snapshot(w.mo2.path()),
        before,
        "the MO2 instance is not written to"
    );

    let report = json(&out);
    assert_eq!(report["profile"], "Example Profile");
    assert_eq!(
        report["enabled_mods"],
        serde_json::json!(["Example Patch", "Example Mod", "Another Example Mod"])
    );
    let profile = w.instance().join("profiles/Example Profile");
    let modlist = nvmod_formats::Modlist::parse(
        &std::fs::read_to_string(profile.join("modlist.txt")).unwrap(),
    );
    let mo2_modlist = nvmod_formats::Modlist::parse(MODLIST);
    assert_eq!(modlist, mo2_modlist, "same Mod list and priorities");
    assert_eq!(
        lines(&profile.join("loadorder.txt")),
        nvmod_formats::plugins::parse_plugin_list(LOADORDER)
    );
    assert_eq!(
        lines(&profile.join("plugins.txt")),
        nvmod_formats::plugins::parse_plugin_list(PLUGINS)
    );
    assert_eq!(report["load_order"].as_array().unwrap().len(), 5);
    assert_eq!(
        std::fs::read(w.instance().join("mods/Example Mod/meshes/rock.nif")).unwrap(),
        b"rock"
    );
    assert!(w.instance().join("mods/Example Group_separator").is_dir());
}

#[test]
fn what_cannot_be_mapped_is_listed() {
    let w = World::new();
    let (code, out, _) = w.import(&[]);
    assert_eq!(code, 0);
    let unmapped = entries(&json(&out), "unmapped");
    for want in [
        ("import.mod-folder-missing", "Another Example Mod"),
        ("import.foreign-entry", "DLC: ExamplePack"),
        ("import.overwrite-not-imported", "overwrite"),
        ("import.profile-file-not-imported", "lockedorder.txt"),
        ("import.profile-file-not-imported", "fallout.ini"),
    ] {
        assert!(
            unmapped.contains(&(want.0.to_owned(), want.1.to_owned())),
            "{want:?} missing from {unmapped:?}"
        );
    }
    let (code, text, _) = nvmod(&[
        "import-mo2",
        "--mo2",
        w.mo2.path().to_str().unwrap(),
        "--instance",
        w.out.path().join("second").to_str().unwrap(),
        "--base",
        w.base.path().to_str().unwrap(),
    ]);
    assert_eq!(code, 0);
    assert!(
        text.contains("Another Example Mod") && text.contains("not imported"),
        "{text}"
    );
}

#[test]
fn plugins_txt_is_decoded_in_the_windows_code_page() {
    let w = World::new();
    w.profile_file("plugins.txt", b"FalloutNV.esm\r\nCaf\xE9.esp\r\n");
    w.profile_file(
        "loadorder.txt",
        "FalloutNV.esm\r\nCaf\u{e9}.esp\r\n".as_bytes(),
    );
    let (code, out, err) = w.import(&[]);
    assert_eq!(code, 0, "{out} {err}");
    assert_eq!(
        json(&out)["load_order"],
        serde_json::json!(["FalloutNV.esm", "Caf\u{e9}.esp"])
    );
    let kept = std::fs::read(w.instance().join("profiles/Example Profile/plugins.txt")).unwrap();
    assert_eq!(
        kept, b"FalloutNV.esm\r\nCaf\xE9.esp\r\n",
        "the file keeps its code page"
    );
}

#[test]
fn a_plugin_missing_from_loadorder_is_one_disagreement_and_nothing_is_written() {
    let w = World::new();
    w.profile_file(
        "loadorder.txt",
        b"FalloutNV.esm\r\nExamplePack.esm\r\nExample Patch.esp\r\n",
    );
    let before = snapshot(w.mo2.path());
    let (code, out, _) = w.import(&[]);
    assert_eq!(code, 1);
    let report = json(&out);
    assert_eq!(
        entries(&report, "disagreements"),
        [(
            "import.plugin-not-in-loadorder".to_owned(),
            "Example Mod.esp".to_owned()
        )]
    );
    assert!(!w.instance().exists(), "nothing is written");
    assert_eq!(snapshot(w.mo2.path()), before);
}

#[test]
fn a_different_order_in_the_two_lists_is_reported_per_plugin() {
    let w = World::new();
    w.profile_file(
        "loadorder.txt",
        b"FalloutNV.esm\r\nExamplePack.esm\r\nExample Patch.esp\r\nExample Mod.esp\r\n",
    );
    let (code, out, _) = w.import(&[]);
    assert_eq!(code, 1);
    let got = entries(&json(&out), "disagreements");
    assert_eq!(got.len(), 2, "{got:?}");
    assert!(got.iter().all(|(c, _)| c == "import.order-differs"));
    let subjects: Vec<&str> = got.iter().map(|(_, s)| s.as_str()).collect();
    assert!(subjects.contains(&"Example Mod.esp") && subjects.contains(&"Example Patch.esp"));
    assert!(!w.instance().exists());
}

#[test]
fn a_missing_list_or_a_plugin_of_a_disabled_mod_is_a_disagreement() {
    let w = World::new();
    std::fs::remove_file(w.mo2.path().join("profiles/Example Profile/plugins.txt")).unwrap();
    let (code, out, _) = w.import(&[]);
    assert_eq!(code, 1);
    assert_eq!(
        entries(&json(&out), "disagreements"),
        [("import.list-missing".to_owned(), "plugins.txt".to_owned())]
    );

    let w = World::new();
    w.profile_file(
        "plugins.txt",
        b"FalloutNV.esm\r\nExamplePack.esm\r\nExample Mod.esp\r\nDisabled Example.esp\r\nExample Patch.esp\r\n",
    );
    w.profile_file(
        "loadorder.txt",
        b"FalloutNV.esm\r\nExamplePack.esm\r\nExample Mod.esp\r\nDisabled Example.esp\r\nExample Patch.esp\r\n",
    );
    let (code, out, _) = w.import(&[]);
    assert_eq!(code, 1);
    assert_eq!(
        entries(&json(&out), "disagreements"),
        [(
            "import.plugin-in-disabled-mod".to_owned(),
            "Disabled Example.esp".to_owned()
        )]
    );
}

#[test]
fn an_unmapped_game_path_needs_a_base_and_other_refusals_exit_two() {
    let w = World::new();
    let (mo2, inst) = (w.mo2.path().to_str().unwrap(), w.instance());
    let inst = inst.to_str().unwrap();
    let (code, _, err) = nvmod(&["import-mo2", "--mo2", mo2, "--instance", inst]);
    assert_eq!(code, 5);
    assert!(err.contains("--base"), "{err}");
    assert!(!w.instance().exists());

    let epic = TempDir::new("imp-epic");
    BaseBuilder::epic().write(epic.path());
    let (code, _, err) = nvmod(&[
        "import-mo2",
        "--mo2",
        mo2,
        "--instance",
        inst,
        "--base",
        epic.path().to_str().unwrap(),
    ]);
    assert_eq!(code, 2);
    assert!(err.contains("Epic"), "{err}");

    let (code, _, err) = w.import(&["--profile", "Nope"]);
    assert_eq!(code, 2);
    assert!(err.contains("Nope"), "{err}");

    let inside = w.mo2.path().join("nvmod");
    let (code, _, err) = nvmod(&[
        "import-mo2",
        "--mo2",
        mo2,
        "--instance",
        inside.to_str().unwrap(),
        "--base",
        w.base.path().to_str().unwrap(),
    ]);
    assert_eq!(code, 2);
    assert!(err.contains("inside"), "{err}");
    assert!(!inside.exists());

    let none = TempDir::new("imp-none");
    let (code, _, err) = nvmod(&[
        "import-mo2",
        "--mo2",
        none.path().to_str().unwrap(),
        "--instance",
        inst,
        "--base",
        w.base.path().to_str().unwrap(),
    ]);
    assert_eq!(code, 2);
    assert!(err.contains("not a Mod Organizer"), "{err}");

    assert_eq!(w.import(&[]).0, 0);
    let (code, _, err) = w.import(&[]);
    assert_eq!(code, 2);
    assert!(err.contains("already"), "{err}");
}

