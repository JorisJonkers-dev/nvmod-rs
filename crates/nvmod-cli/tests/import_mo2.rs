#[test]
fn the_imported_instance_stages_and_passes_the_doctor() {
    let w = World::new();
    // The vanilla target needs xNVSE's DLL in the base copy (ticket 29).
    nvmod_testkit::write_file(
        w.base.path(),
        "nvse_1_4.dll",
        &nvmod_testkit::PeBuilder::dll().build(),
    );
    assert_eq!(w.import(&[]).0, 0);
    let inst = w.instance();
    let inst = inst.to_str().unwrap();
    let (code, out, err) = nvmod(&["stage", "--instance", inst]);
    assert_eq!(code, 0, "{out} {err}");
    let (code, out, _) = nvmod(&["doctor", "--instance", inst, "--json"]);
    assert_eq!(code, 0, "{out}");
}

#[cfg(unix)]
#[test]
fn mods_are_hard_linked_unless_copying_is_asked_for() {
    use std::os::unix::fs::MetadataExt;
    let w = World::new();
    assert_eq!(w.import(&[]).0, 0);
    let nlink = |inst: &Path| {
        std::fs::metadata(inst.join("mods/Example Mod/meshes/rock.nif"))
            .unwrap()
            .nlink()
    };
    assert!(nlink(&w.instance()) >= 2);
    std::fs::remove_dir_all(w.instance()).unwrap();
    assert_eq!(w.import(&["--copy"]).0, 0);
    assert_eq!(nlink(&w.instance()), 1);
}

#[test]
fn the_import_writes_a_profile_record_that_loads() {
    let w = World::new();
    assert_eq!(w.import(&[]).0, 0);
    let text = std::fs::read_to_string(w.instance().join("profiles/Example Profile/profile.json"))
        .unwrap();
    let record = nvmod_core::load_profile(&text).unwrap();
    assert_eq!(record.name, "Example Profile");
    assert_eq!(
        record.load_order,
        nvmod_formats::plugins::parse_plugin_list(LOADORDER)
    );
    assert_eq!(
        record.active_plugins,
        nvmod_formats::plugins::parse_plugin_list(PLUGINS)
    );
    assert!(
        record
            .mods
            .iter()
            .any(|m| m.name == "Example Mod" && m.enabled)
    );
    assert!(
        record
            .mods
            .iter()
            .any(|m| m.name == "Disabled Example" && !m.enabled)
    );
    assert!(record.mods.iter().all(|m| !m.name.ends_with("_separator")));
}

#[test]
fn an_imported_profile_keeps_its_lists_and_the_doctor_names_base_masters_they_lack() {
    let w = World::new();
    write_file(w.base.path(), "Data/DeadMoney.esm", b"synthetic master");
    let (code, out, err) = w.import(&[]);
    assert_eq!(code, 0, "{out} {err}");
    let profile = w.instance().join("profiles/Example Profile");
    // The import copies MO2's lists byte for byte; it does not add the base masters.
    assert_eq!(std::fs::read(profile.join("plugins.txt")).unwrap(), PLUGINS);
    let (_, out, err) = nvmod(&[
        "doctor",
        "--instance",
        w.instance().to_str().unwrap(),
        "--json",
    ]);
    let report = json(&out);
    let found: Vec<_> = report["findings"]
        .as_array()
        .unwrap_or_else(|| panic!("{out} {err}"))
        .iter()
        .filter(|f| f["code"] == "loadorder.base-master-unlisted")
        .collect();
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(
        found[0]["message"]
            .as_str()
            .unwrap()
            .contains("DeadMoney.esm")
    );
}
