//! Disabling and enabling a Mod that provides plugins (#261), run as a program against a scratch Instance.
//! The Mod has the shape of Tale of Two Wastelands: several plugins, among them masters that a later plugin needs.
//! No game data is used; every file is a few synthetic bytes.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn nvmod(args: &[&str]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

const BASE: [&str; 4] = [
    "FalloutNV.esm",
    "DeadMoney.esm",
    "HonestHearts.esm",
    "GunRunnersArsenal.esm",
];
/// Tale of Two Wastelands ships its own copies of the base masters next to its own plugins.
const TTW: [&str; 8] = [
    "FalloutNV.esm",
    "DeadMoney.esm",
    "Fallout3.esm",
    "Anchorage.esm",
    "TaleOfTwoWastelands.esm",
    "YUPTTW.esp",
    "HonestHearts.esm",
    "GunRunnersArsenal.esm",
];
const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Mods `Ttw` (TTW-shaped), `Twin` (also provides Anchorage.esm), `Late` (Late.esp, whose master is
    /// Fallout3.esm), `Empty` (no plugin), all enabled. The base copy has the four base masters. plugins.txt and
    /// loadorder.txt list the base masters, the TTW plugins and Late.esp, all active.
    fn new() -> Scratch {
        let base = TempDir::new("dp-base");
        BaseBuilder::steam().write(base.path());
        for m in BASE {
            write_file(
                base.path(),
                &format!("Data/{m}"),
                &PluginBuilder::master().build(),
            );
        }
        let inst = TempDir::new("dp-inst");
        let (code, _, err) = nvmod(&[
            "init",
            "--base",
            base.path().to_str().unwrap(),
            "--instance",
            inst.path().join("fnv").to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        let s = Scratch { _base: base, inst };
        let root = s.root();
        for p in TTW {
            write_file(
                &root,
                &format!("mods/Ttw/{p}"),
                &PluginBuilder::master().build(),
            );
        }
        write_file(&root, "mods/Ttw/Meshes/a.nif", b"a");
        write_file(
            &root,
            "mods/Twin/Anchorage.esm",
            &PluginBuilder::master().build(),
        );
        write_file(
            &root,
            "mods/Late/Late.esp",
            &PluginBuilder::new().requires("Fallout3.esm").build(),
        );
        write_file(&root, "mods/Empty/Textures/Dirt.dds", b"d");
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            format!("{HEADER}+Late\r\n+Empty\r\n+Twin\r\n+Ttw\r\n").as_bytes(),
        );
        let all = [
            "FalloutNV.esm",
            "DeadMoney.esm",
            "HonestHearts.esm",
            "GunRunnersArsenal.esm",
            "Fallout3.esm",
            "Anchorage.esm",
            "TaleOfTwoWastelands.esm",
            "YUPTTW.esp",
            "Late.esp",
        ];
        let active = all.map(|p| format!("*{p}\r\n")).concat();
        let order = all.map(|p| format!("{p}\r\n")).concat();
        write_file(
            &root,
            "profiles/Default/plugins.txt",
            format!("{HEADER}{active}").as_bytes(),
        );
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            format!("{HEADER}{order}").as_bytes(),
        );
        let (code, _, err) = nvmod(&["stage", "--instance", root.to_str().unwrap()]);
        assert_eq!(code, 0, "{err}");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn mods(&self, args: &[&str]) -> (i32, Value) {
        let root = self.root();
        let mut all = vec!["mods"];
        all.extend_from_slice(args);
        all.extend_from_slice(&["--json", "--instance", root.to_str().unwrap()]);
        let (code, out, err) = nvmod(&all);
        assert_eq!(code, 0, "{err}{out}");
        (code, serde_json::from_str(&out).unwrap())
    }

    fn file(&self, name: &str) -> Vec<u8> {
        fs::read(self.root().join("profiles/Default").join(name)).unwrap()
    }

    fn has_file(&self, name: &str) -> bool {
        self.root().join("profiles/Default").join(name).exists()
    }

    fn plugin_report(&self) -> String {
        let root = self.root();
        let (code, out, err) = nvmod(&[
            "plugins",
            "list",
            "--json",
            "--instance",
            root.to_str().unwrap(),
        ]);
        assert_eq!(code, 0, "{err}");
        out
    }

    fn rollback(&self) {
        let (code, out, err) = nvmod(&["rollback", "--instance", self.root().to_str().unwrap()]);
        assert_eq!(code, 0, "{err}{out}");
    }

    /// The Doctor's findings of the code `loadorder.missing-master`, as `subject: message`.
    fn missing_masters(&self) -> Vec<String> {
        let (_, out, err) = nvmod(&[
            "doctor",
            "--instance",
            self.root().to_str().unwrap(),
            "--json",
        ]);
        let v: Value = serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out} / {err}"));
        v["findings"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|f| f["code"] == "loadorder.missing-master")
            .map(|f| {
                format!(
                    "{}: {}",
                    f["subject"].as_str().unwrap(),
                    f["message"].as_str().unwrap()
                )
            })
            .collect()
    }
}

fn active(bytes: &[u8]) -> Vec<String> {
    String::from_utf8_lossy(bytes)
        .lines()
        .filter_map(|l| l.strip_prefix('*'))
        .map(str::to_owned)
        .collect()
}

#[test]
fn disabling_a_mod_that_ships_base_masters_takes_out_only_what_no_one_else_provides() {
    let s = Scratch::new();
    let (_, v) = s.mods(&["disable", "Ttw"]);
    // Anchorage.esm is also provided by the enabled Mod Twin, the four base masters by the base copy
    assert_eq!(
        v["plugins_deactivated"],
        serde_json::json!(["Fallout3.esm", "TaleOfTwoWastelands.esm", "YUPTTW.esp"])
    );
    assert_eq!(
        active(&s.file("plugins.txt")),
        [
            "FalloutNV.esm",
            "DeadMoney.esm",
            "HonestHearts.esm",
            "GunRunnersArsenal.esm",
            "Anchorage.esm",
            "Late.esp"
        ]
    );
    // the Load order keeps every plugin where it was
    assert_eq!(
        active(&s.file("loadorder.txt")).len(),
        0,
        "loadorder.txt has no star lines"
    );
    assert!(
        String::from_utf8(s.file("loadorder.txt"))
            .unwrap()
            .contains("YUPTTW.esp")
    );
}

#[test]
fn disable_then_enable_is_the_identity_on_the_profile_files_and_the_plugin_report() {
    let s = Scratch::new();
    let plugins = s.file("plugins.txt");
    let order = s.file("loadorder.txt");
    let modlist = s.file("modlist.txt");
    let report = s.plugin_report();
    s.mods(&["disable", "Ttw"]);
    assert_ne!(s.file("plugins.txt"), plugins);
    assert!(s.has_file("deactivated.txt"));
    assert_ne!(s.plugin_report(), report);
    let (_, v) = s.mods(&["enable", "Ttw"]);
    assert_eq!(
        v["plugins_reactivated"],
        serde_json::json!(["Fallout3.esm", "TaleOfTwoWastelands.esm", "YUPTTW.esp"])
    );
    assert_eq!(
        s.file("plugins.txt"),
        plugins,
        "plugins.txt is byte-identical"
    );
    assert_eq!(s.file("loadorder.txt"), order);
    assert_eq!(s.file("modlist.txt"), modlist);
    assert!(!s.has_file("deactivated.txt"), "nothing left to restore");
    assert_eq!(s.plugin_report(), report);
}

#[test]
fn a_mod_with_no_plugin_changes_nothing_but_its_state() {
    let s = Scratch::new();
    let before = snapshot(&s.root().join("profiles"));
    let report = s.plugin_report();
    let (_, v) = s.mods(&["disable", "Empty"]);
    assert!(v.get("plugins_deactivated").is_none());
    assert_eq!(s.plugin_report(), report);
    assert!(!s.has_file("deactivated.txt"));
    let (_, v) = s.mods(&["enable", "Empty"]);
    assert!(v.get("plugins_reactivated").is_none());
    assert_eq!(snapshot(&s.root().join("profiles")), before);
}

#[test]
fn two_mods_that_provide_the_same_plugin_keep_it_until_both_are_off() {
    let s = Scratch::new();
    let plugins = s.file("plugins.txt");
    // Twin is off, Ttw still provides Anchorage.esm
    let (_, v) = s.mods(&["disable", "Twin"]);
    assert!(v.get("plugins_deactivated").is_none());
    assert_eq!(s.file("plugins.txt"), plugins);
    // now Ttw goes too: Anchorage.esm leaves with the others
    let (_, v) = s.mods(&["disable", "Ttw"]);
    assert_eq!(
        v["plugins_deactivated"],
        serde_json::json!([
            "Anchorage.esm",
            "Fallout3.esm",
            "TaleOfTwoWastelands.esm",
            "YUPTTW.esp"
        ])
    );
    assert!(!active(&s.file("plugins.txt")).contains(&"Anchorage.esm".to_owned()));
    // Twin comes back first: it provides Anchorage.esm, which returns to its place; the rest waits for Ttw
    let (_, v) = s.mods(&["enable", "Twin"]);
    assert_eq!(
        v["plugins_reactivated"],
        serde_json::json!(["Anchorage.esm"])
    );
    let now = active(&s.file("plugins.txt"));
    assert!(now.contains(&"Anchorage.esm".to_owned()) && !now.contains(&"YUPTTW.esp".to_owned()));
    s.mods(&["enable", "Ttw"]);
    assert_eq!(s.file("plugins.txt"), plugins);
    assert!(!s.has_file("deactivated.txt"));
}

#[test]
fn a_rollback_undoes_a_disable_and_an_enable_including_what_is_to_be_put_back() {
    let s = Scratch::new();
    let plugins = s.file("plugins.txt");
    s.mods(&["disable", "Ttw"]);
    let disabled = s.file("plugins.txt");
    let notes = s.file("deactivated.txt");
    s.mods(&["enable", "Ttw"]);
    // undo the enable: back to the disabled state, with the notes, so an enable still restores everything
    s.rollback();
    assert_eq!(s.file("plugins.txt"), disabled);
    assert_eq!(s.file("deactivated.txt"), notes);
    // undo the disable: the original again, no notes
    s.rollback();
    assert_eq!(s.file("plugins.txt"), plugins);
    assert!(!s.has_file("deactivated.txt"));
    // and the whole cycle still works after the two rollbacks
    s.mods(&["disable", "Ttw"]);
    s.mods(&["enable", "Ttw"]);
    assert_eq!(s.file("plugins.txt"), plugins);
}

#[test]
fn a_dry_run_reports_both_directions_and_writes_nothing() {
    let s = Scratch::new();
    let before = snapshot(&s.root().join("profiles"));
    let (_, v) = s.mods(&["disable", "Ttw", "--dry-run"]);
    assert_eq!(v["plugins_deactivated"].as_array().unwrap().len(), 3);
    assert_eq!(snapshot(&s.root().join("profiles")), before);
    s.mods(&["disable", "Ttw"]);
    let mid = snapshot(&s.root().join("profiles"));
    let (_, v) = s.mods(&["enable", "Ttw", "--dry-run"]);
    assert_eq!(v["plugins_reactivated"].as_array().unwrap().len(), 3);
    assert_eq!(snapshot(&s.root().join("profiles")), mid);
}

#[test]
fn a_plugin_of_another_mod_stays_listed_and_the_doctor_names_its_missing_master() {
    let s = Scratch::new();
    assert!(s.missing_masters().is_empty(), "{:?}", s.missing_masters());
    s.mods(&["disable", "Ttw"]);
    assert!(active(&s.file("plugins.txt")).contains(&"Late.esp".to_owned()));
    let found = s.missing_masters();
    assert!(
        found.iter().any(|f| f.starts_with("Late.esp")
            && f.contains("Fallout3.esm")
            && f.contains("not active")),
        "{found:?}"
    );
    s.mods(&["enable", "Ttw"]);
    assert!(s.missing_masters().is_empty(), "{:?}", s.missing_masters());
}

#[test]
fn a_plugin_that_moved_meanwhile_returns_by_the_load_order() {
    let s = Scratch::new();
    s.mods(&["disable", "Ttw"]);
    // the user (or a sort) rewrote plugins.txt: the line each plugin sat below is gone
    let root = s.root();
    write_file(
        &root,
        "profiles/Default/plugins.txt",
        format!("{HEADER}*FalloutNV.esm\r\n*Late.esp\r\n").as_bytes(),
    );
    s.mods(&["enable", "Ttw"]);
    assert_eq!(
        active(&s.file("plugins.txt")),
        [
            "FalloutNV.esm",
            "Fallout3.esm",
            "TaleOfTwoWastelands.esm",
            "YUPTTW.esp",
            "Late.esp"
        ]
    );
}
