//! `nvmod overwrite list|create-mod|move|delete|sync`, run as a program against a scratch Instance made by
//! `nvmod init`. Plugins and files are synthetic; no game data is used.

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, snapshot, write_file};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

fn nvmod_env(args: &[&str], env: &[(&str, &str)]) -> (i32, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_nvmod"))
        .args(args)
        .envs(env.iter().copied())
        .output()
        .unwrap();
    (
        out.status.code().unwrap(),
        String::from_utf8(out.stdout).unwrap(),
        String::from_utf8(out.stderr).unwrap(),
    )
}

struct Scratch {
    _base: TempDir,
    inst: TempDir,
}

impl Scratch {
    /// Mods `Core` (Textures/Dirt.dds, Config/core.ini), `Extra` (Textures/Dirt.dds) and `Plain` (Meshes/m.nif),
    /// and an Overwrite holding a log, a plugin, two Dirt textures (one in another letter case), a config of Core
    /// and a file nobody provides, in nested folders; staged.
    fn new() -> Scratch {
        let base = TempDir::new("ow-base");
        BaseBuilder::steam().write(base.path());
        write_file(
            base.path(),
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        let inst = TempDir::new("ow-inst");
        let root = inst.path().join("fnv");
        let (code, _, err) = nvmod_env(
            &[
                "init",
                "--base",
                base.path().to_str().unwrap(),
                "--instance",
                root.to_str().unwrap(),
            ],
            &[],
        );
        assert_eq!(code, 0, "{err}");
        write_file(&root, "mods/Core/Textures/Dirt.dds", b"core dirt");
        write_file(&root, "mods/Core/Config/core.ini", b"core ini");
        write_file(&root, "mods/Extra/Textures/Dirt.dds", b"extra dirt");
        write_file(&root, "mods/Plain/Meshes/m.nif", b"nif");
        write_file(
            &root,
            "profiles/Default/modlist.txt",
            format!("{HEADER}+Extra\r\n+Core\r\n+Plain\r\n").as_bytes(),
        );
        write_file(&root, "profiles/Default/plugins.txt", b"FalloutNV.esm\r\n");
        write_file(
            &root,
            "profiles/Default/loadorder.txt",
            b"FalloutNV.esm\r\n",
        );
        write_file(&root, "overwrite/Logs/run/one.log", b"log one");
        write_file(&root, "overwrite/Logs/two.log", b"log two");
        write_file(&root, "overwrite/Tool.esp", &PluginBuilder::new().build());
        write_file(&root, "overwrite/textures/dirt.dds", b"new dirt");
        write_file(&root, "overwrite/Config/core.ini", b"new core ini");
        write_file(&root, "overwrite/Only/here.txt", b"nobody has it");
        let s = Scratch { _base: base, inst };
        let (code, _, err) = nvmod_env(&["stage", "--instance", root.to_str().unwrap()], &[]);
        assert_eq!(code, 0, "{err}");
        s
    }

    fn root(&self) -> PathBuf {
        self.inst.path().join("fnv")
    }

    fn run(&self, args: &[&str]) -> (i32, String, String) {
        let root = self.root();
        let mut all = vec!["overwrite"];
        all.extend_from_slice(args);
        all.extend_from_slice(&["--instance", root.to_str().unwrap()]);
        nvmod_env(&all, &[])
    }

    fn json(&self, args: &[&str]) -> Value {
        let mut all = args.to_vec();
        all.push("--json");
        let (code, out, err) = self.run(&all);
        assert_eq!(code, 0, "{args:?}: {err}");
        serde_json::from_str(&out).unwrap()
    }

    fn rollback(&self) {
        let (code, _, err) = nvmod_env(
            &["rollback", "--instance", self.root().to_str().unwrap()],
            &[],
        );
        assert_eq!(code, 0, "{err}");
    }

    fn file(&self, rel: &str) -> String {
        fs::read_to_string(self.root().join(rel)).unwrap()
    }

    fn tree(&self) -> BTreeMap<String, Vec<u8>> {
        snapshot(&self.root())
            .into_iter()
            // The manifest of a built tree holds the file ids and times of the files it linked: not byte-identical
            // after the tree is built again.
            .filter(|(k, _)| {
                let manifest = k.starts_with("staging/")
                    && Path::new(k)
                        .extension()
                        .is_some_and(|x| x.eq_ignore_ascii_case("json"));
                !(k.starts_with(".nvmod") || manifest)
            })
            .collect()
    }

    fn staged(&self, rel: &str) -> Option<Vec<u8>> {
        fs::read(self.root().join("staging/Default/data").join(rel)).ok()
    }
}

fn paths(v: &Value) -> Vec<String> {
    v["files"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["path"].as_str().unwrap().to_owned())
        .collect()
}

#[test]
fn list_shows_each_file_with_the_mods_that_provide_the_same_path() {
    let s = Scratch::new();
    let list = s.json(&["list"]);
    assert_eq!(
        paths(&list),
        [
            "Config/core.ini",
            "Logs/run/one.log",
            "Logs/two.log",
            "Only/here.txt",
            "Tool.esp",
            "textures/dirt.dds"
        ]
    );
    let by = |p: &str| -> Vec<String> {
        list["files"]
            .as_array()
            .unwrap()
            .iter()
            .find(|f| f["path"] == p)
            .unwrap()["providers"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap().to_owned())
            .collect()
    };
    assert_eq!(by("textures/dirt.dds"), ["Extra", "Core"]);
    assert_eq!(by("Config/core.ini"), ["Core"]);
    assert_eq!(by("Only/here.txt"), Vec::<String>::new());
    assert_eq!(list["files"][0]["size"], 12);
}

#[test]
fn create_mod_with_a_glob_moves_only_matches_and_keeps_the_folders() {
    let s = Scratch::new();
    let before = s.tree();
    let dry = s.json(&["create-mod", "Tool Output", "logs/**", "--dry-run"]);
    assert_eq!(dry["status"], "dry-run");
    assert_eq!(s.tree(), before, "a dry run wrote something");
    let r = s.json(&["create-mod", "Tool Output", "logs/**"]);
    assert_eq!(r["status"], "changed");
    assert_eq!(paths(&json_files(&r)), ["Logs/run/one.log", "Logs/two.log"]);
    assert_eq!(s.file("mods/Tool Output/Logs/run/one.log"), "log one");
    assert_eq!(s.file("mods/Tool Output/Logs/two.log"), "log two");
    assert!(!s.root().join("overwrite/Logs").exists());
    assert!(s.root().join("overwrite/Tool.esp").is_file());
    assert!(
        s.file("profiles/Default/modlist.txt")
            .contains("+Tool Output\r\n+Extra")
    );
    assert_eq!(s.staged("logs/two.log").unwrap(), b"log two");
    s.rollback();
    assert_eq!(s.tree(), before);
}

fn json_files(r: &Value) -> Value {
    serde_json::json!({ "files": r["files"].as_array().unwrap().iter().map(|p| serde_json::json!({"path": p})).collect::<Vec<_>>() })
}

#[test]
fn create_mod_of_everything_lists_its_plugin_as_inactive_and_refuses_a_clash() {
    let s = Scratch::new();
    let before = s.tree();
    let (code, _, err) = s.run(&["create-mod", "Core"]);
    assert_eq!((code, err.contains("already exists")), (2, true), "{err}");
    let (code, _, err) = s.run(&["create-mod", "Nothing", "nomatch/*"]);
    assert_eq!((code, err.contains("matches")), (2, true), "{err}");
    assert_eq!(s.tree(), before);
    let r = s.json(&["create-mod", "All"]);
    assert_eq!(r["files"].as_array().unwrap().len(), 6);
    assert!(
        fs::read_dir(s.root().join("overwrite"))
            .unwrap()
            .next()
            .is_none()
    );
    assert!(
        s.file("profiles/Default/loadorder.txt")
            .contains("Tool.esp")
    );
    assert!(!s.file("profiles/Default/plugins.txt").contains("Tool.esp"));
    s.rollback();
    assert_eq!(s.tree(), before);
}

#[test]
fn move_puts_a_folder_into_a_mod_and_refuses_a_name_the_mod_has() {
    let s = Scratch::new();
    let before = s.tree();
    let (code, _, err) = s.run(&["move", "Config/core.ini", "--to", "Core"]);
    assert_eq!((code, err.contains("already has")), (2, true), "{err}");
    let (code, _, err) = s.run(&["move", "Nope.txt", "--to", "Core"]);
    assert_eq!((code, err.contains("not in Overwrite")), (2, true), "{err}");
    let (code, _, _) = s.run(&["move", "../x", "--to", "Core"]);
    assert_eq!(code, 2);
    assert_eq!(s.tree(), before);
    // The folder is spelled as the Mod already has it.
    let r = s.json(&["move", "Logs", "--to", "Plain"]);
    assert_eq!(r["status"], "changed");
    assert_eq!(s.file("mods/Plain/Logs/run/one.log"), "log one");
    assert!(!s.root().join("overwrite/Logs").exists());
    s.rollback();
    assert_eq!(s.tree(), before);
    s.json(&["move", "textures/dirt.dds", "--to", "Plain"]);
    assert_eq!(s.file("mods/Plain/textures/dirt.dds"), "new dirt");
}

#[test]
fn delete_moves_to_the_trash_and_rollback_brings_it_back() {
    let s = Scratch::new();
    let before = s.tree();
    let r = s.json(&["delete", "Logs", "logs/two.log", "Only/here.txt"]);
    assert_eq!(r["status"], "changed");
    assert!(!s.root().join("overwrite/Logs").exists());
    assert!(!s.root().join("overwrite/Only").exists());
    let id = r["journal"].as_str().unwrap();
    assert_eq!(
        s.file(&format!(".nvmod/trash/{id}/overwrite/Logs/run/one.log")),
        "log one"
    );
    assert_eq!(s.staged("logs/two.log"), None);
    s.rollback();
    assert_eq!(s.tree(), before);
}

#[test]
fn sync_moves_what_has_one_provider_and_refuses_an_ambiguous_one_without_to() {
    let s = Scratch::new();
    let before = s.tree();
    let (code, _, err) = s.run(&["sync"]);
    assert_eq!(code, 2);
    assert!(
        err.contains("textures/dirt.dds") && err.contains("Extra, Core"),
        "{err}"
    );
    assert_eq!(s.tree(), before);
    // With --to, only that Mod's files move; the file nobody provides never does.
    let r = s.json(&["sync", "--to", "Core"]);
    assert_eq!(
        paths(&json_files(&r)),
        ["Config/core.ini", "textures/dirt.dds"]
    );
    assert_eq!(s.file("mods/Core/Config/core.ini"), "new core ini");
    assert_eq!(s.file("mods/Core/Textures/Dirt.dds"), "new dirt");
    assert_eq!(s.file("mods/Extra/Textures/Dirt.dds"), "extra dirt");
    assert!(s.root().join("overwrite/Only/here.txt").is_file());
    // The replaced copies are in the trash.
    let id = r["journal"].as_str().unwrap();
    assert_eq!(
        s.file(&format!(".nvmod/trash/{id}/mods/Core/Config/core.ini")),
        "core ini"
    );
    assert_eq!(s.staged("textures/dirt.dds").unwrap(), b"extra dirt");
    s.rollback();
    assert_eq!(s.tree(), before);
}

#[test]
fn sync_of_an_unambiguous_overwrite_moves_it_and_the_conflict_report_sees_the_result() {
    let s = Scratch::new();
    s.json(&["delete", "textures"]);
    let r = s.json(&["sync"]);
    assert_eq!(paths(&json_files(&r)), ["Config/core.ini"]);
    assert_eq!(s.file("mods/Core/Config/core.ini"), "new core ini");
    let (code, out, err) = nvmod_env(
        &[
            "conflicts",
            "--instance",
            s.root().to_str().unwrap(),
            "--json",
        ],
        &[],
    );
    assert_eq!(code, 0, "{err}");
    assert!(!out.contains("overwrite/Config"), "{out}");
    let (code, out, _) = s.run(&["sync"]);
    assert_eq!(code, 0);
    assert!(out.contains("nothing to change"), "{out}");
}

#[test]
fn a_failure_in_the_middle_puts_everything_back() {
    let s = Scratch::new();
    let before = s.tree();
    let root = s.root();
    let (code, _, err) = nvmod_env(
        &[
            "overwrite",
            "create-mod",
            "Broken",
            "--instance",
            root.to_str().unwrap(),
        ],
        &[("NVMOD_FAIL_AT", "lists")],
    );
    assert_eq!(code, 4, "{err}");
    assert_eq!(s.tree(), before);
}

#[test]
fn bad_command_lines_are_usage_errors() {
    let s = Scratch::new();
    for args in [
        vec!["move", "Tool.esp"],
        vec!["list", "x"],
        vec!["create-mod"],
        vec!["delete"],
        vec!["nope"],
    ] {
        let (code, _, _) = s.run(&args);
        assert_eq!(code, 5, "{args:?}");
    }
}
